#!/usr/bin/env python3
"""Independent NumPy 2.3.5 edge cases for 0.79 PCG64 rejection samplers."""
from pathlib import Path
import numpy as np,math
ROOT=Path(__file__).resolve().parents[1]
def lit(v):
 if isinstance(v,np.ndarray):return lit(v.tolist())
 if isinstance(v,(list,tuple)):return '{'+','.join(map(lit,v))+'}'
 if v is None:return 'nil'
 if isinstance(v,(int,np.integer)):return str(v)
 x=float(v)
 if math.isnan(x):return '(0/0)'
 if math.isinf(x):return '(1/0)' if x>0 else '(-1/0)'
 return repr(x)
rows=[]
for seed in (0,42,218,10101):
 for name,args,size in [
 ('gamma',[[0.0,1.0,0.5,2.0],0.0],None),
 ('gamma',[[0.0,1.0,0.5,2.0],[0.0,0.5,1,2]],None),
 ('gamma',[[0,1,2],1],(0,3)),
 ('gamma',[[0.1,50.0,1.0],.0001],(2,3)),
 ('beta',[[1e-104,1e-106],[1e-105,1e-106]],None),
 ('beta',[[1e-100,.00001,.9999],[1e-100,1.,10.]],None),
 ('beta',[[1,2],3],(0,2)),
 ('beta',[[.1,100,1.0], [.2,10,1]],(2,3)),
 ('chisquare',[[.0001,1,100]],None),
 ('chisquare',[[1,2,3]],(0,3)),
 ('f',[[1e-4,1,100],[1,2,3]],(2,3)),
 ('f',[[1,2,3],[1,2,3]],(0,3)),
 ]:
  r=np.random.default_rng(seed)
  v=getattr(r,name)(*args,size=size)
  h='%016x'%int(r.bit_generator.random_raw())
  rows.append((seed,name,args,size,v,h))
lines=['''-- Independently generated by tools/generate_random79_edge_oracle.py
local np=require('luaray_core')
local count=0
local function same(a,b)
 if type(a)~=type(b) then return false end
 if type(b)=='table' then
  if #a~=#b then return false end
  for i=1,#a do if not same(a[i],b[i]) then return false end end
  return true
 end
 if type(b)=='number' then
  if a~=a then return b~=b end
  if a==b then return true end
  return math.abs(a-b)<=1e-11*math.max(1,math.abs(b))
 end
 return a==b
end
''']
for i,(seed,name,args,size,v,h) in enumerate(rows):
 lines.append(f'do local r=np.random.default_rng({seed});local x=r:{name}('+','.join(lit(a) for a in args)+','+lit(list(size) if size is not None else None)+')\n')
 if isinstance(v,np.ndarray):lines.append(' assert(type(x)=="userdata" and same(x.shape,'+lit(v.shape)+') and same(x:tolist(),'+lit(v)+'),"edge values '+str(i)+'")\n')
 else:lines.append(' assert(same(x,'+lit(v)+'),"edge scalar '+str(i)+'")\n')
 lines.append(' assert(r:raw_hex()=="'+h+'","edge PCG64 '+str(i)+'")\nend\n')
lines.append('print("random79 edge differential passed: '+str(len(rows))+' cases")\n')
p=ROOT/'tests/random79_edge_generated.lua';p.write_text(''.join(lines));print('NumPy',np.__version__,len(rows),'edge cases')
