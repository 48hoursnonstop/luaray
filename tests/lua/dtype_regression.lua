local lr=require('luaray')
local checks=0
local function check(value)checks=checks+1;assert(value)end
local function reject(call)check(not pcall(call))end
local d=lr.dtype('float64')
check(d.name=='float64' and d.kind=='f' and d.char=='d' and d.num==12)
check(d.itemsize==8 and d.alignment==8 and d.isnative and not d.hasobject)
check(d.byteorder=='=' and #d.shape==0 and d.ndim==0 and rawequal(d.base,d))
check(d.fields==nil and d.names==nil and d.subdtype==nil and d.metadata==nil)
check(rawequal(lr.dtype(d),d) and lr.dtype()==d and lr.dtype(nil)==d)
check(lr.dtype('float')==d and lr.array({1},'float').itemsize==8)
check(lr.dtype('f')==lr.dtype('float32') and lr.dtype('int')==lr.dtype('int64'))
check(lr.dtype('longlong')==lr.dtype('int64') and lr.can_cast('longlong','int64','no'))
check(lr.dtype('longlong').num==9 and lr.dtype('longlong').char=='q')
check(lr.dtype('longdouble').name=='float128' and tostring(lr.dtype('longdouble'))=='float128')
local text=lr.dtype('U3');check(text.name=='str96' and text.flags==8 and text.itemsize==12)
check(lr.dtype('S3').name=='bytes24' and lr.dtype('S3').byteorder=='|')
check(text~=lr.dtype('U0') and text~=lr.dtype('>U3') and lr.dtype('>U3').isnative==false)
check(not lr.can_cast(lr.dtype('>U1'),lr.dtype('U0'),'no'))
check(lr.can_cast(lr.dtype('>U1'),lr.dtype('U0'),'equiv'))
local descr=d.descr;check(descr[1][1]=='' and descr[1][2]==d.str)
descr[1][2]='bad';check(d.descr[1][2]==d.str)
local a=lr.array({1,2,3},d);check(a.dtype=='float64')
check(lr.asarray(a,d)==a and lr.asanyarray(a,d)==a)
check(lr.zeros({2},d).dtype=='float64' and lr.ones({2},d)[1]==1)
check(lr.empty({0},d).shape[1]==0 and lr.full({2},3,d)[2]==3)
check(lr.zeros_like(a,d).dtype=='float64' and lr.ones_like(a,d)[1]==1)
check(lr.empty_like(a,d).shape[1]==3 and lr.full_like(a,7,d)[2]==7)
check(lr.ascontiguousarray(a,d)==a and lr.asfortranarray(a,d)==a)
check(lr.astype(a,lr.dtype('int32')).dtype=='int32')
check(a:view(lr.dtype('uint64')).dtype=='uint64')
check(lr.frombuffer(a,lr.dtype('uint8')).shape[1]==24)
check(lr.arange(3,d).dtype=='float64')
check(lr.promote_types(lr.dtype('int8'),d)=='float64' and lr.result_type(d,1)=='float64')
check(lr.issubdtype(d,'floating') and lr.issubdtype(d,lr.dtype('float64')))
check(lr.sum(a,{dtype=d})==6 and lr.cumsum(a,{dtype=d}).dtype=='float64')
check(lr.concatenate({a,a},{dtype=d}).dtype=='float64')
check(lr.linspace(0,1,3,{dtype=d}).dtype=='float64')
check(lr.logspace(0,1,3,{dtype=d}).dtype=='float64')
check(lr.geomspace(1,16,3,{dtype=d}).dtype=='float64')
check(lr.eye(2,{dtype=d}).dtype=='float64')
local unicode=lr.empty({4},text);check(unicode[1]=='' and unicode[4]=='')
check(lr.dtype(a.dtype)==d and type(a.dtype)=='string')
local joined=lr.concatenate({lr.array({1},'int32'),lr.array({2},'int32')},{dtype=lr.dtype('S0'),casting='unsafe'})
check(joined.itemsize==11 and joined[1]=='1' and joined[2]=='2')
local swapped=lr.array({'ab'},'>U3')
local one=lr.concatenate({swapped},{dtype=lr.dtype('U0'),casting='unsafe'})
check(one.dtype=='>U3' and one[1]=='ab')
check(lr.dtype('U0').itemsize==0 and lr.dtype('S0').itemsize==0)
local durations=lr.array({1,2,3},'timedelta64[D]')
check(lr.astype(lr.array(lr.sum(durations)),'int64'):tolist()==6)
check(lr.astype(lr.array(lr.mean(durations)),'int64'):tolist()==2)
check(lr.astype(lr.cumsum(durations),'int64')[3]==6)
local selected=lr.sum(durations,{where=lr.array({true,false,true})})
check(lr.astype(lr.array(selected),'int64'):tolist()==4)
local with_nat=lr.array({math.mininteger,1,2},'timedelta64[D]')
check(lr.array(lr.mean(with_nat)).dtype=='timedelta64[D]' and lr.array(lr.mean(with_nat)):item().isnat)
check(lr.mean(lr.array({},'timedelta64[D]')).isnat)
local output=lr.zeros({},'timedelta64[D]')
check(rawequal(lr.sum(durations,{out=output}),output) and lr.astype(output,'int64'):tolist()==6)
local overflow=lr.array({math.maxinteger,1},'timedelta64[D]')
reject(function()lr.sum(overflow)end)
reject(function()lr.cumsum(overflow)end)
reject(function()lr.sum(lr.array({},'int32'),{dtype=lr.dtype('U3')})end)
reject(function()lr.add_accumulate(lr.array({},'int32'),{dtype=lr.dtype('timedelta64[h]')})end)
check(lr.cumsum(lr.array({1,2},'int32'),{dtype=lr.dtype('timedelta64[h]')}).dtype=='int32')
check(lr.linspace(0,2,3,{dtype=lr.dtype('S0')})[1]=='0.0')
reject(function()d.itemsize=1 end)
reject(function()lr.dtype('float64\0bad')end)
reject(function()lr.dtype('>f8')end)
reject(function()lr.dtype('object')end)
reject(function()lr.dtype('int32',false)end)
reject(function()lr.dtype({})end)
reject(function()lr.dtype(1)end)
reject(function()lr.frombuffer('',lr.dtype('U0'),0)end)
reject(function()return d.type end)
reject(function()return d.isbuiltin end)
print('dtype regression: '..checks..' checks passed')
