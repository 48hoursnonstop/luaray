local np=require('luaray_core')
assert(np._version=='0.140.0-dev')
local function near(a,b,tol)
  tol=tol or 1e-10
  if a~=a and b~=b then return true end
  return math.abs(a-b) <= tol*math.max(1,math.abs(b))
end
local function reject(fn) assert(not pcall(fn),'expected error') end
local a=np.array({{1,2,3},{4,5,6}},np.float64)
assert(near(np.var(a),35/12))
assert(near(np.std(a),math.sqrt(35/12)))
local v=np.var(a,{axis=2,ddof=1})
assert(v.dtype=='float64')
assert(near(v:tolist()[1],1) and near(v:tolist()[2],1))
local vv=np.var(a,{axis=1,keepdims=true})
assert(vv.shape[1]==1 and vv.shape[2]==3)
local empty=np.array({},np.float64)
assert(np.var(empty)~=np.var(empty))
local f=np.array({1,2,3},np.float32)
assert(near(np.std(f),math.sqrt(2/3),2e-6))
local z=np.array({{1,2},{3,4}},np.int64)
local o=np.zeros({2},np.float64)
assert(np.var(z,{axis=2,out=o})==o)
assert(near(o:tolist()[1],0.25))
local mask=np.array({{true,false,true},{true,false,true}},np.bool)
assert(near(np.var(a,{where=mask}),3.25))
assert(near(np.std(a,{ddof=1}),math.sqrt(3.5)))
-- Strided negative views and transposes, including noncontiguous out.
local tr=np.transpose(a)
local trv=np.var(tr,{axis=1})
assert(trv.shape[1]==2)
assert(near(trv:tolist()[1],2/3) and near(trv:tolist()[2],2/3))
local rev=np.flip(a,2)
assert(near(np.var(rev),35/12))
local dest=np.flip(np.zeros({3},np.float64))
assert(np.var(a,{axis=1,out=dest})==dest)
for _,x in ipairs(dest:tolist()) do assert(near(x,2.25)) end
local alias=np.array({3,5,7},np.float64)
assert(np.var(alias,{axis={},out=alias})==alias)
for _,x in ipairs(alias:tolist()) do assert(x==0) end
-- Broadcasting a column mask across rows.
local m=np.array({true,false,true},np.bool)
local cols=np.var(a,{axis=2,where=m})
assert(near(cols:tolist()[1],1) and near(cols:tolist()[2],1))
local c=np.array({np.complex(1,2),np.complex(3,4)},np.complex128)
assert(near(np.var(c),2))
assert(near(np.std(c),math.sqrt(2)))
assert(near(np.var(c,{dtype='float64'}),11))
assert(near(np.std(c,{dtype='float64'}),math.sqrt(11)))
assert(near(np.std(a,{correction=1}),math.sqrt(3.5)))
reject(function()np.var(a,{ddof=0,correction=1})end)
reject(function()np.std(a,{where=np.array({true},np.int32)})end)
reject(function()np.var(a,{out=np.zeros({3})})end)
reject(function()np.mean(a,{ddof=1})end)
reject(function()np.sum(a,{correction=1})end)
reject(function()np.var(a,{ddof=0/0})end)
reject(function()np.var(a,{dtype='int64'})end)
reject(function()np.var(a,{mean=np.zeros({1,3})})end)
reject(function()np.var(np.array({'a','b'},'U1'))end)
print('stats regression: ok')
