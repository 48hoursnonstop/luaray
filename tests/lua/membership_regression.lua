local lr=require('luaray')
local function bits(a,expected)
  local values=a:ravel():tolist()
  assert(#values==#expected)
  for i=1,#values do assert(values[i]==expected[i]) end
end
local a=lr.array({{0,2,3},{1,5,2}},'uint8')
bits(lr.isin(a,{2,5}),{false,true,false,false,true,true})
bits(lr.isin(a,{2,5},{kind='table',invert=true}),{true,false,true,true,false,false})
local sparse=lr.isin(lr.array({-128,-1,0,127},'int8'),lr.array({-128,127},'int8'))
bits(sparse,{true,false,false,true})
assert(not pcall(lr.isin,a,lr.array({-128,127},'int8'),{kind='table'}))

local wide=lr.ndarray({3},{dtype='uint64',buffer=string.pack('<I8I8I8',0,math.mininteger,-1)})
local keys=lr.ndarray({2},{dtype='uint64',buffer=string.pack('<I8I8',-2,-1)})
bits(lr.isin(wide,keys,{kind='table'}),{false,false,true})
bits(lr.isin(wide,lr.array({-1,0},'int64'),{kind='table'}),{true,false,false})

local series=lr.arange(1,40,1)
local handles=lr.arange(20,60,1)
local sorted=lr.isin(series,handles,{kind='sort',assume_unique=true})
assert(not sorted[19] and sorted[20] and sorted[39])
bits(lr.isin({0/0,3},{0/0,3}),{false,true})
bits(lr.isin(lr.array({'7'},'S2'),lr.array({7},'int64')),{false})
local empty=lr.isin(lr.empty({2,0}),{})
assert(empty.shape[1]==2 and empty.shape[2]==0 and empty.strides[1]==1)
assert(not pcall(lr.isin,a,{0.5},{kind='table'}))
assert(not pcall(lr.isin,a,{1},{kind='invalid'}))
print('Membership regression passed')
