local np=require('luaray_core')
assert(np._version=='0.157.0-dev')
local function eq(a,b) assert(a==b,tostring(a)..' != '..tostring(b)) end
local function arr(a, b)
  local aa=a:tolist()
  for i,v in ipairs(b) do eq(aa[i],v) end
end
local a=np.arange(8,'int32')
local rev=np.flip(a)
eq(np.may_share_memory(a,rev),true)
eq(np.shares_memory(a,rev),true)
local copy=np.astype(a,'int32')
eq(np.shares_memory(a,copy),false)
-- Actual slice syntax may vary, use tests below independent of the helper.
np.copyto(a,rev)
arr(a,{7,6,5,4,3,2,1,0})
local dst=np.zeros({2,3},'int32')
np.copyto(dst,np.array({1,2,3},'int32'))
assert(dst:get(2,3)==3)
local m=np.array({{true,false,true},{false,true,false}},'bool')
np.copyto(dst,9,'unsafe',m)
eq(dst:get(1,1),9);eq(dst:get(1,2),2);eq(dst:get(2,2),9)
local err=pcall(function()np.copyto(dst,np.array({1.5,2.5,3.5},'float64'))end)
assert(not err)
np.putmask(dst,m,np.array({10,20},'int32'))
eq(dst:get(1,1),10);eq(dst:get(1,3),10);eq(dst:get(2,2),10)
print('memory97 regression: ok')
local u=np.zeros({4},'uint8')
np.copyto(u, 5)
arr(u, {5,5,5,5})
assert(not pcall(function() np.copyto(u,300) end))
assert(not pcall(function() np.copyto(u,-1) end))
assert(not pcall(function() np.copyto(np.zeros({3},'bool'),5) end))
np.putmask(u,{true,false,true,false},1)
arr(u,{1,5,1,5})
np.putmask(u,{true,false,true,false},1.5)
arr(u,{1,5,1,5})
assert(not pcall(function()np.putmask(u,{true,false,true,false},300)end))
local untouched=np.arange(4,'int32')
assert(not pcall(function() np.copyto(untouched,np.array({1,2,3,4},'float64')) end))
arr(untouched,{0,1,2,3})
local mw=np.array({true,true,false,true},'bool')
np.copyto(mw,false,'unsafe',mw)
arr(mw,{false,false,false,false})
print('memory97 edge regressions: ok')
