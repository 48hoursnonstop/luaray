local function eq(a,b)checks=checks+1;assert(a==b,tostring(a)..' ~= '..tostring(b))end
local function fails(fn)checks=checks+1;assert(not pcall(fn))end
local f=lr.dtype('float32')
eq(lr.isdtype(f,'real floating'),true);eq(lr.isdtype(f,'integral'),false)
eq(lr.isdtype(f,{'integral','real floating'}),true);eq(lr.isdtype(f,{}),false)
