eq(lr.isdtype(lr.dtype('bool'),'numeric'),false)
eq(lr.isdtype(lr.dtype('int64'),lr.dtype('longlong')),false)
eq(lr.isdtype(lr.dtype('S3'),lr.dtype('S8')),true)
eq(lr.isdtype(lr.dtype('datetime64[D]'),lr.dtype('datetime64[ns]')),true)
eq(lr.isdtype(lr.dtype('timedelta64[h]'),'integral'),false)
fails(function()lr.isdtype(f,{'real floating','invalid'})end)
fails(function()lr.isdtype(f,{'real floating',false})end)
fails(function()lr.isdtype(f,{{'numeric'}})end)
fails(function()lr.isdtype(f,{[1]='numeric',[3]='integral'})end)
fails(function()lr.isdtype(f,{extra='numeric'})end)
fails(function()lr.isdtype('float32','numeric')end)
fails(function()lr.isdtype(f,'float32')end)
fails(function()lr.isdtype(lr.array(1.0),'numeric')end)
fails(function()lr.isdtype(f,'numeric\0ignored')end)
fails(function()lr.isdtype(f)end)
eq(lr.common_type(),lr.dtype('float16'))
