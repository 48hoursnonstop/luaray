local np=require('luaray_core')
assert(np._version=='0.118.0-dev')
local checks=0
local function rejected_without_draw(fn)
 local r=np.random.default_rng(820082)
 local ref=np.random.default_rng(820082)
 local ok=pcall(function() fn(r) end)
 assert(not ok,'expected parameter rejection '..(checks+1))
 assert(r:raw_hex()==ref:raw_hex(),'invalid argument consumed PCG64')
 checks=checks+1
end
rejected_without_draw(function(r) r:wald({1,-1},{1,2}) end)
rejected_without_draw(function(r) r:wald({1,0},{1,2},{0,2}) end)
rejected_without_draw(function(r) r:wald({1,2},{1,-2},{0,2}) end)
rejected_without_draw(function(r) r:wald({1,0/0},{1,2}) end)
rejected_without_draw(function(r) r:wald({1,2},{1,0/0}) end)
rejected_without_draw(function(r) r:wald({1,2},{1,2,3}) end)
rejected_without_draw(function(r) r:wald({1,2},{1,2},{2,3}) end)
rejected_without_draw(function(r) r:wald({1,2},nil) end)
rejected_without_draw(function(r) r:wald(nil,{1,2}) end)
rejected_without_draw(function(r) r:wald(np.array({{1,2},{3,4}}),np.array({1,2,3})) end)
rejected_without_draw(function(r) r:logseries({0.4,1}) end)
rejected_without_draw(function(r) r:logseries({0.1,-0.1},{0,2}) end)
rejected_without_draw(function(r) r:logseries({0.1,0/0}) end)
rejected_without_draw(function(r) r:logseries(np.array({1/0})) end)
rejected_without_draw(function(r) r:logseries({.1,.2},{2,3}) end)
rejected_without_draw(function(r) r:logseries(np.array({{.1,.2},{.3,.4}}),{4}) end)
local r=np.random.default_rng(82)
local a=r:wald({{1},{2}},{{.5,3,9}})
assert(a.dtype=='float64' and a.shape[1]==2 and a.shape[2]==3)
local b=r:logseries(np.flip(np.array({.1,.3,.8}),1))
assert(b.dtype=='int64' and b.shape[1]==3)
local c=r:logseries({0,.5,.9},{0,3})
assert(c.dtype=='int64' and c.shape[1]==0 and c.shape[2]==3)
local d=r:wald(np.array({1.}),np.array({1.}))
assert(type(d)=='userdata' and d.dtype=='float64')
local scalar=r:logseries(np.array(.3))
assert(type(scalar)=='number')
-- Smoke and distributional checks, not substitutions for differential testing.
local w=np.random.default_rng(826):wald(2.,3.,{20000}):tolist()
local sum=0
for i=1,#w do assert(w[i]>=0);sum=sum+w[i] end
assert(math.abs(sum/#w-2)<0.10,'Wald mean outside wide statistical threshold')
local l=np.random.default_rng(826):logseries(.5,{20000}):tolist()
local total=0
for i=1,#l do assert(l[i]>=1 and math.floor(l[i])==l[i]);total=total+l[i] end
local expected=-.5/((1-.5)*math.log(1-.5))
assert(math.abs(total/#l-expected)<.09,'Logseries mean outside wide statistical threshold')
print('random82 regressions: '..checks..' invalid-input checks, 40000 samples, shapes/views passed')
