local lr = require("luaray")
local a = lr.array({{1, 2}, {3, 4}}, "int16")
local b = lr.array({{8}, {9}}, "int16")
local joined = lr.block({{a, b}, {lr.array({10, 11, 12})}})
assert(lr.array_equal(joined, {{1, 2, 8}, {3, 4, 9}, {10, 11, 12}}))
assert(not lr.shares_memory(joined, a) and not lr.shares_memory(joined, b))
assert(lr.array_equal(lr.block({lr.array({1, 2}), 3}), {1, 2, 3}))
local copied = lr.block(a)
assert(lr.array_equal(copied, a) and not lr.shares_memory(copied, a))

local input = lr.array({{0, 0, 0}, {0, 5, 0}, {0, 6, 0}, {0, 0, 0}})
local crop = lr.trim_zeros(input)
assert(lr.array_equal(crop, {{5}, {6}}))
assert(lr.shares_memory(crop, input))
crop:set(9, 1, 1)
assert(input:get(2, 2) == 9)
assert(lr.array_equal(lr.trim_zeros(input, "b", 2), {{0, 0}, {0, 9}, {0, 6}, {0, 0}}))
assert(lr.trim_zeros(lr.zeros({2, 3}), "f", 1).shape[1] == 0)
assert(rawequal(lr.trim_zeros(input, "fb", {}), input))
local list = lr.trim_zeros({0, 3, 0, 7, 0})
assert(#list == 3 and list[1] == 3 and list[2] == 0 and list[3] == 7)
assert(not pcall(lr.trim_zeros, input, "unknown"))
assert(not pcall(lr.trim_zeros, input, "fb", {1, -2}))
assert(not pcall(lr.block, {a, {b}}))
assert(not pcall(lr.block, {}))
local cyclic = {}
cyclic[1] = cyclic
assert(not pcall(lr.block, cyclic))

local f = lr.zeros({257, 257}, {dtype="int16", order="F"})
local g = lr.ones({257, 257}, {dtype="int16", order="F"})
local large = lr.block({{f, g}, {g, f}})
assert(large.shape[1] == 514 and large.shape[2] == 514 and large.flags.f_contiguous)
assert(large:get(257,257) == 0 and large:get(258,257) == 1)
assert(large:get(257,258) == 1 and large:get(258,258) == 0)
print("Block assembly and zero trimming regression passed")
