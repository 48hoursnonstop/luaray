local lr = require("luaray")

assert(lr.array_equal(lr.bartlett(5), {0, 0.5, 1, 0.5, 0}))
assert(lr.allclose(lr.blackman(5), {0, 0.34, 1, 0.34, 0}))
assert(lr.allclose(lr.hamming(5), {0.08, 0.54, 1, 0.54, 0.08}))
assert(lr.allclose(lr.hanning(5), {0, 0.5, 1, 0.5, 0}))
assert(lr.array_equal(lr.kaiser(5, 0), {1, 1, 1, 1, 1}))
assert(lr.allclose(lr.kaiser(5, 3), {0.20488475640125, 0.72692553028764, 1, 0.72692553028764, 0.20488475640125}))
assert(lr.hanning(0).size == 0 and lr.hamming(-1).size == 0)
assert(lr.kaiser(1, 0/0)[1] == 1)
assert(lr.blackman(lr.array(3, "longdouble")).dtype == "longdouble")

local x = lr.array({{0, 1}, {8, -8}}, "float32", {order="F"})
local snapshot = x:tobytes()
local bessel = lr.i0(x)
assert(bessel.dtype == "float32" and bessel.flags.f_contiguous)
assert(lr.allclose(bessel, {{1, 1.26606587775}, {427.5641157, 427.5641157}}))
assert(x:tobytes() == snapshot)
assert(lr.i0(lr.array(0)).ndim == 0)
assert(not pcall(lr.i0, lr.complex(0, 1)))
assert(not pcall(lr.hanning, math.huge))

assert(lr.sinc(0) == 1)
assert(lr.allclose(lr.sinc({-1, -0.5, 0, 0.5, 1}), {0, 2/math.pi, 1, 2/math.pi, 0}))
assert(lr.sinc(lr.complex(0, 0)).real == 1)
print("Windows and special functions regression passed")
