local lr = require("luaray")
local a = lr.array({0,2},"datetime64[D]")
local b = lr.array({{5},{7}},"datetime64[D]")
assert(lr.array_equal(lr.busday_count(a,b),{{3,1},{5,3}}))
assert(lr.busday_count("1970-01-01","1970-01-08")==5)
assert(lr.busday_count("1970-01-04","1970-01-01")==-1)
assert(lr.busday_count("1970-01-01","1970-01-04")==2)
local calendar=lr.busdaycalendar{holidays={1,4}}
assert(lr.busday_count("1970-01-01","1970-01-08",{calendar=calendar})==3)
local out=lr.zeros({2,2},"int64")
assert(rawequal(lr.busday_count(a,b,{out=out}),out))
assert(lr.array_equal(out,{{3,1},{5,3}}))
assert(not pcall(lr.busday_count,"NaT","1970-01-03"))
assert(not pcall(lr.busday_count,0,7))
local minimum=lr.array(math.mininteger+1,"datetime64[D]")
local maximum=lr.array(math.maxinteger,"datetime64[D]")
assert(not pcall(lr.busday_count,minimum,maximum,{weekmask="1111111"}))
local wide=lr.busday_count(minimum,maximum,{weekmask="0000001"})
assert(math.type(wide)=="integer" and wide>1000000000000000000)
print("Business day interval regression passed")
