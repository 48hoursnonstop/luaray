local np=require('luaray_core')
local rng=np.random.default_rng(42)
local out=np.zeros({2,3},'float32')
local returned=rng:standard_gamma({{0.5},{2.0}},nil,'float32',out)
assert(rawequal(returned,out))
print('standard_gamma float32 out:',out.dtype,out.shape[1],out.shape[2])
local special=rng:standard_gamma({0/0,1/0,1,2})
print('special values:',special:tolist()[1],special:tolist()[2])
print('next PCG64:',rng:raw_hex())
