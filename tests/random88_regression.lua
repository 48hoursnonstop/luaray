local np=require('luaray_core')
assert(np._version=='0.102.0-dev')
local rejected=0
local function must_reject(fn)
    local r=np.random.default_rng(880088)
    local ref=np.random.default_rng(880088)
    assert(not pcall(function()fn(r)end),'invalid argument accepted #'..(rejected+1))
    assert(r:raw_hex()==ref:raw_hex(),'invalid argument consumed RNG #'..(rejected+1))
    rejected=rejected+1
end
must_reject(function(r)r:standard_normal(nil,'int64')end)
must_reject(function(r)r:standard_normal(nil,'float64',{})end)
must_reject(function(r)r:standard_normal(nil,'float32',np.zeros({3},'float64'))end)
must_reject(function(r)r:standard_normal({1,3},'float32',np.zeros({3},'float32'))end)
must_reject(function(r)r:standard_normal(nil,'float64',np.flip(np.zeros({2,3}),2))end)
must_reject(function(r)r:standard_normal(nil,'float64',np.transpose(np.zeros({2,3},'float64')),1)end)
must_reject(function(r)r:standard_normal({-1},'float64')end)
must_reject(function(r)r:standard_exponential(nil,'int64')end)
must_reject(function(r)r:standard_exponential(nil,'float32','wrong')end)
must_reject(function(r)r:standard_exponential(nil,'float32','zig',{})end)
must_reject(function(r)r:standard_exponential(nil,'float64','inv',np.zeros({2},'float32'))end)
must_reject(function(r)r:standard_exponential({2,3},'float32','zig',np.zeros({6},'float32'))end)
must_reject(function(r)r:standard_exponential(nil,'float64','zig',np.flip(np.zeros({2,3}),2))end)
must_reject(function(r)r:standard_exponential(nil,'float64','zig',np.zeros({2},'float64'),1)end)
local rng=np.random.default_rng(1234)
local c=np.zeros({3,2},'float32')
assert(rawequal(rng:standard_normal(nil,'float32',c),c))
local f=np.transpose(np.zeros({3,2},'float64'))
assert(rawequal(rng:standard_exponential(nil,'float64','inv',f),f))
assert(f.shape[1]==2 and f.shape[2]==3)
local s=np.zeros({},'float64')
assert(rawequal(rng:standard_normal(nil,'float64',s),s))
local empty=np.zeros({0,4},'float32')
assert(rawequal(rng:standard_exponential(nil,'float32','zig',empty),empty))
print('random88 regression PASS: '..rejected..' invalid/no-draw tests, C/F/scalar/empty output')
