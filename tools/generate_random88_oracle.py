def lua(v):
 if v is None:return 'nil'
 if isinstance(v, str):return '"'+v+'"'
 if isinstance(v,(int,float,np.number)):
  f=float(v)
  if np.isnan(f):return '(0/0)'
  if np.isposinf(f):return 'math.huge'
  if np.isneginf(f):return '-math.huge'
  return repr(v.item() if isinstance(v,np.generic) else v)
 if isinstance(v,(list,tuple,np.ndarray)):
  return '{'+','.join(lua(x) for x in v)+'}'
 raise ValueError(repr(v))

methods=[('standard_normal',None),('standard_exponential','zig'),('standard_exponential','inv')]
shapes=[(),(1,),(3,),(2,3),(3,2),(1,2,3),(0,3),(2,0,3)]
seeds=[0,1,7,42,1234,2**32-1,2026088]
