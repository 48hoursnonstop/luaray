#!/usr/bin/env python3
"""Generate exact comparisons to numpy Generator.integers; Python only needed to regenerate fixtures."""
from pathlib import Path
import numpy as np
seedset=[0,1,42,12345,2**40+3]
bounds=[(0,2),(0,10),(-9,11),(100,101),(0,2**32),(0,2**32+17),(-(2**55),2**55),(0,2**62)]
dtypes=['int64','uint64','int32','uint32','int16','uint16','int8','uint8','bool']
L=[f'-- generated by NumPy {np.__version__}, independent oracle', "local np=require('luaray_core')", "local cases=0", "local function eq(x,y) assert(x==y,tostring(x)..' ~= '..tostring(y));cases=cases+1 end"]
for seed in seedset:
 for dt in dtypes:
  for lo,hi in ([(0,1),(0,2),(1,2)] if dt=='bool' else bounds):
   for endpoint in [False,True]:
    for shape in [None,3, (2,4)]:
     dtype=np.dtype(dt)
     try:
      r=np.random.default_rng(seed).integers(lo,hi,size=shape,dtype=dtype,endpoint=endpoint)
     except (ValueError,OverflowError,TypeError): continue
     if np.any(np.asarray(r)>2**63-1): continue
     shape_lit='nil' if shape is None else (str(shape) if isinstance(shape,int) else '{2,4}')
     bound_lit=f'{lo},{hi}'
     # skip too large lua literal due to signed integral conversion issue? all within 2**63
     L.append(f'do local r=np.random.default_rng({seed});local v=r:integers({bound_lit},{shape_lit},"{dt}",{str(endpoint).lower()})')
     if shape is None:
      L.append(f'eq(v,{str(bool(r)).lower() if dt=="bool" else int(r)})')
     else:
      L.append(f'eq(v.dtype,"{dt}")')
      for ix in np.ndindex(r.shape):
       idx=','.join(str(i+1) for i in ix)
       L.append(f'eq(v:get({idx}),{str(bool(r[ix])).lower() if dt=="bool" else int(r[ix])})')
     L.append('end')
L.append("print('integers differential passed: '..cases..' exact comparisons')")
path=Path(__file__).resolve().parents[1]/'tests/integers_differential_generated.lua'
path.write_text('\n'.join(L)+'\n'); print('generated',path, 'lines',len(L))
