-- Executable example verified against LuaRay 0.57.0-dev.
local np = require('luaray_core')
local rng = np.random.default_rng(42)
local incomes = rng:lognormal(0, 1, {2, 3})
local noise = rng:standard_cauchy(5)
local errors = rng:laplace(0, 2.5, {2, 2})
assert(incomes.dtype == 'float64' and incomes.shape[1] == 2 and incomes.shape[2] == 3)
assert(noise.shape[1] == 5)
assert(errors.dtype == 'float64' and errors.shape[1] == 2 and errors.shape[2] == 2)
print('example 0.55 executed: lognormal, standard_cauchy, laplace')
