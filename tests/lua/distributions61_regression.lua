local np=require("luaray_core")
assert(np._version=="0.122.0-dev")
local rng=np.random.default_rng(42)
local a=rng:poisson(4,{2,3})
assert(a.dtype=="int64" and a.shape[1]==2 and a.shape[2]==3)
assert(math.type(a:get(1,1))=="integer")
assert(type(rng:poisson(10))=="number")
local zero=np.random.default_rng(42)
local before=np.random.default_rng(42)
local z=zero:poisson(0,{100})
for i=1,100 do assert(z:get(i)==0) end
assert(zero:raw_hex()==before:raw_hex())
local empty=np.random.default_rng(42)
local original=np.random.default_rng(42)
local e=empty:poisson(2,{0,3})
assert(e.shape[1]==0 and e.shape[2]==3)
assert(empty:raw_hex()==original:raw_hex())
for _,lambda in ipairs({-1,math.huge,1e13}) do
    local r=np.random.default_rng(42)
    local ref=np.random.default_rng(42)
    assert(not pcall(function() return r:poisson(lambda) end))
    assert(r:raw_hex()==ref:raw_hex())
end
print("distributions61 Lua regression passed")
