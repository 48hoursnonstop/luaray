local np=require('luaray_core')
local function near(x,y)
 if type(x)=='number' then assert(math.abs(x-y)<1e-6,tostring(x)..' ~= '..tostring(y))
 else assert(x==y,tostring(x)..' ~= '..tostring(y)) end
end
local a=np.array({{1,2,3},{4,5,6}},'float64')
local w=np.array({1,2,3},'float64')
local r=np.average(a,{axis=2,weights=w});assert(r.dtype=='float64')
near(r:get(1),14/6);near(r:get(2),32/6)
local avg,sw=np.average(a,{axis=2,weights=w,returned=true})
near(avg:get(1),14/6);near(sw:get(1),6);near(sw:get(2),6)
local b=np.average(a,{axis=1,weights=np.array({1,2},'float64')})
near(b:get(1),3);near(b:get(3),5)
local t=np.transpose(a)
local s=np.average(t,{axis=1,weights=w});near(s:get(1),14/6)
local scalar=np.average(np.array({1,2,3},'int32'));near(scalar,2)
local unweighted,units=np.average(np.array({1,2,3},'int32'),{returned=true});near(unweighted,2);near(units,3)
assert(not pcall(function()np.average(a,{weights=np.array({1,2,3},'float64')})end))
assert(not pcall(function()np.average(a,{axis=2,weights=np.array({0,0,0},'float64')})end))
assert(not pcall(function()np.average(a,{axis=2,weights=np.array({1,2},'float64')})end))
print('average regression passed')
