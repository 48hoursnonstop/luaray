local np=require('luaray_core')
assert(np._version=='0.116.0-dev')
local function eq(a,b)
 if type(b)=='table' then assert(type(a)=='table' and #a==#b,'table length') for i=1,#b do eq(a[i],b[i]) end
 else assert(a==b,tostring(a)..' ~= '..tostring(b)) end
end
local a=np.array({1,2,3},'int32')
eq(np.insert(a,2,9):tolist(),{1,9,2,3})
eq(np.insert(a,4,{7,8}):tolist(),{1,2,3,7,8})
eq(np.insert(a,{2,2},{7,8}):tolist(),{1,7,8,2,3})
eq(np.insert(a,{3,1},{8,7}):tolist(),{7,1,2,8,3})
eq(np.insert(a,{2},{7,8}):tolist(),{1,7,8,2,3})
local m=np.reshape(np.array({1,2,3,4,5,6},'int32'),{3,2})
eq(np.insert(m,2,9,2):tolist(),{{1,9,2},{3,9,4},{5,9,6}})
eq(np.insert(m,{2},np.array({{7},{8},{9}}),2):tolist(),{{1,7,2},{3,8,4},{5,9,6}})
local r=np.insert(m,2,{50,60})
eq(r:tolist(),{1,50,60,2,3,4,5,6})
m[1][1]=90;assert(r[1]==1)
eq(np.insert(np.flip(a),2,-9):tolist(),{3,-9,2,1})
eq(np.insert(np.array({'東','界'},'U2'),2,'ö'):tolist(),{'東','ö','界'})
eq(np.insert(np.array({1,2,3},'int32'),np.array({false,true,false},'bool'),9):tolist(),{1,9,2,3})
eq(np.insert(np.array({1,2,3},'int32'),np.slice(2,4),9):tolist(),{1,9,2,9,3})
assert(not pcall(function()np.insert(a,0,5)end))
assert(not pcall(function()np.insert(a,6,5)end))
assert(not pcall(function()np.insert(a,{1,2},np.array({1,2,3}))end))
print('insert regression: ok')
