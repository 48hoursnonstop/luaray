local np = require('luaray_core')
local a = np.arange(12, 'int32'):reshape({3,4})
local same = a:astype('int32', {copy=false})
assert(same == a)
local f = a:astype('float64', {order='F'})
assert(f.dtype == 'float64')
assert(f:get(3,4) == 11)
local view = np.transpose(a)
local copied = view:astype('float32', {order='K',copy=false})
assert(copied.dtype == 'float32' and copied:get(4,3) == 11)
print('LuaRay 0.92 astype example: ok')
