local np=require('luaray_core')
assert(np._version=='0.99.0-dev')
-- NumPy resolves multi-operand promotion by kind, not left-to-right.
assert(np.result_type('int8','uint16','float16')=='float32')
assert(np.promote_types('int32','uint64')=='float64')
assert(np.result_type('float16',np.complex(1,1))=='complex64')
assert(np.result_type(np.array({7},'uint8'),5)=='uint8')
assert(np.result_type(np.array({7},'uint8'),5.5)=='float64')
assert(np.result_type(np.array({1,2},'bool'),7)=='int64')
assert(np.result_type('datetime64[D]','timedelta64[h]')=='datetime64[h]')
assert(np.result_type('U2','S3')=='<U3')
assert(np.result_type(true,9,2.5)=='float64')
assert(np.result_type(true,9, np.complex(1,2))=='complex128')
assert(not pcall(np.result_type))
assert(not pcall(np.promote_types,'unknown','int8'))
print('dtype91 regression: ok')
