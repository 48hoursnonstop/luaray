local np = require('luaray_core')
assert(np._version == '0.125.0-dev')
local function same(a,b)
  if type(a)=='table' then
    assert(type(b)=='table' and #a==#b)
    for i=1,#a do same(a[i],b[i]) end
  else
    assert(a==b or (a~=a and b~=b),tostring(a)..' ~= '..tostring(b))
  end
end
local a=np.array({{3,1,9},{-2,5,4}},np.int64)
assert(np.min(a)==-2 and np.max(a)==9)
same(np.amin(a,{axis=1}):tolist(),{-2,1,4})
same(np.amax(a,{axis=2,keepdims=true}):tolist(),{{9},{5}})
local b=np.flip(a,2)
same(np.min(b,{axis=1}):tolist(),{4,1,-2})
local tr=np.transpose(a)
same(np.max(tr,{axis=1}):tolist(),{9,5})
local out=np.flip(np.zeros({3},np.int64))
assert(np.amax(a,{axis=1,out=out})==out)
same(out:tolist(),{3,5,9})
local mask=np.array({{false,true,true},{true,false,true}},np.bool)
same(np.min(a,{axis=2,where=mask,initial=7}):tolist(),{1,-2})
assert(np.max(a,{where=false,initial=-10})==-10)
assert(np.min(a,{axis={},where=true}):tolist()[1][1]==3)
local x=np.array({true,false,true},np.bool)
assert(np.min(x)==false and np.max(x)==true)
local f=np.array({1.0,0/0,5.0},np.float64)
assert(np.max(f)~=np.max(f) and np.min(f)~=np.min(f))
local sign_zero=np.array({0.0,-0.0},np.float64)
assert(1/np.min(sign_zero)==-math.huge)
assert(1/np.max(sign_zero)==-math.huge)
local sign_reverse=np.array({-0.0,0.0},np.float64)
assert(1/np.min(sign_reverse)==math.huge)
local z=np.array({np.complex(2,1),np.complex(2,9),np.complex(3,-1)},np.complex128)
assert(np.max(z).real==3 and np.min(z).imag==1)
local empty=np.array({},np.int32)
local function reject(fn)assert(not pcall(fn))end
reject(function() np.min(empty) end)
assert(np.min(empty,{initial=5})==5)
reject(function() np.min(a,{where=false}) end)
reject(function() np.min(a,{dtype='float64'}) end)
reject(function() np.max(a,{out=np.zeros({2})}) end)
print('extrema regression: ok')
