local np=require('luaray_core')
assert(np._version=='0.125.0-dev')
local g=np.random.default_rng(42)
local a=g:noncentral_chisquare(.5,20,{2,3})
local b=g:noncentral_f(2,4,5,{2,3})
assert(a.dtype=='float64' and b.dtype=='float64')
assert(a.shape[1]==2 and a.shape[2]==3 and b.shape[1]==2)
assert(type(g:noncentral_chisquare(2,0))=='number')
assert(type(g:noncentral_f(2,3,4))=='number')
local z=np.random.default_rng(42)
local empty=z:noncentral_chisquare(1,2,{0,4})
assert(empty.shape[1]==0 and empty.shape[2]==4)
local original=np.random.default_rng(42)
assert(z:raw_hex()==original:raw_hex())
print('distributions60 Lua regression passed')
