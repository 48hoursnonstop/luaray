local np=require('luaray_core')
assert(np._version=='0.137.0-dev')
local function eq(x,y) assert(x==y,tostring(x)..' ~= '..tostring(y)) end
local function fails(f)assert(not pcall(f),'accepted invalid repeats')end
local a=np.reshape(np.arange(12,'int32'),{3,4})
local b=np.tile(a,{2,3})
eq(b.shape[1],6);eq(b.shape[2],12);eq(b:get(4,7),a:get(1,3))
a:set(999,1,3);eq(b:get(4,7),2) -- independent allocation
b:set(55,4,7);eq(a:get(1,3),999)
local f=np.flip(a,2)
local rev=np.tile(f,{2,1});eq(rev:get(1,1),3);eq(rev:get(4,4),0)
local trans=np.transpose(a)
local t=np.tile(trans,{2,3});eq(t:get(2,2),a:get(2,2))
local scalar=np.tile(np.array(7,'float64'),{2,3})
eq(scalar.shape[1],2);eq(scalar.shape[2],3);eq(scalar:get(2,3),7)
local flat=np.repeat_elements(np.array({10,20,30},'int16'),{2,0,3})
eq(flat.size,5);eq(flat[1],10);eq(flat[2],10);eq(flat[3],30)
local withaxis=np['repeat'](np.reshape(np.arange(6,'int32'),{2,3}),{1,2,0},2)
eq(withaxis.shape[1],2);eq(withaxis.shape[2],3)
eq(withaxis:get(2,3),4)
local empty=np.repeat_elements(np.zeros({2,0},'int32'),3,2)
eq(empty.size,0);eq(empty.shape[1],2)
local nested=np.repeat_elements(np.transpose(np.reshape(np.arange(6,'int32'),{2,3})),{2,0,1},1)
eq(nested.shape[1],3);eq(nested.shape[2],2)
eq(nested:get(3,2),5)
local unicode=np.tile(np.array({'東京','é'},'U2'),{3})
eq(unicode.dtype,'<U2');eq(unicode[3],'東京')
local d=np.repeat_elements(np.array({'2026-10-09'},'datetime64[D]'),2)
eq(d.dtype,'datetime64[D]');eq(tostring(d[2]),'2026-10-09')
fails(function()np.tile(a,{-1,1})end)
fails(function()np.repeat_elements(a,{-1})end)
fails(function()np.repeat_elements(a,{1,2})end)
fails(function()np.repeat_elements(a,1,3)end)
fails(function()np.tile(a,{1,2.5})end)
fails(function()np.repeat_elements(a,np.array({1.5},"float64"))end)
collectgarbage('collect')
print('repeat/tile regression: ok')
