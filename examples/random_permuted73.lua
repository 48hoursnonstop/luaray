local np=require('luaray_core')
local rng=np.random.default_rng(2026)
local scores=np.arange(12,'float64'):reshape({3,4})
local independently_shuffled=rng:permuted(scores,2)
local all_values_shuffled=rng:permuted(scores)
local destination=np.zeros({3,4},'float64')
local returned=rng:permuted(scores,2,destination)
assert(rawequal(returned,destination))
assert(scores:get(1,1)==0 and scores:get(3,4)==11)
assert(independently_shuffled.size==12 and all_values_shuffled.size==12)
print('Generator.permuted independently shuffles each axis fiber, or all flattened values')
print('Original first/last:',scores:get(1,1),scores:get(3,4))
print('Axis sample:',independently_shuffled:get(1,1),independently_shuffled:get(1,2))
print('Flat sample:',all_values_shuffled:get(1,1),all_values_shuffled:get(3,4))
print('out sample:',destination:get(1,1),destination:get(3,4))
print('Next PCG64:',rng:raw_hex())
