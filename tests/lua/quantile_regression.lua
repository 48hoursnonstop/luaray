local np=require('luaray_core')
assert(np._version=='0.131.0-dev')
local function near(a,b,eps)
 eps=eps or 1e-7
 if type(a)=='table' then
  assert(type(b)=='table' and #a==#b)
  for i=1,#a do near(a[i],b[i],eps) end
 else
  assert(type(a)=='number' and type(b)=='number')
  assert(a==b or a~=a and b~=b or math.abs(a-b)<eps*math.max(1,math.abs(b)),tostring(a)..' != '..tostring(b))
 end
end
local function reject(f)assert(not pcall(f))end
local x=np.array({1,2,3,4},np.float64)
near(np.median(x),2.5)
near(np.quantile(x,0.25),1.75)
near(np.percentile(x,25),1.75)
near(np.quantile(x,{0,0.25,0.5,1}):tolist(),{1,1.75,2.5,4})
near(np.quantile(x,np.array({0.5,0.75})):tolist(),{2.5,3.25})
near(np.quantile(x,0.5,{method='lower'}),2)
near(np.quantile(x,0.5,{method='higher'}),3)
near(np.quantile(x,0.5,{method='midpoint'}),2.5)
near(np.quantile(x,0.5,{method='nearest'}),3)
near(np.quantile(x,0.5,{method='inverted_cdf'}),2)
local m=np.array({{1,2,3},{4,5,6}},np.int32)
near(np.median(m),3.5)
near(np.median(m,{axis=2}):tolist(),{2,5})
near(np.quantile(m,{0,0.5,1},{axis=1}):tolist(),{{1,2,3},{2.5,3.5,4.5},{4,5,6}})
near(np.median(m,{axis=1,keepdims=true}):tolist(),{{2.5,3.5,4.5}})
near(np.median(np.transpose(m),{axis=1}):tolist(),{2,5})
near(np.median(np.flip(m,2)),3.5)
assert(np.quantile(m,{0.5},{method='lower'}).dtype=='int32')
assert(np.quantile(m,{0.5}).dtype=='float64')
local o=np.zeros({2},np.float64)
assert(np.quantile(m,0.5,{axis=2,out=o})==o)
near(o:tolist(),{2,5})
local a=np.array({4,1,3,2},np.float64)
assert(np.median(a)==2.5)
near(a:tolist(),{4,1,3,2})
reject(function()np.quantile(a,-0.1)end)
reject(function()np.quantile(a,1.1)end)
reject(function()np.quantile(a,0/0)end)
reject(function()np.quantile(a,0.5,{method='hazen'})end)
reject(function()np.quantile(a,0.5,{weights={1,2,3,4}})end)
assert(np.median(np.array({},np.float64))~=np.median(np.array({},np.float64)))
reject(function()np.median(np.array({np.complex(1,1)},np.complex128))end)
print('quantile regression: ok')
-- Extra argument contract: median must not accept the quantile method option.
assert(not pcall(function()np.median(np.array({1,2,3}),{method='lower'})end))
