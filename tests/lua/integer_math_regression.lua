local lr=require('luaray')
local checks=0
local function eq(a,b)
 checks=checks+1
 if type(b)=='table' then
  assert(type(a)=='table' and #a==#b)
  for i=1,#b do eq(a[i],b[i]) end
 else assert(a==b,tostring(a)..' ~= '..tostring(b)) end
end
local function fails(f)checks=checks+1;assert(not pcall(f),debug.traceback())end
local a=lr.array({-7,-1,0,7},'int8')
eq(lr.bitwise_count(a):tolist(),{3,1,0,3})
eq(lr.dtype(lr.bitwise_count(a).dtype).name,'uint8')
eq(lr.invert(a):tolist(),{6,0,-1,-8});eq((~a):tolist(),{6,0,-1,-8})
eq((a<<1):tolist(),{-14,-2,0,14});eq((a>>1):tolist(),{-4,-1,0,3})
eq((a<<-1):tolist(),{0,0,0,0});eq((a>>-1):tolist(),{-1,-1,0,0})
eq((a<<8):tolist(),{0,0,0,0});eq((a>>8):tolist(),{-1,-1,0,0})
eq((1<<lr.array({0,1,2},'int8')):tolist(),{1,2,4})
eq(lr.invert({0,1}):tolist(),{-1,-2})
eq(lr.bitwise_not,lr.invert);eq(lr.bitwise_invert,lr.invert)
eq(lr.bitwise_left_shift,lr.left_shift);eq(lr.bitwise_right_shift,lr.right_shift)
local booleans=lr.array({true,false})
eq((~booleans):tolist(),{false,true})
eq(lr.bitwise_count(booleans):tolist(),{1,0})
eq(lr.left_shift(booleans,true):tolist(),{2,0})
fails(function()lr.gcd(booleans,booleans)end)
fails(function()lr.lcm(booleans,booleans)end)
eq(lr.gcd(booleans,3):tolist(),{1,3})
local unsigned=lr.array({0,1,127,255},'uint8')
eq((unsigned<<1):tolist(),{0,2,254,254})
eq((unsigned>>1):tolist(),{0,0,63,127})
fails(function()return unsigned<<-1 end)
fails(function()return unsigned<<256 end)
fails(function()return unsigned<<1.0 end)
local minimum=lr.array({math.mininteger,math.maxinteger},'int64')
eq(lr.bitwise_count(minimum):tolist(),{1,63})
eq((~minimum):tolist(),{math.maxinteger,math.mininteger})
eq((minimum<<1):tolist(),{0,-2})
eq((minimum>>63):tolist(),{-1,0})
eq(lr.gcd(minimum,0):tolist(),{math.mininteger,math.maxinteger})
eq(lr.lcm(minimum,1):tolist(),{math.mininteger,math.maxinteger})
eq(lr.gcd(lr.array({-12,0,18},'int16'),6):tolist(),{6,6,6})
eq(lr.lcm(lr.array({-12,0,18},'int16'),6):tolist(),{12,0,18})
eq(lr.gcd(0,0):item(),0);eq(lr.lcm(0,0):item(),0)
local broadcast=lr.left_shift(lr.array({{1},{2}},'int16'),lr.array({0,1,2},'int16'))
eq(broadcast:tolist(),{{1,2,4},{2,4,8}})
local out=lr.full({3},99,{dtype='int16'})
local source=lr.array({1,2,3},'int16')
eq(rawequal(lr.right_shift(source,1,{out=out,where=lr.array({true,false,true})}),out),true)
eq(out:tolist(),{0,99,1})
local shared=lr.array({1,2,3},'int8')
local reversed=lr.flip(shared,1)
eq(rawequal(lr.left_shift(shared,1,{out=reversed}),reversed),true)
eq(shared:tolist(),{6,4,2})
local locked=lr.array({1,2,3},'int16');locked:setflags(false)
eq(lr.invert(locked):tolist(),{-2,-3,-4})
fails(function()lr.invert(locked,{out=locked})end)
eq(locked:tolist(),{1,2,3})
local raw=lr.ndarray({3},{dtype='bool',buffer=string.char(0,2,255)})
eq(lr.invert(raw):tolist(),{true,false,false})
eq(lr.bitwise_count(raw):tolist(),{0,1,1})
local backing=lr.zeros({2},'uint64')
local unaligned=backing:getfield('uint16',1)
unaligned:fill(0x0102)
eq(unaligned.flags.aligned,false)
eq(lr.bitwise_count(unaligned):tolist(),{2,2})
eq(lr.invert(unaligned):tolist(),{0xfefd,0xfefd})
for _,dtype in ipairs({'int8','uint8','int16','uint16','int32','uint32','int64','uint64','longlong','ulonglong'}) do
 local typed=lr.array({0,1,7},dtype)
 eq(lr.dtype(lr.invert(typed).dtype).char,lr.dtype(dtype).char)
 eq(lr.dtype(lr.gcd(typed,typed).dtype).char,lr.dtype(dtype).char)
 eq(lr.bitwise_count(typed):tolist(),{0,1,3})
end
for _,dtype in ipairs({'float16','float32','float64','longdouble','complex64','complex128','complex256','S3','U3','datetime64[D]','timedelta64[h]'}) do
 local typed=lr.empty({0},dtype)
 fails(function()lr.invert(typed)end)
 fails(function()lr.bitwise_count(typed)end)
 fails(function()lr.left_shift(typed,1)end)
 fails(function()lr.gcd(typed,1)end)
end
fails(function()lr.left_shift(lr.array({1},'uint64'),lr.array({1},'int64'))end)
fails(function()lr.invert(source,{dtype='int16'})end)
fails(function()lr.invert(source,{out=out,where=lr.ones({3},'int8')})end)
local alias=lr.array({1,2},'longlong')
eq(lr.dtype(lr.left_shift(alias,false).dtype).char,lr.dtype('int64').char)
eq(lr.dtype(lr.left_shift(alias,1).dtype).char,lr.dtype('int64').char)
eq(lr.dtype(lr.left_shift(alias,lr.array(1,'longlong')).dtype).char,lr.dtype('longlong').char)
eq(lr.dtype(lr.gcd(alias,lr.array({1,2},'int64')).dtype).char,lr.dtype('longlong').char)
eq(lr.dtype(lr.gcd(lr.array({1,2},'int64'),alias).dtype).char,lr.dtype('longlong').char)
eq(lr.astype(raw,'int8'):tolist(),{0,1,1})
local scalar=lr.invert(0)
eq(scalar.ndim,0);eq(scalar:item(),-1);eq(scalar.flags.owndata,true)
print('integer math regression: '..checks..' checks passed')
