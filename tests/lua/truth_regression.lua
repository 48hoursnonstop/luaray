local np = require('luaray_core')
assert(np._version == '0.137.0-dev')
local function eq(x,y)
 if type(x)=='table' then assert(type(y)=='table' and #x==#y); for i=1,#x do eq(x[i],y[i]) end
 else assert(x==y,tostring(x)..' != '..tostring(y)) end
end
local a=np.array({{0,2,0},{3,0,5}},np.int64)
assert(np.count_nonzero(a)==3)
assert(np.any(a)==true and np.all(a)==false)
eq(np.count_nonzero(a,{axis=1}):tolist(),{1,1,1})
eq(np.count_nonzero(a,{axis=2}):tolist(),{1,2})
eq(np.any(a,{axis=1,keepdims=true}):tolist(),{{true,true,true}})
eq(np.all(a,{axis=2}):tolist(),{false,false})
assert(np.any(a,{where=false})==false)
assert(np.all(a,{where=false})==true)
local w=np.array({{false,true,false}},np.bool)
eq(np.any(a,{axis=2,where=w}):tolist(),{true,false})
eq(np.all(a,{axis=2,where=w}):tolist(),{true,false})
local t=np.transpose(a)
assert(np.count_nonzero(t)==3)
eq(np.count_nonzero(np.flip(a,2),{axis=1}):tolist(),{1,1,1})
local o=np.zeros({3},np.int64)
assert(np.any(a,{axis=1,out=o})==o)
eq(o:tolist(),{1,1,1})
local empty=np.zeros({0,2},np.float64)
assert(np.count_nonzero(empty)==0)
eq(np.all(empty,{axis=1}):tolist(),{true,true})
eq(np.any(empty,{axis=1}):tolist(),{false,false})
local f=np.array({0/0,0,-0.0,math.huge},np.float64)
assert(np.count_nonzero(f)==2)
local s=np.array({'','a',''},'U2')
assert(np.count_nonzero(s)==1 and np.any(s)==true and np.all(s)==false)
local b=np.array({0,3,0},np.int64)
assert(np.any(b,{axis={},out=b})==b)
assert(b:get(1)==0 and b:get(2)==1)
assert(not pcall(function() np.count_nonzero(a,{where=false}) end))
assert(not pcall(function() np.any(a,{dtype='float64'}) end))
print('truth regression passed')
