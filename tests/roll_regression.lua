local np=require('luaray_core')
assert(np._version=='0.98.0-dev')
local function equal(x,y)assert(x==y,tostring(x)..' ~= '..tostring(y))end
local a=np.reshape(np.arange(12,'int32'),{3,4})
local b=np.roll(a,1,2)
equal(b:get(2,1),a:get(2,4))
a:set(42,2,4)
equal(b:get(2,1),7)
b:set(111,2,1)
equal(a:get(2,4),42) -- roll copies independently
local c=np.roll(a,1)
equal(c:get(1,1),11)
local d=np.roll(a,{1,-1},{1,2})
equal(d:get(1,1),a:get(3,2))
local z=np.roll(np.zeros({0,3},'float64'),100,1)
equal(z.size,0)
local s=np.roll(np.array(3,'float64'),4)
equal(s.ndim,0)
local v=np.rollaxis(np.reshape(np.arange(24,'int16'),{2,3,4}),3,1)
equal(v.shape[1],4);equal(v.shape[2],2);equal(v.shape[3],3)
v:set(555,2,2,2)
equal(v:get(2,2,2),555)
local parent=np.reshape(np.arange(24,'int16'),{2,3,4})
local view=np.rollaxis(parent,3,1)
view:set(889,2,1,1)
equal(parent:get(1,1,2),889)
parent=nil;collectgarbage('collect')
equal(view:get(2,1,1),889)
local neg=np.roll(np.flip(np.array({'東','é','X'},'U1')),-1)
equal(neg[1],'é');equal(neg.dtype,'<U1')
assert(not pcall(function() np.roll(a,1,0) end))
assert(not pcall(function() np.rollaxis(a,1,0) end))
assert(not pcall(function() np.roll(a,{1,2,3},{1,2}) end))
print('roll/rollaxis regression: ok')
