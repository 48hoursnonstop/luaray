local n = require('luaray_core')
assert(n._version == '0.98.0-dev')
local function near(x,y)
 if x~=x and y~=y then return end
 assert(x==y, tostring(x)..' != '..tostring(y))
end
local a=n.array({{0/0,5,1},{2,0/0,6}},n.float64)
near(n.nanmin(a),1);near(n.nanmax(a),6)
local x=n.nanmin(a,{axis=2}); assert(x.shape[1]==2);near(x:get(1),1);near(x:get(2),2)
local y=n.nanmax(a,{axis=1}); assert(y.shape[1]==3);near(y:get(1),2);near(y:get(2),5);near(y:get(3),6)
near(n.nanargmin(a),3);near(n.nanargmax(a),6)
assert(n.nanargmin(a,{axis=2}):get(1)==3)
assert(n.nanargmin(a,{axis=2}):get(2)==1)
assert(n.nanargmax(a,{axis=1}):get(1)==2)
assert(n.nanargmax(a,{axis=1}):get(2)==1)
local b=n.array({0/0,0/0},n.float64)
near(n.nanmin(b),0/0); near(n.nanmax(b),0/0)
assert(not pcall(function() n.nanargmin(b) end))
assert(not pcall(function() n.nanargmax(b) end))
local c=n.flip(a,2)
near(n.nanmin(c),1)
local out=n.zeros({2},n.float64)
assert(n.nanmin(a,{axis=2,out=out})==out)
near(out:get(1),1);near(out:get(2),2)
local oi=n.zeros({2},n.int64)
assert(n.nanargmax(a,{axis=2,out=oi})==oi)
assert(oi:get(1)==2 and oi:get(2)==3)
local v=n.array({9,3,6},n.int64)
assert(n.nanmin(v)==3 and n.nanargmax(v)==1)
-- Verify source untouched, including NaN payload.
assert(a:get(1,1)~=a:get(1,1))
print('nan extrema regression passed')
local masked=n.array({{0,0,1},{1,0,1}},n.bool)
local rm=n.nanmin(n.array({{10,0/0,4},{0/0,3,8}},n.float64),{axis=2,where=masked,initial=50})
near(rm:get(1),4);near(rm:get(2),8)
assert(not pcall(function()n.nanmin(a,{where=masked})end))
local vm=n.array({4,0/0,9},n.float64)
assert(vm:nanmax()==9 and vm:nanargmax()==3)
