from pathlib import Path
import numpy as np,itertools,hashlib
p=Path(__file__).resolve().parents[1]
seeds=[0,1,2,42,1234,2**32-1,2**32,2**63-1]
pairs=[(0,0),(0,1),(1,0),(1,1),(0,30),(30,0),(1,30),(30,1),(3,6),(15,15),(20,20),(100,200),(300,100),(1000,300),(400,700),(10000,10000),(100000000,100000000),(999999999,1)]
sizes=[None,(),(0,),(1,),(2,3),(13,)]
def fmtshape(s):return 'nil' if s is None else '{'+','.join(map(str,s))+'}'
def raw(r):return format(int(r.bit_generator.random_raw()),'016x')
lines=['-- Generated by tests/generate_distributions66_oracle.py against NumPy '+np.__version__,'local np=require("luaray_core")','assert(np._version=="0.66.0-dev")','local total=0','local function eq(a,b) assert(a==b,("case %d %s ~= %s"):format(total,tostring(a),tostring(b)));total=total+1 end']
for seed in seeds:
 for good,bad in pairs:
  n=good+bad
  sample_opts=sorted({x for x in [0,1,2,5,9,10,11,n//2,max(0,n//2-1),min(n,n//2+1),max(0,n-10),max(0,n-9),n] if x<=n})
  for sample in sample_opts:
   for size in sizes:
    r=np.random.default_rng(seed)
    out=r.hypergeometric(good,bad,sample,size=size)
    after=raw(r)
    lines.append(f'do local r=np.random.default_rng({seed}); local v=r:hypergeometric({good},{bad},{sample},{fmtshape(size)})')
    if size is None:
     lines.append(f'eq(v,{int(out)})')
    else:
     lines.append('eq(v.dtype,"int64")')
     lines.append(f'eq(#v.shape,{len(size)})')
     for i,d in enumerate(size):lines.append(f'eq(v.shape[{i+1}],{d})')
     for ix in np.ndindex(out.shape):lines.append('eq(v:get('+','.join(str(i+1) for i in ix)+'),'+str(int(out[ix]))+')')
    lines.append(f'eq(r:raw_hex(),"{after}") end')
# independent mixed PCG64 state
for seed in seeds:
 r=np.random.default_rng(seed)
 lines.append(f'do local r=np.random.default_rng({seed})')
 for g,b,s in [(12,8,4),(400,500,100),(0,100,99),(100000,100000,100000),(1,999,10),(20,35,35)]:
  lines.append(f'eq(r:hypergeometric({g},{b},{s}),{int(r.hypergeometric(g,b,s))})')
  lines.append(f'eq(r:random(),{repr(float(r.random()))})')
  lines.append(f'eq(r:integers(0,1000),{int(r.integers(0,1000))})')
 lines.append(f'eq(r:raw_hex(),"{raw(r)}") end')
# invalid params, no state changes
for seed in seeds:
 for triple in [(-1,5,1),(5,-1,1),(5,5,-1),(5,6,12),(1000000000,2,2),(2,1000000000,2)]:
  r=np.random.default_rng(seed)
  lines.extend([f'do local r=np.random.default_rng({seed})',f'local ok=pcall(function()r:hypergeometric({triple[0]},{triple[1]},{triple[2]})end)','eq(ok,false)',f'eq(r:raw_hex(),"{raw(r)}") end'])
lines.append('print("distributions66 differential passed",total,"checks")')
(p/'tests/distributions66_differential_generated.lua').write_text('\n'.join(lines)+'\n')
print('oracle lines',len(lines),'python numpy version',np.__version__)

