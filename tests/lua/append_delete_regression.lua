local np=require('luaray_core')
assert(np._version=='0.120.0-dev')
local function same(a,b)
 if type(b)=='table' then assert(type(a)=='table' and #a==#b) for i=1,#b do same(a[i],b[i]) end
 else assert(a==b,tostring(a)..' ~= '..tostring(b)) end
end
local a=np.reshape(np.array({1,2,3,4,5,6},'int16'),{2,3})
local b=np.reshape(np.array({7,8,9},'int16'),{1,3})
local r=np.append(a,b,1)
same(r.shape,{3,3});same(r:tolist(),{{1,2,3},{4,5,6},{7,8,9}})
a[1][1]=100
assert(r[1][1]==1) -- independent copy
same(np.append(np.flip(a,2),np.flip(b,2),1):tolist(),{{3,2,100},{6,5,4},{9,8,7}})
same(np.append(np.array({1,2},'int16'),np.array({3.5},'float64')):tolist(),{1,2,3.5})
same(np.append(np.array({'東'},'U3'),np.array({'界'},'U2')):tolist(),{'東','界'})
same(np.append(np.array(9,'int32'),np.array(8,'int32')):tolist(),{9,8})
assert(not pcall(function()np.append(a,b,2)end))
local d=np.delete(a,2,2)
same(d:tolist(),{{100,3},{4,6}})
a[1][1]=999;assert(d[1][1]==100)
same(np.delete(np.array({1,2,3,4}),{2,4}):tolist(),{1,3})
same(np.delete(np.array({1,2,3,4}),{true,false,true,false}):tolist(),{2,4})
same(np.delete(np.array({1,2,3,4}),np.array({true,false,true,false},'bool')):tolist(),{2,4})
same(np.delete(np.array({1,2,3,4}),np.slice(2,4)):tolist(),{1,4})
same(np.delete(np.array({1,2,3,4}),np.slice(nil,nil,-2)):tolist(),{1,3})
same(np.delete(np.array({1,2,3,4}),np.array({1,-1},'int32')):tolist(),{2,3})
same(np.delete(np.array(11),1):tolist(),{})
same(np.delete(np.array(11),{}):tolist(),{11})
same(np.delete(np.flip(np.array({1,2,3,4})),2):tolist(),{4,2,1})
assert(not pcall(function()np.delete(np.array({1,2}),0)end))
assert(not pcall(function()np.delete(np.array({1,2}),5)end))
assert(not pcall(function()np.delete(np.array({1,2}),{true})end))
assert(not pcall(function()np.delete(np.array({1,2}),np.array({0},'int16'))end))
print('append/delete regression: ok')
