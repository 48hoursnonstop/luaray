local lr = require("luaray")
local coefficients = lr.poly({1, 2, 3})
assert(lr.array_equal(coefficients, {1, -6, 11, -6}))
assert(lr.allclose(lr.sort(lr.roots(coefficients)), {1, 2, 3}, {atol=1e-11}))
local conjugate = lr.poly({lr.complex(0, 1), lr.complex(0, -1)})
assert(conjugate.dtype=="float64" and lr.array_equal(conjugate, {1, 0, 1}))
local z = lr.roots(conjugate)
assert(lr.allclose(lr.real(z), {0, 0}) and lr.allclose(lr.sort(lr.imag(z)), {-1, 1}))
assert(lr.array_equal(lr.roots({0, 1, 0, 0}), {0, 0}))
assert(lr.roots({0,0,0}).size == 0 and lr.poly({}) == 1)
local matrix = lr.array({{1,0,0},{0,3,2},{0,0,4}}, "float32")
local characteristic = lr.poly(matrix)
assert(characteristic.dtype=="float32" and lr.allclose(characteristic,{1,-8,19,-12}))
assert(lr.mintypecode("Fd")=="D")
assert(lr.mintypecode({"f","d"})=="d")
assert(lr.mintypecode(lr.ones({2},"float32"))=="f")
assert(lr.mintypecode("bh",nil,"G")=="G")
assert(not pcall(lr.poly, lr.ones({2,3})))
assert(not pcall(lr.roots, lr.ones({2,2})))
assert(not pcall(lr.roots, lr.array({1,0,1},"float16")))
assert(not pcall(lr.mintypecode, "x", "x"))
print("Polynomial roots regression passed")
