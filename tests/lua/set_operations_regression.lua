local lr=require('luaray')
local function same(a,expected) assert(table.concat(a:tolist(),',')==expected) end
local a,b=lr.array({{3,1},{3,2}},'int16'),lr.array({1,2,2,5},'int16')
same(lr.union1d(a,b),'1,2,3,5')
same(lr.setxor1d(a,b),'3,5')
same(lr.setdiff1d(a,b),'3')
local values,first,second=lr.intersect1d(a,b,{return_indices=true})
same(values,'1,2')
same(first,'2,4')
same(second,'1,2')
same(lr.take(a,first,{axis=false}),'1,2')
same(lr.setdiff1d({4,3,2,1},{2,1},{assume_unique=true}),'4,3')
same(lr.intersect1d({4,3,2,1},{2,1},{assume_unique=true}),'1,2')
local empty=lr.empty({0,2},'float32')
assert(lr.intersect1d(empty,empty).size==0)
assert(lr.setxor1d(empty,empty).dtype=='float32')
assert(lr.union1d({0/0},{0/0}).size==1)
assert(lr.intersect1d({0/0},{0/0}).size==0)
assert(not pcall(lr.setxor1d,a,b,{return_indices=true}))
assert(not pcall(lr.intersect1d,a,b,{assume_unique=1}))
print('Array set operations regression passed')
