local lr = require('luaray')
local values,first,inverse,counts=lr.unique({3,1,3,2,1},{
  return_index=true,return_inverse=true,return_counts=true
})
local function matches(a,s) assert(table.concat(a:tolist(),',')==s) end
matches(values,'1,2,3')
matches(first,'2,4,1')
matches(inverse,'3,1,3,2,1')
matches(counts,'2,1,2')
local all=lr.unique_all({7,3,7})
matches(all.values,'3,7')
matches(all.indices,'2,1')
matches(all.inverse_indices,'2,1,2')
matches(all.counts,'1,2')
matches(lr.unique_counts({2,1,2}).counts,'1,2')
matches(lr.unique_inverse({2,1,2}).inverse_indices,'2,1,2')
matches(lr.unique_values({2,1,2}),'1,2')

local a=lr.array({{3,2},{1,1},{3,2},{2,2}})
local rows,index=lr.unique(a,{axis=1,return_index=true})
assert(rows[3][2]==2 and rows[1][1]==1 and index[3]==1)
local empty=lr.unique(lr.empty({3,0}),{axis=1})
assert(empty.shape[1]==1 and empty.shape[2]==0)

local special=lr.array({2,0/0,0/0,2},'float64')
assert(lr.unique(special).size==2)
assert(lr.unique_values(special).size==3)
local half=lr.array({{4,-1,0/0},{0,4,4}},'float16')
local columns=lr.unique(half,{axis=-1})
assert(columns[1][1]~=columns[1][1] and columns[1][2]==-1)
assert(lr.unique(lr.ndarray({3},'S0')).dtype=='|S1')
assert(not pcall(lr.unique,lr.ndarray({2,3},'S0'),{axis=1}))
assert(not pcall(lr.unique,a,{axis=3}))
assert(not pcall(lr.unique,a,{equal_nan='yes'}))
print('Unique values regression passed')
