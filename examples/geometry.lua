local lr=require('luaray')
assert(lr.cross({1,0,0},{0,1,0}):tolist()[3]==1)
local x=lr.array({0.,1.},'float32')
local y=lr.array({0.,1.,2.},'float64')
local g=lr.meshgrid({x,y},{indexing='xy'})
assert(g[1].dtype=='float32' and g[2].dtype=='float64')
assert(g[1].shape[1]==3 and g[1].shape[2]==2)
assert(g[1]:tolist()[3][2]==1. and g[2]:tolist()[3][2]==2.)
local shared=lr.meshgrid({x,y},{copy=false})
shared[1]:set(7.,1,1)
assert(x:tolist()[1]==7. and shared[1]:tolist()[3][1]==7.)
local sparse=lr.meshgrid({x,y},{sparse=true,copy=false,indexing='ij'})
assert(sparse[1].shape[2]==1 and sparse[2].shape[1]==1)
print('vector116 public module example passed: cross, typed grids, sparse shapes and shared writes')
