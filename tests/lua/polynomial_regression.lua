local lr = require("luaray")
assert(lr.array_equal(lr.polyadd({1, 2, 3}, {3, 4}), {1, 5, 7}))
assert(lr.array_equal(lr.polysub({1, 2, 3}, {3, 4}), {1, -1, -1}))
assert(lr.array_equal(lr.polymul({0, 1, -1}, {1, 1}), {1, 0, -1}))
assert(lr.array_equal(lr.polymul({}, {2, 1}), {0, 0}))
assert(lr.array_equal(lr.polyder({1, 2, 3}), {2, 2}))
assert(lr.polyder({1}, 2).size == 0)
local coefficients = lr.array({3, 4, 5}, "float32")
assert(rawequal(lr.polyder(coefficients, 0), coefficients))
assert(lr.array_equal(lr.polyint({2, 4}, 1, 10), {1, 4, 10}))
assert(lr.allclose(lr.polyint({6}, 2, {2, 3}), {3, 2, 3}))
assert(lr.polyval({1, 2, 3}, 2) == 11)
assert(lr.array_equal(lr.polyval({1, 2, 3}, {1, 2}), {6, 11}))
assert(lr.array_equal(lr.polyval(lr.array({{1, 2}, {3, 4}}), {2, 3}), {5, 10}))
local c = lr.polyval({lr.complex(1, 2), lr.complex(0, 3)}, 2)
assert(c.real == 2 and c.imag == 7)
assert(lr.polyval({}, lr.array(3, "int8")).dtype == "int8")
assert(not pcall(lr.polyder, {1, 2}, -1))
assert(not pcall(lr.polyint, {1, 2}, 3, {2, 3}))
assert(not pcall(lr.polyval, 3, {1, 2}))
print("Polynomial arithmetic regression passed")
