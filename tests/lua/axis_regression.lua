local np=require('luaray_core')
assert(np._version=='0.161.0-dev')
local function eq(a,b) assert(a==b,tostring(a)..' ~= '..tostring(b)) end
local function reject(fn) assert(not pcall(fn),'expected invalid axis to be rejected') end
local a=np.reshape(np.arange(24,'int32'),{2,3,4})
local t=np.transpose(a,{3,1,2})
eq(t.shape[1],4);eq(t.shape[2],2);eq(t.shape[3],3)
t:set(777,2,1,3);eq(a:get(1,3,2),777)
local sw=np.swapaxes(a,1,3)
eq(sw:get(2,2,1),a:get(1,2,2))
local moved=np.moveaxis(a,{1,3},{3,1})
eq(moved:get(2,3,1),a:get(1,3,2))
local reversed=np.flip(a,{1,3})
eq(reversed:get(1,2,1),a:get(2,2,4))
reversed:set(-33,2,1,4);eq(a:get(1,1,1),-33)
local original=np.array({1,2,3,4,5},'int64')
local flip=np.flip(original)
flip[1]=100;eq(original[5],100)
local reverse_back=np.flip(flip)
eq(reverse_back[5],100)
local expanded=np.expand_dims(original,{1,3})
eq(expanded.ndim,3);eq(expanded.shape[1],1);eq(expanded.shape[2],5);eq(expanded.shape[3],1)
expanded:set(77,1,2,1);eq(original[2],77)
local sq=np.squeeze(expanded)
eq(sq.ndim,1);eq(sq[2],77)
local keep=np.squeeze(expanded,{1})
eq(keep.ndim,2);eq(keep.shape[2],1)
local m=np.reshape(np.arange(6,'int64'),{2,3})
local r=np.rot90(m)
eq(r.shape[1],3);eq(r.shape[2],2)
eq(r:get(1,1),2);eq(r:get(3,2),3)
r:set(999,1,1);eq(m:get(1,3),999)
local rot3=np.rot90(m,-1)
eq(rot3:get(1,1),m:get(2,1))
local ud=np.flipud(m); local lr=np.fliplr(m)
eq(ud:get(1,2),m:get(2,2));eq(lr:get(1,1),m:get(1,3))
-- The view must outlive its source and hold the same storage.
local function orphan()
  local orig=np.reshape(np.arange(12,'float64'),{3,4})
  return np.moveaxis(np.flip(orig,2),1,2)
end
local v=orphan();collectgarbage('collect');collectgarbage('collect')
eq(v:get(1,3),11);v:set(42,4,2);eq(v:get(4,2),42)
-- Parameterized descriptors are retained by axis transforms.
local strings=np.reshape(np.array({'東京','é','界','a'},'U2'),{2,2})
local words=np.rot90(strings)
eq(words.dtype,'<U2');eq(words:get(1,1),'é')
local dt=np.array({'2026-10-09','2026-10-10'},'datetime64[D]')
eq(np.flip(dt).dtype,'datetime64[D]')
eq(tostring(np.flip(dt)[1]),'2026-10-10')
local scalar=np.array(5,'int64')
eq(np.flip(scalar),5)
eq(np.expand_dims(scalar,1).shape[1],1)
eq(np.squeeze(scalar,1).ndim,0)
reject(function()np.transpose(a,{1,1,3})end)
reject(function()np.transpose(a,{1,2})end)
reject(function()np.flip(a,{1,1})end)
reject(function()np.flip(a,0)end)
reject(function()np.flip(scalar,1)end)
reject(function()np.moveaxis(a,{1,2},{1,1})end)
reject(function()np.expand_dims(a,{1,1})end)
reject(function()np.squeeze(a,1)end)
reject(function()np.rot90(a,1,{1,1})end)
reject(function()np.fliplr(original)end)
print('axis regression: ok')
