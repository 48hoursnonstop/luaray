#!/usr/bin/env python3
"""Independent NumPy 2.3.5 oracle for gamma, standard_gamma, beta.
Source reference: NumPy 2.5.3; compare numerical values and next PCG64 word.
"""
import numpy as np
from pathlib import Path

out=Path(__file__).resolve().parents[1]/'tests/distributions58_differential_generated.lua'
lines=[f'-- Differential comparison with NumPy {np.__version__}; generated by tools/generate_distributions58_differential.py',
    "local np=require('luaray_core')", "assert(np._version=='0.82.0-dev')", 'local n=0',
    'local function eq(a,b) assert(a==b or (a~=a and b~=b), tostring(n).." :: "..tostring(a).." != "..tostring(b));n=n+1 end',
    'local function eqf(a,b) assert(a==b or (a~=a and b~=b) or math.abs(a-b)<=3e-5*math.max(math.abs(b),1e-7), tostring(n).." :: "..tostring(a).." ~= "..tostring(b));n=n+1 end']

def lit(v):
    x=float(v)
    if np.isnan(x):return '(0/0)'
    if np.isposinf(x):return 'math.huge'
    if np.isneginf(x):return '-math.huge'
    return repr(x)
def shp(s):
    if s is None:return 'nil'
    if len(s)==1:return str(s[0])
    return '{'+','.join(map(str,s))+'}'
def verify(v,s,approx=False):
    cmp="eqf" if approx else "eq"
    if s is None: lines.append(cmp+'(v,'+lit(v)+')')
    else:
        lines.append(f'eq(v.dtype,"{v.dtype}")')
        for i,d in enumerate(s,1): lines.append(f'eq(v.shape[{i}],{d})')
        for ix in np.ndindex(*s):
            idx=','.join(str(j+1) for j in ix)
            lines.append(f'{cmp}(v:get({idx}),{lit(v[ix])})')
def raw(r): lines.append(f'eq(r:raw_hex(),"{int(r.bit_generator.random_raw()):016x}")')

seeds=[0,1,2,42,99,123456789,1099511627779,4611686018427387909]
shapes=[None,(),(0,),(1,),(2,3),(2,0,4),(3,2,3),(127,)]
params={
 'standard_gamma': [(0.,),(0.125,),(0.75,),(1.,),(2.,),(3.5,),(10.,),(100.,)],
 'gamma':[(0.,1.),(0.125,0.),(0.125,1.),(0.75,2.),(1.,1.),(2.,3.),(10.,.125),(50.,0.)],
 'beta':[(0.125,0.125),(.5,.5),(.75,1.),(1.,1.),(1.,3.),(3.,1.),(2.,3.),(5.,8.),(1e-110,1e-110),(.00001,.0001)]}
for seed in seeds:
 for name, plist in params.items():
  for par in plist:
   for size in shapes:
    dtypes=[None,np.float32] if name=='standard_gamma' else [None]
    for dt in dtypes:
     r=np.random.default_rng(seed)
     kwargs={'size':size}
     if dt is not None:kwargs['dtype']=dt
     v=getattr(r,name)(*par,**kwargs)
     args=','.join([*(lit(p) for p in par),shp(size)]+(['"float32"'] if dt is not None else ([] if name!='standard_gamma' else ['"float64"'])))
     lines.append(f'do local r=np.random.default_rng({seed}); local v=r:{name}({args})')
     verify(v,size,dt is not None);raw(r);lines.append('end')

for seed in seeds:
 r=np.random.default_rng(seed)
 lines.append(f'do local r=np.random.default_rng({seed})')
 for i in range(360):
  j=i%9
  if j==0: v=r.standard_gamma(.125);call='r:standard_gamma(.125)'
  elif j==1: v=r.beta(.75,1.);call='r:beta(.75,1)'
  elif j==2: v=r.gamma(2.,3.);call='r:gamma(2,3)'
  elif j==3: v=r.standard_normal();call='r:standard_normal()'
  elif j==4: v=r.standard_gamma(3.,dtype=np.float32);call='r:standard_gamma(3,nil,"float32")'
  elif j==5: v=r.random();call='r:random()'
  elif j==6: v=r.standard_exponential();call='r:standard_exponential()'
  elif j==7: v=r.beta(1e-110,1e-110);call='r:beta(1e-110,1e-110)'
  else: v=r.gamma(0.,0.);call='r:gamma(0,0)'
  lines.append(f'{"eqf" if j==4 else "eq"}({call},{lit(v)})')
 raw(r);lines.append('end')

invalid=['r:gamma(-1,2)','r:gamma(2,-1)','r:gamma(0/0,2)','r:beta(0,1)','r:beta(1,0)','r:beta(-1,1)','r:beta(1,-1)',
'r:standard_gamma(-1)','r:gamma(math.huge,1)','r:beta(1,math.huge)','r:standard_gamma(2,nil,"int64")',
'r:gamma(2,1,{-1})','r:beta(1,2,{-1})','r:standard_gamma(1,{-1})',
'r:gamma(1,2,3,4)','r:beta(1,2,3,4)','r:standard_gamma(1,2,"float64",5)']
r=np.random.default_rng(42)
initial=f'{int(r.bit_generator.random_raw()):016x}'
for expr in invalid:
 lines.append(f'do local r=np.random.default_rng(42);eq(pcall(function() {expr} end),false);eq(r:raw_hex(),"{initial}") end')
for v in (float('nan'),float('inf')):
    r=np.random.default_rng(42)
    x=r.standard_gamma(v)
    next_raw=f'{int(r.bit_generator.random_raw()):016x}'
    expression='0/0' if np.isnan(v) else 'math.huge'
    lines.append(f'do local r=np.random.default_rng(42);eq(r:standard_gamma({expression}),{lit(x)});eq(r:raw_hex(),"{next_raw}") end')
lines.append("print('distributions58 differential approved: '..n..' comparisons')")
out.write_text('\n'.join(lines)+'\n')
print('generated',out,'lines',len(lines))
