local n=require('luaray_core')
assert(n._version=='0.111.0-dev')
local function equal(a,b)
 if type(a)=='table' then assert(type(b)=='table' and #a==#b); for i=1,#a do equal(a[i],b[i]) end
 else assert(a==b or (a~=a and b~=b),tostring(a)..' != '..tostring(b)) end
end
local a=n.array({{1,2,3},{4,5,6}},'int32')
equal(n.cumsum(a):tolist(),{1,3,6,10,15,21})
equal(n.cumprod(a):tolist(),{1,2,6,24,120,720})
equal(n.cumsum(a,{axis=1}):tolist(),{{1,2,3},{5,7,9}})
equal(n.cumsum(a,{axis=2}):tolist(),{{1,3,6},{4,9,15}})
equal(n.cumprod(a,{axis=-1}):tolist(),{{1,2,6},{4,20,120}})
equal(n.cumsum(n.transpose(a)):tolist(),{1,5,7,12,15,21})
local x=n.array({1,0/0,2,0/0,3},'float64')
equal(n.nancumsum(x):tolist(),{1,1,3,3,6})
equal(n.nancumprod(x):tolist(),{1,1,2,2,6})
assert(x:get(2)~=x:get(2))
-- Explicit output aliases are safe even when the source is modified.
local inplace=n.array({2,3,4},'int64')
assert(n.cumsum(inplace,{out=inplace})==inplace)
equal(inplace:tolist(),{2,5,9})
local z2=n.array({0/0,3,4},'float64')
assert(n.nancumprod(z2,{out=z2})==z2)
equal(z2:tolist(),{1,3,12})
assert(not pcall(function()n.cumsum(n.array({1,2,3},'int32'),{out=n.zeros({2},'int32')})end))
local y=n.array({0/0,2},'float64')
local out=n.zeros({2},'float64')
assert(n.nancumsum(y,{out=out})==out)
equal(out:tolist(),{0,2})
equal(n.nancumprod(y):tolist(),{1,2})
local s=n.array(7,'int32')
equal(n.cumsum(s):tolist(),{7})
local z=n.reshape(n.array({},'float64'),{0,3})
assert(#n.cumsum(z):tolist()==0)
assert(n.cumsum(z,{axis=2}).shape[2]==3)
local c=n.array({n.complex(1,2),n.complex(0/0,0),n.complex(3,4)},'complex128')
local r=n.nancumsum(c):tolist()
assert(r[1].real==1 and r[3].real==4)
assert(r[3].imag==6)
print('cumulative regression passed')
