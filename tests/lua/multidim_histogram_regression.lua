local lr = require("luaray")
local x = lr.array({0, 0, 2, 2, -1, 3})
local y = lr.array({0, 2, 0, 2, 0, 0})
local bounds = {0, 1, 2}
local counts, xe, ye = lr.histogram2d(x, y, {bins=bounds})
assert(lr.array_equal(counts, {{1, 1}, {1, 1}}))
assert(lr.array_equal(xe, bounds) and lr.array_equal(ye, bounds))
assert(rawequal(xe, ye))
assert(counts.dtype == "float64" and not counts.flags.owndata)
assert(counts.strides[1] == 32 and counts.strides[2] == 8)
local density = lr.histogram2d(x, y, {bins=bounds, weights={1, 2, 3, 4, 5, 6}, density=true})
assert(lr.allclose(density, {{0.1, 0.2}, {0.3, 0.4}}))

local points = lr.array({{0, 0, 0}, {2, 1, 1}, {1, 1, 1}}, "float32")
local grid, edges = lr.histogramdd(points, {bins={2, 2, 2}})
assert(grid:get(1, 1, 1) == 1 and grid:get(2, 2, 2) == 2)
assert(#edges == 3 and edges[1].dtype == "float32")
local columns = {{0, 2, 1}, {0, 1, 1}, {0, 1, 1}}
assert(lr.array_equal(lr.histogramdd(columns, {bins=2}), grid))
local empty = lr.histogramdd(lr.empty({0, 2}), {bins={2, 3}})
assert(lr.array_equal(empty, lr.zeros({2, 3})))
assert(not pcall(lr.histogram2d, x, {1}))
assert(not pcall(lr.histogramdd, points, {bins={2, 3}}))
assert(not pcall(lr.histogram2d, x, y, {bins={{2, 1}, {1, 2}}}))
print("Multidimensional histogram regression passed")
