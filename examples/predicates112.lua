local real=np.real_if_close(near)
assert(real.dtype=='float32' and np.shares_memory(real,near))
np.copyto(real,7,'unsafe');assert(near:tolist()[1].real==7)
assert(rawequal(np.real_if_close(near,1e-12),near))
