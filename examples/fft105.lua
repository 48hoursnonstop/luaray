local np=require('luaray')
local f=np.fft.fftfreq(4,0.5)
assert(f:get(2)==0.5 and f:get(3)==-1)
local shifted=np.fft.fftshift(f)
assert(shifted:get(1)==-1)
local back=np.fft.ifftshift(shifted)
assert(back:get(2)==0.5)
local h=np.fft.hfft({1,2,3})
assert(h.size==4)
local inv=np.fft.ihfft(h)
assert(math.abs(inv:get(2).real-2)<1e-12)
print('LuaRay native FFT helpers example: passed')
