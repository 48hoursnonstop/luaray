local np=require('luaray_core')
assert(np._version=='0.125.0-dev')
local rejected=0
local function rejects(f)
 local rng=np.random.default_rng(890089)
 local control=np.random.default_rng(890089)
 assert(not pcall(function()f(rng)end),'unexpected success of invalid bound #'..(rejected+1))
 assert(rng:raw_hex()==control:raw_hex(),'invalid bound consumed RNG #'..(rejected+1))
 rejected=rejected+1
end
rejects(function(r)r:integers({3,4},{2,5})end)
rejects(function(r)r:integers({-1,0},5,nil,'uint8')end)
rejects(function(r)r:integers({0,1},{256,10},nil,'int8')end)
rejects(function(r)r:integers({1,2},{5,8},{3,3})end)
rejects(function(r)r:integers({0,5},{1,4},nil,'int16',true)end)
rejects(function(r)r:integers({0,1},{1,2},nil,'float64')end)
rejects(function(r)r:integers({0,1},{1,2},nil,'int32','yes')end)
rejects(function(r)r:integers(np.array({0/0},'float64'),5)end)
rejects(function(r)r:integers(np.array({math.huge},'float64'),5)end)
rejects(function(r)r:integers(np.array({9223372036854775807},'uint64'),np.array({9223372036854775807},'uint64'),nil,'int64')end)
rejects(function(r)r:integers({0,1},{1,2},nil,'int32',true,false)end)
local a=np.array({{1},{2}},'int64')
local b=np.array({{4,5,6}},'int64')
local r=np.random.default_rng(42)
local x=r:integers(a,b)
assert(x.dtype=='int64' and x.shape[1]==2 and x.shape[2]==3)
assert(x:get(1,1)==1 and x:get(2,3)>=2)
local scalar=np.random.default_rng(42):integers(np.array(1,'int64'),np.array(5,'int64'))
assert(type(scalar)=='number' and scalar==1)
local empty=np.random.default_rng(42):integers({5,6},{4,3},{0,2})
assert(empty.dtype=='int64' and empty.shape[1]==0)
local flat=np.random.default_rng(42):integers({1,2,3},nil)
assert(flat.dtype=='int64' and flat.shape[1]==3)
local fixed=np.random.default_rng(42)
local expected=np.random.default_rng(42)
local ones=fixed:integers({7,8,9},{7,8,9},{2,3},'int16',true)
assert(ones:get(1,1)==7 and ones:get(2,3)==9)
assert(fixed:raw_hex()==expected:raw_hex(),'width-one endpoint must not consume PCG64')
print('random89 regression PASS: '..rejected..' rejections/no-state-change and vector API cases')
