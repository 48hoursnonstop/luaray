local np=require('luaray_core')
assert(np._version=='0.99.0-dev')
local nan=0/0
local function near(a,b,tol)
 tol=tol or 1e-8
 if type(a)=='table' then assert(type(b)=='table' and #a==#b);for i=1,#a do near(a[i],b[i],tol) end
 elseif type(a)=='number' and type(b)=='number' then assert(a==b or (a~=a and b~=b) or math.abs(a-b)<=tol*math.max(1,math.abs(b)),tostring(a)..' != '..tostring(b))
 else assert(a==b,tostring(a)..' != '..tostring(b)) end
end
local a=np.array({nan,1,2,nan,3},'float64')
near(np.nansum(a),6)
near(np.nanprod(a),6)
near(np.nanmean(a),2)
near(np.nanvar(a),2/3)
near(np.nanstd(a),math.sqrt(2/3))
near(a:nanmean(),2)
near(np.sum(a),nan)
near(a:tolist(),{nan,1,2,nan,3})
local b=np.array({{nan,1,2},{nan,nan,nan}},'float64')
near(np.nansum(b,{axis=2}):tolist(),{3,0})
near(np.nanprod(b,{axis=2}):tolist(),{2,1})
near(np.nanmean(b,{axis=2}):tolist(),{1.5,nan})
near(np.nanvar(b,{axis=2}):tolist(),{.25,nan})
near(np.nanstd(b,{axis=2}):tolist(),{.5,nan})
near(np.nanmean(np.flip(b,2),{axis=2,keepdims=true}):tolist(),{{1.5},{nan}})
local mask=np.array({false,true,true},'bool')
near(np.nanmean(b,{axis=2,where=mask}):tolist(),{1.5,nan})
local dst=np.flip(np.zeros({2},'float64'))
assert(np.nansum(b,{axis=2,out=dst})==dst)
near(dst:tolist(),{3,0})
local original=np.array({1,nan,4},'float64')
assert(np.nansum(original,{axis={},out=original})==original)
near(original:tolist(),{1,0,4})
local z=np.array({np.complex(1,2),np.complex(nan,3),np.complex(3,4)},'complex128')
near(np.nanvar(z),2)
near(np.nanstd(z),math.sqrt(2))
local zz=np.nansum(z)
near(zz.real,4);near(zz.imag,6)
near(np.nansum(np.array({},'float32')),0)
near(np.nanprod(np.array({},'float32')),1)
near(np.nanmean(np.array({},'float32')),nan)
local ok=pcall(function()np.nanmean(np.array({'x'},'U1'))end);assert(not ok)
print('nanreductions regression: ok')
