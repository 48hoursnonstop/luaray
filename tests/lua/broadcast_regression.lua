local np = require('luaray_core')
assert(np._version=='0.142.0-dev')
local function eq(a,b) assert(a==b,tostring(a)..' ~= '..tostring(b)) end
local function rejects(fn) assert(not pcall(fn),'invalid broadcast accepted') end
local a=np.array({3,5,7},'int64')
local v=np.broadcast_to(a,{2,3})
eq(v.ndim,2);eq(v.shape[1],2);eq(v.shape[2],3)
eq(v.strides[1],0);eq(v.strides[2],8)
eq(v:get(2,3),7)
rejects(function()v:set(100,1,1)end)
rejects(function()v[1]=100 end)
a[2]=42;eq(v:get(2,2),42)
local derived=np.transpose(v)
rejects(function()derived:set(100,2,1)end)
local one=np.broadcast_to(np.array(8,'float32'),{2,2,2})
eq(one:get(2,1,1),8);eq(one.strides[1],0);eq(one.strides[2],0)
local arrays=np.broadcast_arrays(np.array({{1},{2}},'int32'),np.array({5,6,7},'int32'))
eq(#arrays,2)
eq(arrays[1].shape[1],2);eq(arrays[1].shape[2],3)
eq(arrays[1].strides[2],0);eq(arrays[2].strides[1],0)
arrays[1]:set(99,1,3);eq(arrays[1]:get(1,1),99)
arrays[2]:set(44,2,2);eq(arrays[2]:get(1,2),44)
local preserved=np.reshape(np.array({1,2,3},'int16'),{1,3})
local result=np.broadcast_arrays(preserved)
eq(result[1].strides[1],preserved.strides[1])
eq(result[1].strides[2],preserved.strides[2])
local reshaped=np.reshape(np.arange(6,'float64'),{2,3})
local neg=np.flip(reshaped,2)
local flipped=np.broadcast_to(neg,{3,2,3})
eq(flipped.strides[1],0);eq(flipped.strides[3],-8)
eq(flipped:get(3,1,1),2)
local empty_source=np.reshape(np.array({},'int32'),{0,1})
assert(np.flip(empty_source,1).strides[1]==empty_source.strides[1])
local empty=np.broadcast_to(np.zeros({0,1},'int32'),{0,7})
eq(empty.shape[2],7);eq(empty.size,0)
local strs=np.broadcast_to(np.array({'東京'},'U2'),{3})
eq(strs.dtype,'<U2');eq(strs[3],'東京')
rejects(function()strs:set('abc',2)end)
local dates=np.broadcast_to(np.array({'2026-10-09'},'datetime64[D]'),{3})
eq(dates.dtype,'datetime64[D]');eq(tostring(dates[3]),'2026-10-09')
local broadcast_after_gc
local function orphan()
  local x=np.array({11,22},'int32')
  return np.broadcast_to(x,{4,2})
end
broadcast_after_gc=orphan()
collectgarbage('collect');collectgarbage('collect')
eq(broadcast_after_gc:get(4,2),22)
local shape=np.broadcast_shapes({2,1,3},{1,4,1},{4,3})
eq(#shape,3);eq(shape[1],2);eq(shape[2],4);eq(shape[3],3)
rejects(function()np.broadcast_to(a,{4,2})end)
rejects(function()np.broadcast_to(a,{-1,3})end)
rejects(function()np.broadcast_to(a,{9223372036854775807,2,3})end)
rejects(function()np.broadcast_to(a,{})end)
rejects(function()np.broadcast_shapes({2,3},{4,3})end)
rejects(function()np.broadcast_arrays(np.zeros({3}),np.zeros({4}))end)
eq(#np.broadcast_arrays(),0);eq(#np.broadcast_shapes(),0)
-- Passing Lua numeric/sequence inputs uses the native array constructor.
eq(np.broadcast_to(5,{2})[2],5)
eq(np.broadcast_to({1,2},{2,2}):get(2,2),2)
print('broadcast regression: ok')
