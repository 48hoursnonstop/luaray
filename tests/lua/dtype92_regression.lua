local np=require('luaray_core')
assert(np._version=='0.133.0-dev')
local a=np.arange(24,'int32'):reshape({2,3,4})
assert(np.astype(a,'int32',{copy=false})==a)
assert(np.astype(a,'int32',{order='C',copy=false})==a)
assert(np.astype(a,'int32',{order='F',copy=false})~=a)
local tr=np.transpose(a,{3,2,1})
assert(np.astype(tr,'int32',{order='F',copy=false})==tr)
assert(np.astype(tr,'int32',{order='C',copy=false})~=tr)
assert(np.astype(tr,'int32',{order='A',copy=false})==tr)
local r=np.flip(a,1)
assert(np.astype(r,'int32',{order='K',copy=false})==r)
assert(np.astype(r,'int32',{order='A',copy=false})~=r)
local c=np.astype(r,'float64',{order='K'})
assert(c.dtype=='float64')
assert(c:get(1,1,1)==r:get(1,1,1))
assert(c:get(2,3,4)==r:get(2,3,4))
local b=np.astype(a,'float64',{order='F',casting='safe'})
assert(b.dtype=='float64' and b:get(2,3,4)==23)
assert(not pcall(np.astype,a,'float64',{order='Q'}))
assert(not pcall(np.astype,a,'float64',{copy=9}))
assert(not pcall(np.astype,a,'int8',{casting='safe'}))
local f=np.astype(np.array({1.0,2.0,3.0},'float64'),'float32',{casting='same_value'})
assert(f:get(1)==1)
print('dtype92 regression: ok')
