local lr=require('luaray')
local a=lr.asfortranarray(lr.array({{1,2,3},{5,7,11}},'int16'))
for version=1,3 do
  local stream=assert(io.tmpfile())
  lr.save(stream,a,{version=version})
  local end_first=assert(stream:seek())
  lr.save(stream,lr.array(42,'uint8'))
  local end_second=assert(stream:seek())
  assert(stream:seek('set',0)==0)
  local b=lr.load(stream)
  assert(lr.array_equal(a,b) and b.dtype=='int16' and b.flags.f_contiguous)
  assert(stream:seek()==end_first)
  assert(lr.load(stream):item()==42 and stream:seek()==end_second)
  assert(stream:close())
end

local path=os.tmpname()
lr.save(path,lr.array({1,5},'float32'))
local v=lr.load(path..'.npy')
assert(v.dtype=='float32' and v[2]==5)
assert(os.remove(path..'.npy'))
os.remove(path)

local f=assert(io.tmpfile())
lr.save(f,a)
assert(f:seek('set',0)==0)
assert(not pcall(lr.load,f,{max_header_size=1}))
assert(f:seek('set',0)==0)
local prefix=assert(f:read('*a'))
assert(f:close())
f=assert(io.tmpfile())
assert(f:write(prefix:sub(1,-2)))
assert(f:seek('set',0)==0)
assert(not pcall(lr.load,f))
assert(f:close())
assert(not pcall(lr.load,f))
assert(not pcall(lr.save,'unused',{1},{version=4}))
print('NPY regression passed')
