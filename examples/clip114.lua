local np=require('luaray')
local a=np.array({-2,0,4},'float32')
local r=np.clip(a,0,3)
assert(r.dtype=='float32' and r:tolist()[1]==0 and r:tolist()[3]==3)
local out=np.full({3},7,'float32')
assert(rawequal(a:clip(nil,2,{out=out,where=np.array({true,false,true})}),out))
assert(out:tolist()[1]==-2 and out:tolist()[2]==7 and out:tolist()[3]==2)
local bytes=np.array({0,1,255},'uint8')
assert(np.clip(bytes,-999,999).dtype=='uint8')
assert(np.clip(bytes,-999,2.).dtype=='float64')
local duration=np.array({-1,0,4},'timedelta64[h]')
assert(np.astype(np.clip(duration,0,2),'int64'):tolist()[3]==2)
print('clip114 public module example passed')
