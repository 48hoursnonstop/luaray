local np=require('luaray_core')
local rng=np.random.default_rng(42)
local data=rng:bytes(8)
local hex=data:gsub('.',function(c)return string.format('%02x',string.byte(c))end)
print('Random bytes:',hex)
local dst=np.zeros({2,3},'float32')
local values=rng:random(nil,'float32',dst)
assert(values==dst)
print('float32 values:',values:tolist()[1][1], values:tolist()[1][2])
print('next PCG64:',rng:raw_hex())
