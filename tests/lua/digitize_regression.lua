local lr=require('luaray')
local function same(a,expected) assert(table.concat(a:tolist(),',')==expected) end
same(lr.digitize({-1,0,4,10},{0,5,10}),'0,1,1,3')
same(lr.digitize({-1,0,4,10},{0,5,10},true),'0,0,1,2')
same(lr.digitize({-1,0,5,10,11},{10,5,0}),'3,2,1,0,0')
assert(lr.digitize(5,{10,5,0},true)==2)
same(lr.digitize({0,1,2},{}),'0,0,0')
same(lr.digitize({1,2,3},{2,2,2}),'0,3,3')
assert(not pcall(lr.digitize,{1,2},{0,2,1}))
assert(not pcall(lr.digitize,{lr.complex(1,0)},{0,1}))
assert(not pcall(lr.digitize,{1},lr.array({0,1},'longdouble')))
assert(not pcall(lr.digitize,{1},{0,1},'right'))
local mixed=lr.searchsorted(lr.array({0,1,2,10,11},'int32'),lr.array({'0','2','10','11'},'S2'))
same(mixed,'1,3,3,5')
local a=lr.array({'a','abc','z'},'U5')
same(lr.searchsorted(a,lr.array({'aa','zz'},'>U2')),'2,4')
local times=lr.array({lr.timedelta64(1,'D'),lr.timedelta64(3,'D')},'timedelta64[D]')
assert(lr.digitize(times,{0,1,2})[2]==3)
print('Digitize and typed search regression passed')
