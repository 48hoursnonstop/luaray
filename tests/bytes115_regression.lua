local np=require('luaray_core')
local checks=0
local function check(value)checks=checks+1;assert(value)end
local function rejects(fn)check(not pcall(fn))end
local a=np.array({1.,-0.},'float64')
check(a.itemsize==8 and a.nbytes==16)
local bits=a:view('uint64')
check(bits:tolist()[1]==4607182418800017408)
check(np.shares_memory(a,bits) and not rawequal(a,a:view()))
check(a:tobytes()==string.pack('dd',1.,-0.))
check(a:tobytes('k')==a:tobytes('C'))
check(a:tobytes({order='f'})==a:tobytes())
rejects(function()np.array(1.):view('uint8')end)
rejects(function()a:view('S0')end)
rejects(function()a:view('S3')end)
rejects(function()a:view('int64\0')end)
rejects(function()a:view({dtype='int64'})end)
rejects(function()a:view('int64','x')end)
rejects(function()a:tobytes('CF')end)
rejects(function()a:tobytes(true)end)
rejects(function()a:tobytes({['order\0']='C'})end)
rejects(function()a:tobytes({dtype='float64'})end)
local raw=np.zeros({33},'uint8')
local mis=raw:get(np.s(2,34)):view('float64')
mis:set(1.25,1)
check(mis:tolist()[1]==1.25 and raw:tolist()[1]==0)
check(np.add(mis,1.):tolist()[1]==2.25)
check(np.square(mis):tolist()[1]==1.5625)
check(np.sum(mis)==1.25)
check(np.add_accumulate(mis):tolist()[4]==1.25)
check(np.add_reduceat(mis,np.array({1,3},'int64')):tolist()[1]==1.25)
local old=mis:tobytes();raw=nil;collectgarbage('collect')
check(mis:tobytes()==old)
local ro=np.broadcast_to(np.array(1.),{3}):view('int64')
rejects(function()ro:set(7,1)end)
check(ro:tobytes()==string.rep(string.pack('d',1.),3))
rejects(function()np.empty({2,0,3},'uint8'):view('float64')end)
local empty=np.empty({2,0,8},'uint8'):view('float64')
check(empty.nbytes==0 and #empty:tobytes()==0 and empty.shape[3]==1)
print('bytes115 regression: '..checks..' checks passed')
