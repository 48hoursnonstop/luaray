      # for zeros any contiguity is valid, values are empty anyway
      lines.append(f'do local r=np.random.default_rng({seed});local out={init};local v={lmethod};assert(rawequal(v,out),"identity {count}");assert(v.dtype=="{dtype}","dtype {count}");assert(eq(v.shape,{lua(list(shape))},0),"shape {count}");assert(eq(v:tolist(),{expected},{2e-6 if dtype=="float32" else 2e-12}),"values {count}");assert(r:raw_hex()=="{next_word:016x}","PCG {count}") end')
