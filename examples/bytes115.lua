local np=require('luaray')
local a=np.array({1.},'float32')
local bits=a:view('uint32')
assert(bits:tolist()[1]==1065353216 and np.shares_memory(a,bits))
assert(a.itemsize==4 and a.nbytes==4)
assert(a:tobytes()==string.pack('f',1.))
bits:set(0,1)
assert(a:tolist()[1]==0.)
local backing=np.zeros({33},'uint8')
local mis=backing:get(np.s(2,34)):view('float64')
mis:set(1.25,1)
assert(np.square(mis):tolist()[1]==1.5625 and np.sum(mis)==1.25)
backing=nil;collectgarbage('collect')
assert(mis:tolist()[1]==1.25 and #mis:tobytes()==32)
print('bytes115 public module example passed: shared bits, raw bytes and unaligned operations')
