local np=require('luaray')
local a=np.array({-2.5,-.5,.5,2.5},'float32')
local r=np.rint(a)
assert(r.dtype=='float32' and r:tolist()[4]==2)
assert(1/r:tolist()[2]==-math.huge)
local out=np.full({4},99,'float64')
assert(rawequal(np.ceil(a,{out=out,where=np.array({true,false,true,false})}),out))
assert(out:tolist()[1]==-2 and out:tolist()[2]==99 and out:tolist()[3]==1)
local radians=np.deg2rad({0,90,180})
assert(math.abs(radians:tolist()[3]-math.pi)<1e-15)
assert(np.square(3):tolist()==9)
local z=np.conj(np.complex(2,3)):tolist()
assert(z.real==2 and z.imag==-3)
print('unary108 public example passed: rounding, masks, angles and complex values')
