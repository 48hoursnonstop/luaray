local np=require('luaray_core')
local checks=0
local function check(v)checks=checks+1;assert(v)end
local function rejects(fn)check(not pcall(fn))end
check(np.clip(4,1,3):tolist()==3)
check(np.clip({-1,2,4},0,3):tolist()[3]==3)
check(np.array({-1,2,4}):clip(0,3):tolist()[1]==0)
local a=np.array({0,1,255},'uint8')
check(np.clip(a,-999,999).dtype=='uint8')
check(np.clip(a,-999,2.).dtype=='float64')
rejects(function()np.clip(a,999,1000)end)
check(np.clip(a,np.array(0,'int8'),np.array(1,'int8')).dtype=='int16')
local out=np.full({3},7)
check(rawequal(np.clip(a,0,2,{out=out,where=np.array({true,false,true})}),out))
check(out:tolist()[2]==7 and out:tolist()[3]==2)
rejects(function()np.clip()end)
rejects(function()np.clip(nil,0,1)end)
rejects(function()np.clip(a,0,1,4)end)
rejects(function()np.clip(np.array({true,false}),nil,nil)end)
local z=np.array({-0.,0.})
check(np.signbit(np.clip(z,0.,-0.)):tolist()[1])
check(not np.signbit(np.clip(z,0.,-0.)):tolist()[2])
check(np.signbit(np.clip(z,np.array(0.),np.array(-0.))):tolist()[1])
local td=np.array({-1,0,2},'timedelta64[h]')
check(np.astype(np.clip(td,0,1),'int64'):tolist()[3]==1)
rejects(function()np.clip(a,0,1,{dtype='float64'})end)
rejects(function()np.clip(a,0,1,{['out\0']=out})end)
rejects(function()np.clip(a,0,1,{where=true},false)end)
rejects(function()np.clip(a,0,1,out,true,1)end)
rejects(function()np.clip(a,0,1,{where=np.ones({3},'int8')})end)
rejects(function()np.clip(a,0,1,{out=np.zeros({4})})end)
local rank={};for i=1,64 do rank[i]=1 end
local high=np.broadcast_to(np.array(-0.),rank)
check(np.clip(high,0.,1.).ndim==64)
check(np.signbit(np.ravel(np.clip(high,0.,1.))):tolist()[1])
local weak=np.array({0,1},'int8')
check(np.clip(weak,-999,np.array({1.,2.},'float16')).dtype=='float16')
collectgarbage('collect')
print('clip114 regression: '..checks..' checks passed')
