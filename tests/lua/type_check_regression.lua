eq(lr.common_type(single,lr.empty({0},'int8'),lr.ones({1},'complex64')),lr.dtype('complex128'))
eq(lr.common_type(lr.zeros({1},'longdouble'),lr.zeros({1},'complex64')),lr.dtype('clongdouble'))
local duration=lr.zeros({0},'timedelta64[h]');eq(lr.common_type(duration),lr.dtype('float64'))
