#!/usr/bin/env python3
"""Generate frozen independent NumPy differential samples for mvn75.
Oracle generated offline by installed numpy; Lua runtime does not call Python.
"""
import math
import random
from pathlib import Path
import numpy as np

ROOT=Path(__file__).resolve().parent.parent
TESTS=ROOT/'tests'
prng=random.Random(750263)
lines=[]

def lua(v):
    if isinstance(v,(np.integer,int)):
        return str(int(v))
    if isinstance(v,(np.floating,float)):
        f=float(v)
        if math.isnan(f): return '(0/0)'
        if math.isinf(f): return '(math.huge)' if f>0 else '(-math.huge)'
        return repr(f)
    if isinstance(v,(list,tuple)):
        return '{'+','.join(lua(t) for t in v)+'}'
    raise TypeError(type(v))

seeds=[0,1,2,3,7,14,42,127,256,1024,2026,9001,987654,0x7fffffff]
sizes=[None,[],0,1,2,3,[0,2],[2,0],[1,3],[2,3],[2,1,2]]
methods=['svd','eigh','cholesky']
shapes=[]
for n in range(1,7):
    for flavor in ['identity','diagonal','correlated','rankdef','allzero','illconditioned']:
        # separate valid+well-conditioned cases from degenerate ones
        shapes.append((n,flavor))
prng.shuffle(shapes)
for k in range(1020):
    n,flavor=shapes[k%len(shapes)]
    method=methods[(k//3 + k)%3]
    seed=seeds[(k*17 + k//7)%len(seeds)]
    size=sizes[(k*31 + k//13)%len(sizes)]
    local=np.random.default_rng(7500+k)
    mean=local.normal(size=n)
    if k%4==0:
        mean=np.rint(mean).astype(int)
    a=local.normal(size=(n,n))
    if flavor=='identity':
        cov=np.eye(n)*(.01+((k%19)+1)/7)
    elif flavor=='diagonal':
        cov=np.diag(np.arange(1,n+1)/3+0.6)
    elif flavor=='correlated':
        cov=a@a.T+np.eye(n)*0.01
    elif flavor=='rankdef':
        a[:,0]=0
        cov=a@a.T
    elif flavor=='allzero':
        cov=np.zeros((n,n))
    else:
        a[:,0]*=1e-7
        cov=a@a.T
    # LAPACK SVD/eigh can choose different eigenvector bases for degenerate
    # eigenvalues on different vendors; numerical result is still inspected.
    if method=='cholesky' and flavor in ('allzero','rankdef'):
        # singular matrices are intentionally covered as rejection tests elsewhere
        cov+=np.eye(n)*0.01
    # Float32 covariance/mean ndarray cases exercise casting and read paths.
    input_cov=cov.astype(np.float32) if k%7==0 else cov
    input_mean=mean.astype(np.float32) if k%11==0 else mean
    m_arg=f'np.array({lua(input_mean.tolist())}, "float32")' if k%11==0 else lua(input_mean.tolist())
    c_arg=f'np.array({lua(input_cov.tolist())}, "float32")' if k%7==0 else lua(input_cov.tolist())
    g=np.random.default_rng(seed)
    try:
        with np.errstate(invalid='ignore'):
            sampled=g.multivariate_normal(input_mean,input_cov,size=size,method=method)
    except np.linalg.LinAlgError:
        # no sample should be emitted here; test selected invalid cases separately
        continue
    expected=sampled.tolist()
    state=f'{int(g.bit_generator.random_raw()):016x}'
    sample={
        'seed':seed,'method':method,'size':size,'mean':m_arg,'cov':c_arg,
        'expected':lua(expected),'shape':lua(list(sampled.shape)),
        'state':state
    }
    lines.append(f'''do
local g=np.random.default_rng({sample['seed']})
local out=g:multivariate_normal({sample['mean']},{sample['cov']},{'nil' if size is None else lua(size)},'warn',1e-8,'{method}')
assert(out.dtype=='float64','dtype #{k}')
assert(eq(out.shape,{sample['shape']}),'shape #{k}')
assert(close(out:tolist(),{sample['expected']}),'values #{k} {method} {flavor}')
assert(g:raw_hex()=='{state}','PCG64 #{k}')
count=count+1
end''')

prefix='''local np=require('luaray_core')
assert(np._version=='0.75.0-dev')
local function eq(a,b)
 if type(a)~='table' then return a==b end
 if type(b)~='table' or #a~=#b then return false end
 for i=1,#a do if not eq(a[i],b[i]) then return false end end
 return true
end
local function close(a,b)
 if type(a)=='table' then
  if type(b)~='table' or #a~=#b then return false end
  for i=1,#a do if not close(a[i],b[i]) then return false end end
  return true
 end
 if type(a)~='number' or type(b)~='number' then return a==b end
 return math.abs(a-b)<=2e-6*math.max(1,math.abs(a),math.abs(b))
end
local count=0
'''
paths=[]
for i in range(0,len(lines),75):
    p=TESTS/f'mvn75_part_{i//75+1:02}.lua'
    p.write_text(prefix+'\n'.join(lines[i:i+75])+f'\nprint("mvn75 chunk {i//75+1}: "..count.." cases passed")\n')
    paths.append(p)
main=['-- Generated by tools/generate_mvn75_oracle.py, NumPy '+np.__version__]
main.extend(f'dofile("tests/{p.name}")' for p in paths)
main.append(f'print("mvn75: {len(lines)} NumPy differential cases passed")')
(TESTS/'mvn75_differential_generated.lua').write_text('\n'.join(main)+'\n')
print(len(lines),'cases',len(paths),'files',np.__version__)
