local np=require('luaray_core')
local checks=0
local function check(value)checks=checks+1;assert(value)end
local function rejects(fn)check(not pcall(fn))end
local v=np.cross({1,0,0},{0,1,0})
check(v:tolist()[3]==1 and v.dtype=='int64')
rejects(function()np.cross({1,0},{0,1})end)
rejects(function()np.cross()end)
rejects(function()np.cross({1,0,0},nil)end)
rejects(function()np.cross(v,v,{axis=0})end)
rejects(function()np.cross(v,v,{axis=1.0})end)
rejects(function()np.cross(v,v,{['axis\0']=1})end)
rejects(function()np.cross(v,v,{out=v})end)
check(np.cross(v,v,{axis=1,axisa='ignored'}):tolist()[1]==0)
local x=np.array({1.,2.},'float32')
local y=np.array({3,4,5},'int8')
local g=np.meshgrid({x,y})
check(#g==2 and g[1].shape[1]==3 and g[1].shape[2]==2)
check(g[1].dtype=='float32' and g[2].dtype=='int8')
check(g[1]:tolist()[3][2]==2. and g[2]:tolist()[3][2]==5)
check(not np.shares_memory(x,g[1]))
local shared=np.meshgrid({x,y},{copy=false})
check(np.shares_memory(shared[1],x))
shared[1]:set(7.,1,1)
check(x:tolist()[1]==7. and shared[1]:tolist()[3][1]==7.)
local sparse=np.meshgrid({x,y},{copy=false,sparse=true,indexing='ij'})
check(sparse[1].shape[1]==2 and sparse[1].shape[2]==1)
check(sparse[2].shape[1]==1 and sparse[2].shape[2]==3)
check(#np.meshgrid({})==0)
check(np.meshgrid({3})[1]:tolist()[1]==3)
rejects(function()np.meshgrid(x,y)end)
rejects(function()np.meshgrid({x},{copy=1})end)
rejects(function()np.meshgrid({x},{indexing='yx'})end)
rejects(function()np.meshgrid({x},{['indexing\0']='xy'})end)
rejects(function()np.meshgrid({x=x})end)
local inputs={};for i=1,64 do inputs[i]=np.array(i)end
local high=np.meshgrid(inputs,{copy=false,sparse=true})
check(#high==64 and high[64].ndim==64)
inputs[65]=np.array(65)
rejects(function()np.meshgrid(inputs)end)
x=nil;inputs=nil;collectgarbage('collect')
check(shared[1]:tolist()[2][1]==7.)
print('vector116 regression: '..checks..' checks passed')
