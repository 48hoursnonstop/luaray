#!/usr/bin/env python3
"""Independent NumPy 2.3.5 oracle for Generator gamma/beta/chisquare/f broadcasting.
The upstream algorithm reference is NumPy 2.5.3 random/src/distributions.
"""
from pathlib import Path
import numpy as np, math
ROOT=Path(__file__).resolve().parents[1]
R=np.random.default_rng(790079)
names=('gamma','beta','chisquare','f')
targets=((),(1,),(3,),(2,3),(2,1,3))
seeds=(0,1,42,77,1234,32768,981239,998877)
def lit(v):
    if isinstance(v,np.ndarray):return lit(v.tolist())
    if isinstance(v,(tuple,list)):return '{'+','.join(map(lit,v))+'}'
    if v is None:return 'nil'
    if isinstance(v,(np.integer,int)):return str(int(v))
    f=float(v)
    if math.isnan(f):return '(0/0)'
    if math.isinf(f):return '(1/0)' if f>0 else '(-1/0)'
    return repr(f)
def expr(v):
    if isinstance(v,np.ndarray) and R.random()<.65:return 'np.array('+lit(v)+',"'+str(v.dtype)+'")'
    return lit(v)
def param(target,kind):
    if not target or R.random()<.2:
        return round(float(R.uniform(.15,4.0)),4) if kind else float(R.choice([0,1,2,3,.1,.5,1.2,3.3]))
    sh=tuple(1 if R.random()<.48 else d for d in target)
    vals=(np.arange(math.prod(sh),dtype=np.float64).reshape(sh)*.23+.2+R.random())
    if kind==0 and R.random()<.25: vals.flat[0]=0
    return vals
head='''-- Independently generated by tools/generate_random79_oracle.py using NumPy 2.3.5
local np=require('luaray_core')
assert(np._version=='0.79.0-dev')
local cases=0
local function same(a,b)
  if type(a)~=type(b) then return false end
  if type(b)=='table' then
    if #a~=#b then return false end
    for i=1,#b do if not same(a[i],b[i]) then return false end end
    return true
  end
  if type(b)=='number' then
    if a~=a then return b~=b end
    if a==b then return true end
    return math.abs(a-b)<=1e-11*math.max(1,math.abs(b))
  end
  return a==b
end
local function check(ok,why) assert(ok,('random79 case %d: %s'):format(cases,why)) end
'''
lines=[head]
count=0
def append(name,seed,args,luaargs,size):
    global count
    g=np.random.default_rng(seed)
    result=getattr(g,name)(*args,size=size)
    tail='%016x'%int(g.bit_generator.random_raw())
    argtext=','.join(luaargs+[lit(list(size) if size is not None else None)])
    lines.append('do local r=np.random.default_rng(%d);local x=r:%s(%s);cases=cases+1\n'%(seed,name,argtext))
    if isinstance(result,np.ndarray):
        lines.append(' check(type(x)=="userdata","type");check(same(x.shape,%s),"shape");check(same(x:tolist(),%s),"values")\n'%(lit(result.shape),lit(result)))
    else:lines.append(' check(same(x,%s),"scalar")\n'%lit(result))
    lines.append(' check(r:raw_hex()=="%s","PCG64")\nend\n'%tail)
    count+=1
for kind,name in enumerate(names):
    for j in range(180):
        target=targets[int(R.integers(len(targets)))];seed=seeds[(kind+j)%len(seeds)]
        a=param(target,kind)
        args=[a] if name=='chisquare' else [a,param(target,kind if name=='gamma' else 2)]
        size=None if j%5==0 else target if j%3 else (1,)+target
        try:append(name,seed,args,[expr(v) for v in args],size)
        except ValueError as exc:
            if 'size' not in str(exc):raise
    for j in range(80):
        seed=seeds[(kind+j)%len(seeds)]
        dtype=('float64','float32','int64')[j%3]
        orig=np.array([[1,2,3],[4,5,6]],dtype=dtype)
        if j%3==0:
            a=orig.T;ae='np.transpose(np.array('+lit(orig)+',"'+dtype+'"))'
        elif j%3==1:
            a=np.flip(orig,0);ae='np.flip(np.array('+lit(orig)+',"'+dtype+'"),1)'
        else:
            a=np.flip(orig,1);ae='np.flip(np.array('+lit(orig)+',"'+dtype+'"),2)'
        args=[a] if name=='chisquare' else [a,.75]
        las=[ae] if name=='chisquare' else [ae,lit(.75)]
        size=None if j%2 else (2,)+a.shape
        append(name,seed,args,las,size)
lines.append('print("random79 differential passed: %d cases")\n'%count)
p=ROOT/'tests/random79_differential_generated.lua';p.write_text(''.join(lines))
print('NumPy',np.__version__,count,'cases',p.stat().st_size,'bytes')
