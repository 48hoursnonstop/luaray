local np=require('luaray_core')
assert(np._version=='0.100.0-dev')
local checked=0
local function rejected(fn)
 local r=np.random.default_rng(830083)
 local reference=np.random.default_rng(830083)
 local ok=pcall(function() fn(r) end)
 assert(not ok, 'expected argument failure '..(checked+1))
 assert(r:raw_hex()==reference:raw_hex(),'invalid argument consumed PCG64')
 checked=checked+1
end
rejected(function(r) r:geometric({.5,0}) end)
rejected(function(r) r:geometric({.5,0},{0,2}) end)
rejected(function(r) r:geometric({.5,-.1}) end)
rejected(function(r) r:geometric({.5,1.1}) end)
rejected(function(r) r:geometric({.5,0/0}) end)
rejected(function(r) r:geometric({.5,1/0}) end)
rejected(function(r) r:geometric({.5,-1/0}) end)
rejected(function(r) r:geometric({.1,.2},{3}) end)
rejected(function(r) r:geometric(np.array({{.2,.3},{.4,.5}}),{4}) end)
rejected(function(r) r:poisson({.2,-1}) end)
rejected(function(r) r:poisson({.2,-1},{0,2}) end)
rejected(function(r) r:poisson({0,0/0}) end)
rejected(function(r) r:poisson({0,1/0}) end)
rejected(function(r) r:poisson({0,1e13}) end)
rejected(function(r) r:poisson({.1,.2},{3}) end)
rejected(function(r) r:poisson(np.array({{1,2},{3,4}}),{4}) end)
local r=np.random.default_rng(83)
local g=r:geometric(np.flip(np.array({.2,.4,.8}),1))
assert(g.dtype=='int64' and g.shape[1]==3)
local p=r:poisson(np.transpose(np.array({{.1,10.0}})),{3,2,1})
assert(p.dtype=='int64' and p.shape[1]==3 and p.shape[2]==2 and p.shape[3]==1)
local empty=r:poisson({1,5},{0,2})
assert(empty.dtype=='int64' and empty.shape[1]==0 and empty.shape[2]==2)
assert(type(r:geometric(np.array(.5)))=='number')
assert(type(r:poisson(np.array(7.)))=='number')
local a=np.random.default_rng(123):geometric(.5,{20000}):tolist()
local total=0
for i=1,#a do assert(a[i]>=1 and a[i]==math.floor(a[i]));total=total+a[i] end
assert(math.abs(total/#a-2.0)<.08)
local b=np.random.default_rng(456):poisson(10.,{20000}):tolist()
local mean=0
for i=1,#b do assert(b[i]>=0 and b[i]==math.floor(b[i]));mean=mean+b[i] end
assert(math.abs(mean/#b-10.0)<.25)
print('random83 regressions: '..checked..' rejected cases, 40000 statistical samples, shapes/views passed')
