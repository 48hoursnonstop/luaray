local n=require('luaray_core')
assert(n._version=='0.128.0-dev')
local function same(a,b)
 if type(a)=='table' then
  assert(type(b)=='table' and #a==#b)
  for i=1,#a do same(a[i],b[i]) end
 else
  assert(a==b or (type(a)=='number' and type(b)=='number' and a~=a and b~=b),tostring(a)..' != '..tostring(b))
 end
end
local function reject(f) assert(not pcall(f),'expected rejection') end
local a=n.array({{3,1,9},{-2,5,4}},n.int64)
assert(n.argmin(a)==4 and n.argmax(a)==3 and n.ptp(a)==11)
same(n.argmin(a,{axis=1}):tolist(),{2,1,2})
same(n.argmax(a,{axis=2,keepdims=true}):tolist(),{{3},{2}})
same(n.ptp(a,{axis=1}):tolist(),{5,4,5})
assert(n.argmin(a,2,{keepdims=true}).shape[2]==1)
local trans=n.transpose(a)
same(n.argmin(trans,{axis=2}):tolist(),{2,1,2})
local x=n.array({3,1,3,1},n.int64)
assert(n.argmin(x)==2 and n.argmax(x)==1)
local inf=n.array({0/0,100,-100,0/0},n.float64)
assert(n.argmin(inf)==1 and n.argmax(inf)==1)
local u=n.array({1,5,9},n.uint8)
assert(n.ptp(u)==8)
local small=n.array({-120,120},n.int8)
assert(n.ptp(small)==-16)
local dest=n.flip(n.zeros({3},n.int32))
assert(n.argmin(a,{axis=1,out=dest})==dest)
same(dest:tolist(),{2,1,2})
local d=n.flip(n.zeros({3},n.int64))
assert(n.ptp(a,{axis=1,out=d})==d)
same(d:tolist(),{5,4,5})
local src=n.array({{3,9,2},{10,-1,8}},n.int64)
local alias=src:get(1) -- first row shared with source
assert(n.ptp(src,{axis=1,out=alias})==alias)
same(alias:tolist(),{7,10,6})
local empty=n.reshape(n.array({},n.int64),{0,3})
assert(n.argmin(empty,{axis=2}).shape[1]==0)
reject(function() return n.argmin(empty) end)
reject(function() return n.argmax(n.reshape(n.array({},n.int64),{3,0}),{axis=2}) end)
reject(function() return n.argmin(a,{axis={1}}) end)
reject(function() return n.argmax(a,{where=false}) end)
reject(function() return n.ptp(a,{where=false}) end)
reject(function() return n.ptp(n.array({true,false},n.bool)) end)
reject(function() return n.argmax(a,{out=n.zeros({2},n.float64)}) end)
reject(function() return n.argmin(a,{out=n.zeros({2},n.int64)}) end)
reject(function() return n.ptp(a,{out=n.zeros({3},n.float64)}) end)
assert(n.argmin(n.reshape(n.array({5},n.int64),{}))==1)
print('selection regression: ok')
