local np=require('luaray_core')
local checks=0
local function check(v)checks=checks+1;assert(v)end
local function rejects(fn)check(not pcall(fn))end
for _,name in ipairs({'round','around'})do
 check(np[name](2.5):tolist()==2)
 check(np[name]({1.25,2.5},1):tolist()[1]==1.2)
 local out=np.empty({2})
 check(rawequal(np[name]({1.25,2.5},{decimals=1,out=out}),out))
 check(out:tolist()[1]==1.2)
 rejects(function()np[name]()end)
 rejects(function()np[name](np.array({1}),1.0)end)
 rejects(function()np[name]({1},2147483648)end)
 rejects(function()np[name]({1},-2147483649)end)
 rejects(function()np[name]({1},{['decimals\0']=1})end)
 rejects(function()np[name]({1},{['out\0']=out})end)
 rejects(function()np[name]({1},{where=true})end)
 rejects(function()np[name]({1},0,3)end)
 rejects(function()np[name]({1},{out=out},out)end)
end
local a=np.array({15,25},'int64')
check(a:round(-1):tolist()[1]==20 and a:round(-1):tolist()[2]==20)
check(not np.shares_memory(a,a:round(0)))
local ro=np.broadcast_to(np.array(1),{3})
check(rawequal(np.round(ro,0,ro),ro))
check(np.round(np.array({true,false}),0).dtype=='float16')
rejects(function()np.round(np.array({true,false}),1)end)
local z=np.array({np.complex(1.25,2.5)},'complex64')
local out=np.zeros({1},'float64')
rejects(function()np.round(z,0,out)end)
check(out:tolist()[1]==1 and z:tolist()[1].real==1.25)
check(np.round(z,1,np.empty({1},'complex128')):tolist()[1].real==1.2000000476837158)
check(np.round(np.array(1),2147483647):tolist()==1) -- integer fast-copy path
local td=np.array({1,2},'timedelta64[h]')
rejects(function()np.round(td,1,td)end)
check(np.astype(td,'int64'):tolist()[1]==100)
local method=np.array({1,2},'timedelta64[h]')
rejects(function()method:round(1,method)end)
check(np.astype(method,'int64'):tolist()[1]==10)
check(np.astype(np.multiply(method,.5),'int64'):tolist()[1]==5)
check(np.astype(np.true_divide(method,2.0),'int64'):tolist()[2]==10)
check(np.astype(np.multiply(np.array({2.0},'longdouble'),method),'int64'):tolist()[2]==40)
print('round113 regression: '..checks..' checks passed')
