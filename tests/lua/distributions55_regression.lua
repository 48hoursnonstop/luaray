local np=require('luaray_core')
assert(np._version=='0.125.0-dev')
local r=np.random.default_rng(42)
assert(r:lognormal()==1.3562412406168636)
assert(r:raw_hex()=='705a5661a791ffc1')
r:reseed(42)
assert(r:standard_cauchy()==-0.2930016698581793)
assert(r:raw_hex()=='dbcd12c26eda1624')
r:reseed(42)
assert(r:laplace(-2,.75)==-1.4045910180187198)
assert(r:raw_hex()=='705a5661a791ffc1')
r:reseed(42)
local x=r:lognormal(.5,1.5,{2,3})
assert(x.dtype=='float64' and x.shape[1]==2 and x.shape[2]==3)
assert(x:get(1,1)>0)
local y=np.random.default_rng(42):standard_cauchy(4)
assert(y.dtype=='float64' and y.shape[1]==4)
local z=np.random.default_rng(42):laplace(0,1,{2,0,3})
assert(z.shape[2]==0)
local scalar=np.random.default_rng(42):laplace(0,1,{})
assert(scalar.dtype=='float64')
local empty=np.random.default_rng(42):lognormal(0,1,0)
assert(empty.shape[1]==0)
print('distributions55 regression passed')
