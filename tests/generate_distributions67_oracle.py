"""Regenerate deterministic Lua oracle fixtures from installed NumPy (test-time only)."""
from pathlib import Path
import numpy as np
p=Path(__file__).resolve().parents[1]
seeds=[0,1,2,17,42,1234,2**32-1,2**63-1]
colorsets=[[],[0],[1],[0,0,0],[1,0,0],[0,1,0],[1,1],[2,3],[3,4,5],[15,15,10],[25,50,100],[0,0,5,0],[80,20,25,5],[150,250,100,300],[500000,400000,100000]]
sizes=[None,(),(0,),(1,),(2,3)]
methods=['marginals','count']
def form(s):return 'nil' if s is None else '{'+','.join(map(str,s))+'}'
def cols(s):return '{'+','.join(map(str,s))+'}'
def rhex(r):return format(int(r.bit_generator.random_raw()),'016x')
lines=['-- Generated by tests/generate_distributions67_oracle.py using NumPy '+np.__version__,
       'local np=require("luaray_core")','assert(np._version=="0.68.0-dev")',
       'local checks=0','local function eq(a,b) assert(a==b,("comparison %d: %s ~= %s"):format(checks,tostring(a),tostring(b))); checks=checks+1 end']
for seed in seeds:
 for colors in colorsets:
  tot=sum(colors)
  samples=sorted(set([0,1,tot//2,max(0,tot-1),tot])) if tot < 1000 else [0,1,tot//2,tot]
  for n in samples:
   if n>tot:continue
   for method in methods:
    for size in sizes:
     r=np.random.default_rng(seed)
     out=r.multivariate_hypergeometric(colors,n,size=size,method=method)
     # Sometimes use a native ndarray for colors; exercise both input paths.
     usearray = ((seed+n+len(colors))%3==0)
     lua_col=('np.array('+cols(colors)+',"int64")') if usearray and colors else cols(colors)
     lines.append(f'do local r=np.random.default_rng({seed}); local v=r:multivariate_hypergeometric({lua_col},{n},{form(size)},"{method}")')
     lines.append('eq(v.dtype,"int64")')
     lines.append(f'eq(#v.shape,{out.ndim})')
     for i,d in enumerate(out.shape):lines.append(f'eq(v.shape[{i+1}],{d})')
     for ix in np.ndindex(out.shape):
      args=','.join(str(t+1) for t in ix)
      lines.append(f'eq(v:get({args}),{int(out[ix])})')
     lines.append(f'eq(r:raw_hex(),"{rhex(r)}") end')
# Interleaved draws: verify state advancing when sampling multiple vectors.
for seed in seeds:
 r=np.random.default_rng(seed)
 lines.append(f'do local r=np.random.default_rng({seed})')
 for colors,n,meth in [([12,20,7],8,'marginals'),([3,7,20],12,'count'),([15,10],14,'marginals'),([1,2,3,4],6,'count')]:
  expected=r.multivariate_hypergeometric(colors,n,method=meth)
  lines.append(f'local z=r:multivariate_hypergeometric({cols(colors)},{n},nil,"{meth}")')
  for i,v in enumerate(expected):lines.append(f'eq(z:get({i+1}),{int(v)})')
  lines.append(f'eq(r:random(),{repr(float(r.random()))})')
 lines.append(f'eq(r:raw_hex(),"{rhex(r)}") end')
# Failed calls should not mutate state.
invalid=[('{1,2,3}',7,'nil','"marginals"'),('{1,-1,2}',1,'nil','"marginals"'),('{1,2.5,3}',2,'nil','"count"'),('{1,2,3}',-1,'nil','"count"'),('{1,2,3}',1,'nil','"other"'),('{600000000,400000000}',1,'nil','"marginals"'),('np.array({1,2,3},"float64")',1,'nil','"count"')]
for seed in [0,42]:
 for c,n,size,method in invalid:
  r=np.random.default_rng(seed)
  lines.extend([f'do local r=np.random.default_rng({seed})',f'local ok=pcall(function() r:multivariate_hypergeometric({c},{n},{size},{method}) end)','eq(ok,false)',f'eq(r:raw_hex(),"{rhex(r)}") end'])
lines.append('print("distributions67 differential passed",checks,"checks")')
(p/'tests/distributions67_differential_generated.lua').write_text('\n'.join(lines)+'\n')
print('NumPy',np.__version__,'fixture lines:',len(lines))
