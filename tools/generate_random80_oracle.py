#!/usr/bin/env python3
"""Differential fixture generator for LuaRay 0.80 from installed NumPy.
Pinned source reference: NumPy 2.5.3 distributions.c and _generator.pyx.
Requires NumPy at fixture generation time, never for running LuaRay.
"""
from pathlib import Path
import numpy as np, math
ROOT=Path(__file__).resolve().parents[1]
R=np.random.default_rng(800080)
seeds=[0,1,42,1234,781,90210,2**32-1]
shapes=[(),(1,),(2,),(3,),(2,3),(2,1,3),(1,2,3)]
values=[0.,1e-5,.1,.5,.999999,1.,1.0001,2.,3.3,10.,50.,1000.]
def lit(v):
 if isinstance(v,np.ndarray):return lit(v.tolist())
 if isinstance(v,(tuple,list)):return '{'+','.join(map(lit,v))+'}'
 if v is None:return 'nil'
 if isinstance(v,(int,np.integer)):return str(int(v))
 f=float(v)
 if math.isnan(f):return '(0/0)'
 if math.isinf(f):return '(1/0)' if f>0 else '(-1/0)'
 return repr(f)
def argexpr(a,kind):
 if kind=='table':return lit(a)
 if kind=='arr32':return 'np.array('+lit(a)+',"float32")'
 if kind=='arr64':return 'np.array('+lit(a)+',"float64")'
 if kind=='int':return 'np.array('+lit(a)+',"int64")'
 if kind=='transpose':return 'np.transpose(np.array('+lit(a.T)+',"float64"))'
 if kind=='flip':return 'np.flip(np.array('+lit(np.flip(a,axis=-1))+',"float32"),'+str(a.ndim)+')'
 return lit(a)
head='''-- Generated by tools/generate_random80_oracle.py against NumPy %s
local np=require('luaray_core')
assert(np._version=='0.82.0-dev')
local cases=0
local function close(a,b,eps)
 if type(a)~=type(b) then return false end
 if type(b)=='table' then
  if #a~=#b then return false end
  for i=1,#b do if not close(a[i],b[i],eps) then return false end end
  return true
 end
 if type(b)=='number' then
  if a~=a then return b~=b end
  if a==b then return true end
  return math.abs(a-b)<=eps*math.max(1,math.abs(b))
 end
 return a==b
end
local function verify(got,expected_shape,expected,dtype,tail)
 cases=cases+1
 assert(type(got)=='userdata',('case %%d type'):format(cases))
 assert(close(got.shape,expected_shape,0),('case %%d shape'):format(cases))
 assert(got.dtype==dtype,('case %%d dtype: %%s vs %%s'):format(cases,tostring(got.dtype),dtype))
 local eps=dtype=='float32' and 2e-6 or 2e-12
 assert(close(got:tolist(),expected,eps),('case %%d values'):format(cases))
end
'''%np.__version__
lines=[head]
count=0
for i in range(1000):
 kind=['table','arr32','arr64','int','transpose','flip'][i%6]
 shape=shapes[int(R.integers(0,len(shapes)))]
 if kind in ('transpose','flip') and len(shape)<2: shape=(2,3)
 if kind=='table' and shape in ((),(0,),(0,3)):shape=(2,3)
 if kind=='int': dtype_array=np.int64
 elif kind in ('flip','arr32'):dtype_array=np.float32
 else:dtype_array=np.float64
 a=R.choice(values,size=shape).astype(dtype_array)
 if kind=='int':a=a.astype(np.int64)
 if kind=='table': a=np.asarray(a,dtype=np.float64)
 if kind=='transpose': a=a.T.T # display expression using T of T, preserves desired a
 if kind=='flip': a=np.flip(a,axis=-1)
 arg=argexpr(a,kind)
 # Tensor parameter dimensions must be compatible with explicit size.
 size=(0,)+a.shape if i%11==0 else None if i%4==0 else (1,)+a.shape if i%4==1 else a.shape if i%4==2 else (2,)+a.shape
 dtype='float32' if i%2==0 else 'float64'
 # np.float32 over integer dtype etc
 r=np.random.default_rng(seeds[(i//6)%len(seeds)])
 try: v=r.standard_gamma(a,size=size,dtype=dtype)
 except ValueError as ex:
  if 'size' in str(ex):continue
  raise
 tail='%016x'%int(r.bit_generator.random_raw())
 if isinstance(v,np.ndarray):
  lines.append('do local r=np.random.default_rng(%d);local v=r:standard_gamma(%s,%s,"%s");verify(v,%s,%s,"%s");assert(r:raw_hex()=="%s","PCG case %d") end\n'%(
   seeds[(i//6)%len(seeds)],arg,lit(list(size) if size is not None else None),dtype,lit(v.shape),lit(v),dtype,tail,i))
 else:
  lines.append('do local r=np.random.default_rng(%d);local v=r:standard_gamma(%s,%s,"%s");assert(close(v,%s,%s),"scalar case %d");assert(r:raw_hex()=="%s","PCG case %d") end\n'%(seeds[(i//6)%len(seeds)],arg,lit(list(size) if size is not None else None),dtype,lit(v),2e-6 if dtype=='float32' else 2e-12,i,tail,i))
 count+=1
lines.append('print("random80 differential passed: %d cases")\n'%count)
p=ROOT/'tests/random80_differential_generated.lua'
p.write_text(''.join(lines));print('NumPy',np.__version__,count,'cases',p.stat().st_size,'bytes')
