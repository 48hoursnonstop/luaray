local np=require('luaray_core')
local checks=0
local function check(v)checks=checks+1;assert(v)end
for _,dt in ipairs({'complex64','complex128','clongdouble'})do
 local a=np.array({np.complex(1,0),np.complex(2,1)},dt)
 check(np.iscomplexobj(a) and not np.isrealobj(a))
 check(np.isreal(a):tolist()[1] and not np.isreal(a):tolist()[2])
 check(not np.iscomplex(a):tolist()[1] and np.iscomplex(a):tolist()[2])
 check(rawequal(np.real_if_close(a),a))
 local ro=np.broadcast_to(a:get(np.s(1,2)),{3})
 local real=np.real_if_close(ro)
 check(not np.iscomplexobj(real) and np.shares_memory(real,a))
 check(not pcall(function()np.copyto(real,9,'unsafe')end))
 check(not pcall(function()np.real_if_close(a,'bad')end))
 check(not pcall(function()np.real_if_close(a,np.array(3))end))
end
for _,name in ipairs({'isreal','iscomplex','isrealobj','iscomplexobj','real_if_close'})do
 check(not pcall(function()np[name]()end))
 check(np[name]({1,2,3})~=nil)
end
local a=np.array({np.complex(1,1e-6)},'complex64')
check(np.real_if_close(a).dtype=='float32')
check(rawequal(np.real_if_close(a,1e-12),a))
check(np.real_if_close(a,.1).dtype=='float32')
local real=np.array({1,2})
check(rawequal(np.real_if_close(real,'ignored'),real))
check(np.isrealobj({1,2}) and not np.iscomplexobj({1,2}))
check(np.isreal(np.array({'x'},'U3')):tolist()[1]==false)
check(np.isreal(np.array({0},'datetime64[D]')):tolist()[1]==false)
check(np.isreal(np.array({0},'timedelta64[D]')):tolist()[1]==true)
check(np.iscomplex(np.complex(1,0/0)):tolist())
check(np.isreal(np.complex(0/0,0)):tolist())
check(np.real_if_close(np.empty({0},'complex64'),-1).dtype=='float32')
local cast=np.astype(np.array({'(1-4e-4951j)','(1+0.5000000000000000001j)'}),'clongdouble')
check(cast:tolist()[1].imag==0)
check(np.equal(cast.imag:get(np.s(2,3)),np.array(.5,'longdouble')):tolist()[1])
check(np.astype(np.array({'1+j'}),'complex128'):tolist()[1].imag==1)
check(np.astype(np.array({' ( 1+2j ) '}),'complex128'):tolist()[1].real==1)
check(np.astype(np.array({'1e5000+2j'}),'complex128'):tolist()[1].real==math.huge)
check(not pcall(function()np.astype(np.array({'1\0x'}),'float64')end))
check(not pcall(function()np.astype(np.array({'1\0x'}),'int64')end))
check(np.astype(np.array({'1\0x'}),'bool'):tolist()[1])
collectgarbage('collect')
print('predicates112 regression: '..checks..' checks passed')
