local lr = require('luaray')

local a = lr.array({{2,3},{4,5}},'int8')
local sum = lr.cumulative_sum(a,{axis=-1,include_initial=true})
assert(sum.dtype == 'int64' and sum.shape[2] == 3)
assert(sum[1][1] == 0 and sum[1][3] == 5 and sum[2][3] == 9)
local prod = lr.cumulative_prod(7,{include_initial=true})
assert(prod.shape[1] == 2 and prod[1] == 1 and prod[2] == 7)
local empty = lr.cumulative_prod(lr.empty({2,0,3},'float32'),{axis=2,include_initial=true})
assert(empty.dtype == 'float32' and empty.size == 6 and lr.all(lr.equal(empty,1)))

local backing = lr.full({2,6},-1,'int32')
local out = backing:get(lr.s(),lr.s(nil,nil,2))
assert(rawequal(lr.cumulative_prod(a,{axis=2,include_initial=true,out=out}),out))
assert(out[1][1] == 1 and out[1][3] == 6 and out[2][3] == 20)
assert(backing[1][2] == -1 and backing[2][6] == -1)

local text = lr.full({2,3},'0','S5')
assert(rawequal(lr.cumulative_sum(a,{axis=2,include_initial=true,dtype='int64',out=text}),text))
assert(text[1][1] == '0' and text[1][3] == '5')
text:set('bad',2,2)
local unchanged = text:tobytes()
assert(not pcall(lr.cumulative_sum,a,{axis=2,include_initial=true,dtype='int64',out=text}))
assert(text:tobytes() == unchanged)

assert(not pcall(lr.cumulative_sum,a))
assert(not pcall(lr.cumulative_sum,a,{axis=0}))
assert(not pcall(lr.cumulative_prod,a,{axis=2,include_initial='yes'}))
assert(not pcall(lr.cumulative_prod,a,{axis=2,include_initial=true,out=lr.empty({1,3})}))
out:setflags(false)
assert(not pcall(lr.cumulative_prod,a,{axis=2,include_initial=true,out=out}))
print('Array API cumulative regression passed')
