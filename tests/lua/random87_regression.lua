local np=require('luaray_core')
assert(np._version=='0.156.0-dev')
local invalid_count=0
local function invalid(fn)
  local r=np.random.default_rng(870087)
  local ref=np.random.default_rng(870087)
  assert(not pcall(function()fn(r)end),'invalid did not raise #'..(invalid_count+1))
  assert(r:raw_hex()==ref:raw_hex(),'invalid advanced PCG64 #'..(invalid_count+1))
  invalid_count=invalid_count+1
end
invalid(function(r)r:zipf({1,2})end)
invalid(function(r)r:zipf({1,2},{0,2})end)
invalid(function(r)r:zipf({2,0.9})end)
invalid(function(r)r:zipf({2,(0/0)})end)
invalid(function(r)r:zipf(np.flip(np.array({2,1}),1))end)
invalid(function(r)r:zipf({1,2,3},{2,2})end)
invalid(function(r)r:zipf({1,2,3},{0,3})end)
invalid(function(r)r:hypergeometric({5,-1},5,1)end)
invalid(function(r)r:hypergeometric({5,-1},5,1,{0,2})end)
invalid(function(r)r:hypergeometric({5,1000000000},5,1)end)
invalid(function(r)r:hypergeometric({5,6},{5,-1},1)end)
invalid(function(r)r:hypergeometric({5,6},{5,6},{1,13})end)
invalid(function(r)r:hypergeometric({5,6},{5,6},{1,13},{0,2})end)
invalid(function(r)r:hypergeometric({5,6},{5,6},{1,2,3})end)
invalid(function(r)r:hypergeometric(np.array({5.0,6.0},'float64'),5,1)end)
invalid(function(r)r:hypergeometric(5,np.array({5.0,6.0},'float32'),1)end)
invalid(function(r)r:hypergeometric(5,5,np.array({1.0,2.0},'float64'))end)
invalid(function(r)r:hypergeometric({5,6},{5,6},{1,2},{3,3})end)
invalid(function(r)r:hypergeometric({5,6},{5,6},{1,2,3},{0,3})end)
local r=np.random.default_rng(8701)
local a=r:zipf({{1.1},{2},{5}},{3,4})
assert(a.dtype=='int64' and a.shape[1]==3 and a.shape[2]==4)
local b=r:hypergeometric({{5},{10}},{{6,7,8}},2)
assert(b.dtype=='int64' and b.shape[1]==2 and b.shape[2]==3)
local c=r:hypergeometric(np.flip(np.array({10,20,30},'int64'),1),10,5)
assert(c.shape[1]==3)
local d=r:zipf(np.transpose(np.array({{2,3},{4,5}},'float64')))
assert(d.shape[1]==2 and d.shape[2]==2)
local e=r:zipf({1.5,2.5},{0,2})
assert(e.shape[1]==0 and e.shape[2]==2)
local f=r:hypergeometric({5,10},{6,11},1,{0,2})
assert(f.shape[1]==0 and f.shape[2]==2)
local s=r:hypergeometric(np.array(5,'int64'),np.array(6,'int64'),np.array(1,'int64'))
assert(type(s)=='number')
local fraction=r:hypergeometric({-0.2,1.9}, {5.1,0.9}, {1.1,1.8})
assert(fraction.dtype=='int64' and fraction.shape[1]==2)
local n=10000
local h=np.random.default_rng(877):hypergeometric(40,60,20,{n}):tolist()
local sum=0
for _,v in ipairs(h) do assert(v>=0 and v<=20);sum=sum+v end
assert(math.abs(sum/n-8)<.2)
local z=np.random.default_rng(878):zipf(3,{n}):tolist()
local zsum=0
for _,v in ipairs(z) do assert(v>=1);zsum=zsum+v end
assert(zsum/n>1.2 and zsum/n<1.6)
print('random87 regression: '..invalid_count..' rejection tests, 20000 statistical samples, views and shapes passed')
