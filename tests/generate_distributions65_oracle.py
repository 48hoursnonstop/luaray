from pathlib import Path
import numpy as np, math
p=Path(__file__).resolve().parents[1]
seeds=[0,1,2,42,123456,2**32-1,2**32,2**63-1]
params=[np.nextafter(1.,2.),1.000000001,1.01,1.05,1.1,1.2,1.5,2.,2.5,3.,5.,10.,100.,1024.,1025.,1026.,1e7,math.inf]
sizes=[None,(),(0,),(1,),(2,3),(10,),(32,)]
def f(x):return 'math.huge' if math.isinf(x) else repr(float(x))
def shape(s):return 'nil' if s is None else '{'+','.join(map(str,s))+'}'
def raw(r):return format(int(r.bit_generator.random_raw()),'016x')
L=['-- Generated by tests/generate_distributions65_oracle.py, NumPy '+np.__version__, 'local np=require("luaray_core")', 'assert(np._version=="0.66.0-dev")','local total=0','local function eq(a,b) assert(a==b,("case %d: %s ~= %s"):format(total,tostring(a),tostring(b)));total=total+1 end']
for seed in seeds:
 for a in params:
  for s in sizes:
   r=np.random.default_rng(seed)
   out=r.zipf(a,size=s)
   nextword=raw(r)
   L.append(f'do local r=np.random.default_rng({seed}); local v=r:zipf({f(a)},{shape(s)})')
   if s is None: L.append('eq(v,'+str(int(out))+')')
   else:
    L.append('eq(v.dtype,"int64")')
    L.append(f'eq(#v.shape,{len(s)})')
    for i,d in enumerate(s): L.append(f'eq(v.shape[{i+1}],{d})')
    for ix in np.ndindex(out.shape):
     index=','.join(str(i+1) for i in ix)
     L.append(f'eq(v:get({index}),{int(out[ix])})')
   L.append(f'eq(r:raw_hex(),"{nextword}") end')
# mixed consumption
for seed in seeds:
 for series in [(1.5,4.,1025.,2.5),(1.1,3.,1.01,1000.),(math.inf,1024.,1.2,5.)]:
  r=np.random.default_rng(seed)
  L.append(f'do local r=np.random.default_rng({seed})')
  for a in series:
   L.append(f'eq(r:zipf({f(a)}),{int(r.zipf(a))})')
   L.append(f'eq(r:integers(0,1000),{int(r.integers(0,1000))})')
   L.append(f'eq(r:random(),{repr(float(r.random()))})')
  L.append(f'eq(r:raw_hex(),"{raw(r)}") end')
# invalid values rejected before RNG use
for bad in [float('nan'),-math.inf,-2.,0.,1.]:
 txt='(0/0)' if math.isnan(bad) else '-math.huge' if bad==-math.inf else f(bad)
 for seed in seeds:
  r=np.random.default_rng(seed)
  L.extend([f'do local r=np.random.default_rng({seed})',f'local ok=pcall(function()r:zipf({txt})end)', 'eq(ok,false)',f'eq(r:raw_hex(),"{raw(r)}") end'])
L.append('print("distributions65 differential passed",total,"checks")')
(p/'tests/distributions65_differential_generated.lua').write_text('\n'.join(L)+'\n')
print('Generated',len(L),'lines')
