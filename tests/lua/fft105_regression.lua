local np=require('luaray_core')
local checks=0
local function eq(a,b)
 checks=checks+1
 if type(b)=='table' then assert(type(a)=='table' and #a==#b);for i=1,#b do eq(a[i],b[i]) end
 else assert(a==b,tostring(a)..' != '..tostring(b)) end
end
local function fails(fn,fragment)
 checks=checks+1;local ok,err=pcall(fn);assert(not ok,'expected FFT rejection')
 if fragment then assert(tostring(err):find(fragment,1,true),tostring(err)) end
end
local f=np.fft
eq(f.fftfreq(5,.5):tolist(),{0,.4,.8,-.8,-.4})
eq(f.rfftfreq(4,.5):tolist(),{0,.5,1})
eq(f.rfftfreq(-1).size,0)
fails(function()f.fftfreq(-1)end)
fails(function()f.fftfreq(0)end,'division by zero')
fails(function()f.rfftfreq(0)end,'division by zero')
fails(function()f.fftfreq(true)end)
eq(f.rfftfreq(true):tolist(),{0})
fails(function()f.fftfreq(2.5)end)
fails(function()f.fftfreq(4,{.5})end)
fails(function()f.fftfreq(4,.5,1)end)
local typed=f.rfftfreq(0,np.array(.5,'float32'))
eq(typed.size,1);checks=checks+1;assert(typed:get(1)~=typed:get(1))
eq(f.fftfreq(4,np.array(.5,'float32')).dtype,'float64')
local a=np.array({0,1,2,3,4},'int32')
eq(f.fftshift(a):tolist(),{3,4,0,1,2})
eq(f.ifftshift(a):tolist(),{2,3,4,0,1})
eq(f.ifftshift(f.fftshift(a)):tolist(),a:tolist())
eq(f.fftshift(a,{1,1}):tolist(),{1,2,3,4,0})
local copy=f.fftshift(a,{})
eq(copy:tolist(),a:tolist());eq(np.shares_memory(copy,a),false)
eq(f.fftshift(a,-1):tolist(),{3,4,0,1,2})
fails(function()f.fftshift(np.array(1))end)
fails(function()f.fftshift(a,0)end)
fails(function()f.fftshift(a,{true})end)
fails(function()f.fftshift(a,{2})end)
fails(function()f.fftshift(a,1,1)end)
-- Zero-stride KEEPORDER regression: axis with zero byte stride sorts first.
local broad=np.broadcast_to(np.array({{1,2,3,4}},'int32'),{3,4})
eq(f.fftshift(broad).strides,{4,12})
local h=f.hfft({1,2,3})
eq(h:tolist(),{8,-2,0,-2})
local inv=f.ihfft(h)
eq(inv.shape,{3});eq(inv:get(2).real,2);eq(inv:get(2).imag,0)
eq(f.hfft({1,2,3},{norm='forward'}):tolist(),{2,-.5,0,-.5})
eq(f.ihfft({8,-2,0,-2},{norm='forward'}):get(2).real,8)
-- Exact expected float32 computation, even when the destination is complex128.
local input=np.array({1.25,-2.5,3.75,.125},'float32')
local wide=np.zeros({2},'complex128')
eq(f.ihfft(input,3,1,'ortho',wide),wide)
eq(wide:get(1).real,1.4433755874633789)
local cout=np.zeros({3},'complex128')
f.fft(np.astype(input,'complex64'),3,1,'ortho',cout)
eq(cout:get(1).real,1.4433755874633789)
-- Half normalization remains half, without a second half rounding of out.
local hout=np.zeros({3},'float32')
f.hfft(np.astype(input,'float16'),{n=3,norm='ortho',out=hout})
eq(hout:get(1),-2.164306640625)
local readonly=np.broadcast_to(np.array({0},'float64'),{4})
fails(function()f.hfft({1,2,3},{out=readonly})end,'read-only')
eq(readonly:tolist(),{0,0,0,0})
local invalid=np.array({'x','y','z'},'U4')
for _,name in ipairs({'fft','ifft','rfft','irfft','hfft','ihfft'}) do
 fails(function()f[name](invalid,{n=3,norm='ortho',out=np.zeros({3},'complex128')})end)
end
local matrix=np.array({{1,2,3},{4,5,6}},'float64')
local x=f.fft(matrix,nil,1,'forward')
eq(x.shape,{2,3});eq(x:get(1,2).real,3.5)
fails(function()f.hfft({1,2},0)end)
fails(function()f.ihfft({1,2},{norm='invalid'})end)
fails(function()f.hfft({1,2},nil,nil,nil,nil,1)end)
eq(input:tolist(),{1.25,-2.5,3.75,.125})
collectgarbage('collect')
print('fft105 regression: '..checks..' checks passed')
