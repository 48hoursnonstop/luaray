#!/usr/bin/env python3
"""Generate offline NumPy-2.3.5 executable oracle for LuaRay 0.81 standard_gamma.
NumPy 2.5.3's source algorithm is the target; Python is only needed for fixture creation.
"""
from pathlib import Path
import math
import numpy as np
ROOT = Path(__file__).resolve().parents[1]
master = np.random.default_rng(810081)
seeds=[0,1,2,42,1234,810081,2**32-1]
finite=[0., 1e-9,0.001,.1,.5,.999,1.,1.001,2.,3.3,15.,55.]
nonfinite=[float('nan'),float('inf')]
def lit(v):
    if isinstance(v,np.ndarray):return lit(v.tolist())
    if isinstance(v,(tuple,list)):return '{'+','.join(lit(t) for t in v)+'}'
    if v is None:return 'nil'
    if isinstance(v,(np.integer,int)):return str(int(v))
    f=float(v)
    if math.isnan(f):return '(0/0)'
    if math.isinf(f):return '(1/0)' if f>0 else '(-1/0)'
    return repr(f)

def param(a,kind):
    if kind=='table':return lit(a)
    if kind=='scalar':return lit(a.item())
    if kind=='arr64':return 'np.array('+lit(a)+',"float64")'
    if kind=='arr32':return 'np.array('+lit(a)+',"float32")'
    if kind=='int':return 'np.array('+lit(a)+',"int64")'
    if kind=='transpose':return 'np.transpose(np.array('+lit(a.T)+',"float64"))'
    if kind=='flip':return 'np.flip(np.array('+lit(np.flip(a,axis=-1))+',"float32"),'+str(a.ndim)+')'
    raise ValueError(kind)

head='''-- Generated by tools/generate_random81_oracle.py from NumPy %s
local np=require('luaray_core')
assert(np._version=='0.82.0-dev')
local cases=0
local function close(a,b,eps)
 if type(a)~=type(b) then return false end
 if type(b)=='table' then
  if #a~=#b then return false end
  for i=1,#b do if not close(a[i],b[i],eps) then return false end end
  return true
 end
 if type(b)=='number' then
  if a~=a then return b~=b end
  if a==b then return true end
  return math.abs(a-b)<=eps*math.max(1,math.abs(b))
 end
 return a==b
end
local function verify(got,expected_shape,expected,dtype,tail,rng)
 cases=cases+1
 assert(type(got)=='userdata',('case %%d not ndarray'):format(cases))
 assert(close(got.shape,expected_shape,0),('case %%d shape'):format(cases))
 assert(got.dtype==dtype,('case %%d dtype'):format(cases))
 local eps=dtype=='float32' and 2e-6 or 2e-12
 assert(close(got:tolist(),expected,eps),('case %%d values'):format(cases))
 assert(rng:raw_hex()==tail,('case %%d PCG64'):format(cases))
end
'''%np.__version__
lines=[head]
count=0
for i in range(1500):
    dtype=['float32','float64'][i%2]
    kind=['scalar','table','arr32','arr64','int','transpose','flip'][i%7]
    shape=[(),(1,),(2,),(2,3),(3,2),(1,3),(2,1,3)][i%7]
    if kind in ('transpose','flip') and len(shape)<2:shape=(2,3)
    if kind=='scalar':shape=()
    values=finite+nonfinite if i%5==0 or i%9==0 else finite
    a=master.choice(values,size=shape)
    if kind=='int':a=master.choice([0,1,2,3,4,5,15],size=shape).astype(np.int64)
    if kind=='arr32' or kind=='flip':a=a.astype('float32')
    p=param(a,kind)
    size=None if i%4 in (0,1) else ((2,)+shape if i%4==2 else (0,)+shape)
    use_out=(i%3==0)
    outshape=(shape if size is None else size)
    if use_out and kind=='scalar' and size is None:outshape=[(),(2,3),(0,), (3,)][(i//3)%4]
    if use_out and kind!='scalar' and size is None and i%6==0:outshape=(3,)+shape
    seed=seeds[(i//7)%len(seeds)]
    r=np.random.default_rng(seed)
    try:
        if use_out:
            buf=np.zeros(outshape,dtype=dtype)
            result=r.standard_gamma(a,size=size,dtype=dtype,out=buf)
            assert result is buf
        else:
            result=r.standard_gamma(a,size=size,dtype=dtype)
    except ValueError:
        continue
    tail='%016x'%int(r.bit_generator.random_raw())
    code='do local r=np.random.default_rng(%d);'%seed
    outinit=''
    if use_out:
        outinit='local o=np.zeros('+lit(outshape)+',"'+dtype+'");'
        code+=outinit
    code+='local x=r:standard_gamma('+p+','+lit(size)+',"'+dtype+'"'+(',o' if use_out else '')+');'
    if use_out:code+='assert(rawequal(x,o),"out identity '+str(i)+'");'
    if isinstance(result,np.ndarray):
        code+='verify(x,'+lit(result.shape)+','+lit(result)+',"'+dtype+'","'+tail+'",r)'
    else:
        code+='cases=cases+1;assert(close(x,'+lit(result)+','+('2e-6' if dtype=='float32' else '2e-12')+'),"scalar '+str(i)+'");assert(r:raw_hex()=="'+tail+'","PCG '+str(i)+'")'
    code+=' end\n'
    lines.append(code)
    count+=1
lines.append('assert(cases=='+str(count)+')\nprint("random81 differential passed: '+str(count)+' cases")\n')
p=ROOT/'tests/random81_differential_generated.lua'
p.write_text(''.join(lines))
print(f'NumPy {np.__version__}: {count} cases, {p.stat().st_size} bytes')
