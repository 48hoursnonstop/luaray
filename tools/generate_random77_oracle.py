import numpy as np
from pathlib import Path
rng=np.random.default_rng(77)
root=Path(__file__).resolve().parent.parent
def lua(x):
 if isinstance(x,np.ndarray):return lua(x.tolist())
 if isinstance(x,(np.integer,int)):return str(int(x))
 if isinstance(x,(np.floating,float)):return repr(float(x))
 if x is None:return 'nil'
 if isinstance(x,list):return '{'+','.join(lua(v) for v in x)+'}'
 raise TypeError(type(x))
header='''-- Frozen independent NumPy 2.3.5 oracle; generated by tools/generate_random77_oracle.py
local np=require('luaray_core')
local cases=0
local function same(actual,expect)
  if type(actual) ~= type(expect) then return false end
  if type(expect)=='table' then
    if #actual~=#expect then return false end
    for k=1,#actual do if not same(actual[k],expect[k]) then return false end end
    return true
  end
  if type(expect)=='number' then
    return actual == expect or math.abs(actual-expect) <= 4e-13*math.max(1, math.abs(expect))
  end
  return actual==expect
end
local function check(ok,comment)
  assert(ok,('random77 case %d: %s'):format(cases,comment))
end
'''
shapes=[(),(1,),(2,),(3,),(1,3),(2,3),(2,1,3)]
lines=[header]
count=0
for j in range(1200):
 kind=['normal','uniform','exponential'][j%3]
 seed=[0,1,42,77,1234,2**15][j%6]
 shape=shapes[int(rng.integers(len(shapes)))]
 def param(kind,shape,offset):
  if not shape:return float([.1,.3,1.25][int(rng.integers(3))] + offset)
  v = np.arange(np.prod(shape),dtype=np.float64).reshape(shape)
  v=(v%7)*0.25 + [0.1,0.3,1.25][int(rng.integers(3))] + offset
  return v
 a_shape=shapes[int(rng.integers(len(shapes)))];b_shape=shapes[int(rng.integers(len(shapes)))];
 # for 70% choose compatible from known target shape; otherwise use occasional broadcastable equal shapes
 common=shape if shape else ()
 def subset(s):
  if not s:return ()
  return tuple(1 if rng.random()<0.5 else d for d in s)
 a_shape=subset(common)
 b_shape=subset(common)
 a=param(kind,a_shape,0.2 if kind=='uniform' else 0)
 b=param(kind,b_shape,1.6 if kind=='uniform' else 0.1)
 if kind=='uniform':
  # guarantee high >= low on broadcasted elements
  b=np.asarray(b)+3
 elif kind=='normal':
  pass
 else:
  a=np.asarray(a)+0.4 if isinstance(a,np.ndarray) else a+0.4
 explicit=int(rng.integers(4))!=0
 if explicit:
  size=shape if rng.random()>.3 else ((1,)+shape)
 else:size=None
 # avoid array args with shape not broadcasting into explicit size - explicit size must exactly output
 args=[a] if kind=='exponential' else [a,b]
 try:
  oracle=getattr(np.random.default_rng(seed),kind)(*args,size=size)
 except Exception:
  continue
 oracle_rng=np.random.default_rng(seed)
 oracle=getattr(oracle_rng,kind)(*args,size=size)
 state=f'{int(oracle_rng.bit_generator.random_raw()):016x}'
 args_lua=[]
 for arg in args:
  use_table = rng.random()<0.45
  if isinstance(arg,np.ndarray) and arg.ndim>0:
   arg_lua=lua(arg)
   if not use_table:arg_lua=f'np.array({arg_lua},"float64")'
  else:
   arg_lua=lua(arg)
  args_lua.append(arg_lua)
 args_lua.append(lua(list(size) if size is not None else None))
 call=kind+'('+','.join(args_lua)+')'
 data=lua(np.asarray(oracle))
 shape_lua=lua(list(np.asarray(oracle).shape))
 lines.append(f'do local r=np.random.default_rng({seed}); local x=r:{call}; cases=cases+1\n')
 if isinstance(oracle,np.ndarray):
  lines.append(f'  check(type(x)=="userdata","type");check(same(x.shape,{shape_lua}),"shape");check(same(x:tolist(),{data}),"values")\n')
 else:lines.append(f'  check(same(x,{data}),"scalar")\n')
 lines.append(f'  check(r:raw_hex(),"{state}") -- byte-for-byte PCG64 continuation\nend\n'.replace(f'check(r:raw_hex(),"{state}")',f'check(r:raw_hex()=="{state}","PCG64")'))
 count+=1
# Non-contiguous, reversed, and transposed parameter operands; NumPy consumes
# its random bitstream in C-order output iteration, not physical input order.
for j in range(360):
 kind=['normal','uniform','exponential'][j%3]
 seed=[0,42,67,1234,99991][j%5]
 base=np.array([[0.25,0.5,0.75],[1.0,1.25,1.5]],dtype=np.float64)
 dtype=['float32','float64','int64'][j%3]
 base=base+0.5 if dtype=='int64' else base
 base=base.astype(dtype)
 view=['transpose','flip0','flip1'][j%3]
 if view=='transpose':
  a=base.T
  expr_a=f'np.transpose(np.array({lua(base)},"{dtype}"))'
 elif view=='flip0':
  a=np.flip(base,axis=0)
  expr_a=f'np.flip(np.array({lua(base)},"{dtype}"),1)'
 else:
  a=np.flip(base,axis=1)
  expr_a=f'np.flip(np.array({lua(base)},"{dtype}"),2)'
 if kind=='exponential':
  args=[a]
  expr=[expr_a]
 elif kind=='uniform':
  args=[a,9.0]
  expr=[expr_a,'9.0']
 else:
  args=[a,1.25]
  expr=[expr_a,'1.25']
 sz=None if j%2==0 else ((2,)+a.shape)
 ref_rng=np.random.default_rng(seed)
 oracle=getattr(ref_rng,kind)(*args,size=sz)
 state=f'{int(ref_rng.bit_generator.random_raw()):016x}'
 lines.append(f'do local r=np.random.default_rng({seed}); local x=r:{kind}({",".join(expr+[lua(list(sz) if sz is not None else None)])}); cases=cases+1\n')
 lines.append(f'  check(type(x)=="userdata","view type");check(same(x.shape,{lua(list(np.shape(oracle))) }),"view shape");check(same(x:tolist(),{lua(np.asarray(oracle))}),"view values")\n')
 lines.append(f'  check(r:raw_hex()=="{state}","view PCG64")\nend\n')
 count+=1
lines.append(f'print("random77 differential passed: {count} cases")\n')
(root/'tests/random77_differential_generated.lua').write_text(''.join(lines))
print('Generated', count,'differential cases, bytes',sum(map(len,lines)))
