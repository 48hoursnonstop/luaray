local np=require('luaray')
local matrix=np.arange(12,'float32'):reshape({3,4})
local columns=matrix:take({1,-1},{axis=2})
assert(columns:get(2,1)==4 and columns:get(2,2)==7)
local out=np.zeros({2,4},'float64')
assert(np.take(matrix,{-1,1},{axis=1,out=out})==out)
assert(out:get(1,4)==11 and out:get(2,1)==0)
assert(np.take(matrix,-1)==11)
print('LuaRay native take example: passed')
