local np=require('luaray_core')
local checks=0
local function eq(a,b)
 checks=checks+1
 if type(b)=='table' then assert(type(a)=='table' and #a==#b);for i=1,#b do eq(a[i],b[i]) end
 else assert(a==b,tostring(a)..' != '..tostring(b)) end
end
local function fails(fn,fragment)
 checks=checks+1;local ok,err=pcall(fn);assert(not ok,'expected condition-selection rejection')
 if fragment then assert(tostring(err):find(fragment,1,true),tostring(err)) end
end
local a=np.array({{0,2,0},{3,0,4}},'int32')
local coords=np.nonzero(a)
eq(#coords,2);eq(coords[1]:tolist(),{1,2,2});eq(coords[2]:tolist(),{2,1,3})
eq(coords[1].strides,{16});eq(coords[2].strides,{16})
eq(np.shares_memory(coords[1],coords[2]),false)
eq(np.may_share_memory(coords[1],coords[2]),true)
coords[1]:set(9,1);eq(coords[2]:get(1),2);eq(a:get(1,2),2)
eq(a:nonzero()[1]:tolist(),{1,2,2})
eq(np.flatnonzero(a):tolist(),{2,4,6})
eq(a:get(table.unpack(a:nonzero())):tolist(),{2,3,4})
eq(np.flatnonzero(0):tolist(),{})
eq(np.flatnonzero(3):tolist(),{1})
fails(function()np.nonzero(3)end,'zero-dimensional')
local empty=np.nonzero(np.zeros({0,3},'bool'))
eq(empty[1].shape,{0});eq(empty[1].strides,{16});eq(empty[2].strides,{16})
eq(np.shares_memory(empty[1],empty[2]),false)
eq(np.compress({true,false,true},a,{axis=2}):tolist(),{{0,0},{3,4}})
eq(a:compress({true,false},{axis=1}):tolist(),{{0,2,0}})
eq(np.compress({false,true,false,true},a):tolist(),{2,3})
eq(np.extract({{false,true,false},{true,false,true}},a):tolist(),{2,3,4})
eq(np.extract(true,np.array(5)):tolist(),{5})
eq(np.extract(false,np.array(5)):tolist(),{})
-- Overlong false tails are permitted; overlong true positions raise.
eq(np.compress({true,false,false,false},np.array({10,20})):tolist(),{10})
fails(function()np.compress({true,false,true},np.array({10,20}))end,'bounds')
fails(function()np.extract({false,false,true},np.array({10,20}))end,'bounds')
fails(function()np.compress(true,a)end,'one dimension')
fails(function()np.compress({{true}},a)end,'one dimension')
fails(function()np.compress({true},a,0)end)
fails(function()np.compress({true},a,3)end)
fails(function()np.compress({true},a,true)end)
fails(function()np.compress({true},a,{out={}})end)
fails(function()np.nonzero(a,1)end)
fails(function()np.extract(true)end)
fails(function()np.extract(true,a,1)end)
fails(function()np.compress({true})end)
local out=np.zeros({2,2},'float64')
eq(np.compress({true,false,true},a,{axis=2,out=out}),out)
eq(out:tolist(),{{0,0},{3,4}})
local alias=np.array({true,false,true,false},'bool')
np.compress(alias,alias,{out=alias:get(np.s(1,3))})
eq(alias:tolist(),{true,true,true,false})
local nat=np.array({math.mininteger,0,1},'datetime64[D]')
eq(np.flatnonzero(nat):tolist(),{1,3})
eq(np.compress({'','0','a'},np.array({10,20,30})):tolist(),{20,30})
collectgarbage('collect')
print('condition103 regression: '..checks..' checks passed')
