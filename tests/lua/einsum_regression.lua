local lr = require("luaray")
local a = lr.array({{1, 2}, {3, 4}})
local b = lr.array({{5, 6}, {7, 8}})
assert(lr.array_equal(lr.einsum("ij,jk->ik", a, b), {{19, 22}, {43, 50}}))
assert(lr.array_equal(lr.einsum("ij,jk", a, b), lr.matmul(a, b)))
assert(lr.einsum("ii", a) == 5)
assert(lr.einsum("i,i->", {1, 2, 3}, {2, 4, 6}) == 28)
assert(lr.einsum(",", 3, 4) == 12)

local diagonal = lr.einsum("ii->i", a)
assert(lr.shares_memory(diagonal, a) and not diagonal.flags.owndata)
diagonal[2] = 9
assert(a:get(2, 2) == 9)
assert(lr.allclose(lr.einsum("...ij,jk->...ik", lr.stack({a,b}), b),
                  lr.matmul(lr.stack({a,b}), b)))
local expected = lr.einsum("ij,ij->ij", a, b)
local inplace = lr.einsum("ij,ij->ij", a, b, {out=a})
assert(rawequal(inplace, a) and lr.array_equal(a, expected))
local sum = lr.zeros({}, "int64")
assert(rawequal(lr.einsum("i->", {1, 2, 3}, {out=sum}), sum) and sum:item() == 6)

local x = lr.array({100, 100}, "int8")
local y = lr.array({2, 2}, "int8")
assert(lr.einsum("i,i->", x, y) == -112)
local wide = lr.zeros({}, "int64")
assert(lr.einsum("i,i->", x, y, {out=wide}):item() == 400)
assert(lr.einsum("i,i->", x, y, {dtype="float32"}) == 400)
assert(lr.einsum("i,i->", lr.ones({2}, "longdouble"), {1, 2}).dtype == "longdouble")
assert(lr.einsum("i,j->ij", {1, 2, 3}, {2, 3}, {order="A"}).flags.f_contiguous)
assert(lr.array_equal(lr.einsum("ij,jk->ik", lr.empty({2,0}), lr.empty({0,3})), lr.zeros({2,3})))

assert(not pcall(lr.einsum, "ii", lr.ones({2, 3})))
assert(not pcall(lr.einsum, "i->ii", {1, 2, 3}))
assert(not pcall(lr.einsum, "...i->i", lr.ones({2, 3})))
assert(not pcall(lr.einsum, "i->", {1, 2, 3}, {optimize=true}))
print("Einstein summation regression passed")
