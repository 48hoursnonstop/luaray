local lr = require("luaray")

local a = lr.array({{1,2,3},{4,5,6}}, "int16")
local file = assert(io.tmpfile())
local reversed = lr.flip(lr.transpose(a), 1)
assert(file:write("head"))
reversed:tofile(file)
assert(file:seek() == 16)
assert(file:seek("set", 2) == 2)
local read = lr.fromfile(file, {dtype = "int16", offset = 2, count = 3})
assert(read[1] == 3 and read[2] == 6 and read[3] == 2)
assert(file:seek() == 10)
local rest = lr.fromfile(file, {dtype = "int16"})
assert(rest[1] == 5 and rest[2] == 1 and rest[3] == 4)
assert(file:close())
assert(not pcall(lr.fromfile, file))
assert(not pcall(a.tofile, a, file))

local partial = assert(io.tmpfile())
assert(partial:write("abcde"))
assert(partial:seek("set", 0))
assert(lr.fromfile(partial, {dtype = "int32"}).size == 1)
assert(partial:seek() == 4)
assert(partial:seek("set", 0))
assert(lr.fromfile(partial, {dtype = "int32", count = 2}).size == 1)
assert(partial:seek() == 5)
assert(partial:close())

local path = os.tmpname()
local ok, err = pcall(function()
    a:tofile(path)
    local roundtrip = lr.fromfile(path, {dtype = a.dtype})
    assert(roundtrip:tobytes() == a:tobytes())
    assert(not pcall(lr.fromfile, path, {sep = ","}))
    assert(not pcall(lr.fromfile, path, {offset = 1.5}))
    assert(not pcall(lr.fromfile, path .. "\0bad"))
end)
os.remove(path)
assert(ok, err)
print("raw file regression passed")
