"""Regenerate binomial reference fixture with NumPy (not a LuaRay runtime dependency)."""
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'tests/distributions62_differential_generated.lua'
L=[f'-- Generated by NumPy {np.__version__} using tools/generate_distributions62_differential.py',
   'local np=require("luaray_core")','assert(np._version=="0.63.0-dev")',
   'local total=0','local function eq(x,y) assert(x==y, ("case %d: %s ~= %s"):format(total,tostring(x),tostring(y)));total=total+1 end']
def sz(s):return 'nil' if s is None else '{'+','.join(map(str,s))+'}'
def checks(v,sh):
    if sh is None:
        L.append(f'eq(v,{int(v)})')
    else:
        L.append('eq(v.dtype,"int64")')
        L.append(f'eq(#v.shape,{len(sh)})')
        for j,dim in enumerate(sh,1):L.append(f'eq(v.shape[{j}],{dim})')
        for ix in np.ndindex(*sh):
            expr=','.join(str(i+1) for i in ix)
            L.append(f'eq(v:get({expr}),{int(v[ix])})')
seeds=[0,1,2,42,123456789,1099511627779]
ns=[0,1,2,5,10,30,31,50,60,61,100,1000,100000,1000000000,1000000000000]
ps=[0.,0.0000001,0.001,0.01,0.1,0.2,1/3,0.499,0.5,0.501,0.8,0.9,0.99,0.999999,1.]
shapes=[None,(),(0,),(2,3),(4,)]
for seed in seeds:
 for n in ns:
  for p in ps:
   for shape in shapes:
    rng=np.random.default_rng(seed)
    v=rng.binomial(n,p,size=shape)
    L.append(f'do local r=np.random.default_rng({seed});local v=r:binomial({n},{p!r},{sz(shape)})')
    checks(v,shape)
    L.append(f'eq(r:raw_hex(),"{int(rng.bit_generator.random_raw()):016x}") end')
# long interleaved stream exercises cache semantics and bit-generation mixing
for seed in seeds:
 rng=np.random.default_rng(seed)
 L.append(f'do local r=np.random.default_rng({seed})')
 for k in range(360):
  j=k%5
  if j==0:
   n=ns[(k*13//5)%len(ns)];p=ps[(k*7//5)%len(ps)]
   got=int(rng.binomial(n,p));expr=f'r:binomial({n},{p!r})'
  elif j==1:
   n=1000;p=0.3;got=int(rng.binomial(n,p));expr='r:binomial(1000,0.3)'
  elif j==2:
   got=float(rng.random());expr='r:random()'
  elif j==3:
   got=int(rng.integers(0,100));expr='r:integers(0,100)'
  else:
   n=100;p=.7;got=int(rng.binomial(n,p));expr='r:binomial(100,0.7)'
  L.append(f'eq({expr},{repr(got)})')
 L.append(f'eq(r:raw_hex(),"{int(rng.bit_generator.random_raw()):016x}") end')
# invalid arguments must not alter the PCG64 stream
bad=['r:binomial(-1,0.5)','r:binomial(1e15,0.5)','r:binomial(2,1.01)',
     'r:binomial(2,-0.01)','r:binomial(2,math.huge)','r:binomial(2,-math.huge)',
     'r:binomial(2,0/0)','r:binomial(2,0.5,{-1})','r:binomial(2,0.5,{1.5})',
     'r:binomial(2,0.5,{},123)','r:binomial(2.5,0.2)',
     'r:binomial("abc",0.5)','r:binomial(10,"abc")']
for s in bad:
 rng=np.random.default_rng(42)
 L.append(f'do local r=np.random.default_rng(42);eq(pcall(function() return {s} end),false);eq(r:raw_hex(),"{int(rng.bit_generator.random_raw()):016x}") end')
L.append('print("distributions62 differential passed: "..total.." exact checks")')
OUT.write_text('\n'.join(L)+'\n')
print(OUT,len(L),'lines',OUT.stat().st_size,'bytes')
