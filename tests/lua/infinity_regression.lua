local lr=require('luaray')
local checks=0
local function eq(a,b)checks=checks+1;assert(a==b)end
local function fails(fn)checks=checks+1;assert(not pcall(fn))end
local a=lr.array({-math.huge,0/0,math.huge,-0.0,0.0,1.0})
local pos,neg=lr.isposinf(a),lr.isneginf(a)
for i=1,6 do eq(pos[i],i==3);eq(neg[i],i==1)end
eq(pos.dtype,'bool');eq(neg.dtype,'bool');eq(pos.flags.owndata,true)
eq(lr.isposinf(math.huge):tolist(),true);eq(lr.isneginf(-math.huge):tolist(),true)
eq(lr.isposinf({1,math.huge,2})[2],true)
local out=lr.full({2,6},9,'int16')
eq(rawequal(lr.isposinf(a,out),out),true);eq(out:get(2,3),1);eq(out:get(1,1),0)
local aliased=lr.array({-math.huge,0,math.huge})
lr.isposinf(aliased,lr.flip(aliased,1));eq(aliased[1],1);eq(aliased[3],0)
local base=lr.array({math.huge,0,-math.huge})
local repeated=lr.ndarray({3},{dtype=base.dtype,buffer=base,strides={0}})
lr.isneginf(base,repeated);eq(base[1],1);eq(base[3],-math.huge)
local readonly=lr.array({math.huge});readonly:setflags(false)
eq(lr.isposinf(readonly)[1],true);eq(readonly.flags.writeable,false)
local text=lr.empty({3},'S3');lr.isposinf(lr.array({1,math.huge,2}),text);eq(text[2],'Tru')
local dt=lr.empty({3},'timedelta64[h]');lr.isneginf(lr.array({-math.huge,0,1}),dt)
eq(lr.astype(dt,'int64')[1],1)
local invalid=lr.full({3},9,'float64')
fails(function()lr.isposinf(lr.array({lr.complex(1,0)}),invalid)end)
eq(invalid[1],9);eq(invalid[3],9)
fails(function()lr.isposinf(lr.empty({0},'complex128'))end)
fails(function()lr.isneginf(lr.array({'a','b'}))end)
fails(function()lr.isposinf(a,{out=out})end)
fails(function()lr.isposinf(a,out,1)end)
fails(function()lr.isneginf(a,readonly)end)
fails(function()lr.isposinf(a,lr.empty({2}))end)
collectgarbage('collect')
print('infinity regression: '..checks..' checks passed')
