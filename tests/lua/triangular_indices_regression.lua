local lr=require('luaray')
local checks=0
local function check(value)checks=checks+1;assert(value)end
local function reject(call)check(not pcall(call))end
local a=lr.arange(12):reshape({3,4})
local lower=lr.tril_indices_from(a)
local selected=a:get(table.unpack(lower))
check(selected.size==6 and selected[1]==0 and selected[2]==4 and selected[6]==10)
check(lower[1].dtype=='int64' and lower[1].strides[1]==8)
check(not rawequal(lower[1],lower[2]) and not lr.shares_memory(lower[1],lower[2]))
lower[1][1]=2;check(lower[2][1]==1)
local upper=lr.triu_indices(3,{m=4,k=1})
check(upper[1].size==6 and upper[1][1]==1 and upper[2][1]==2)
a:set(-1,table.unpack(upper))
check(a:get(1,2)==-1 and a:get(2,3)==-1 and a:get(3,4)==-1 and a:get(3,1)==8)
local reverse=lr.flip(a,1)
local coordinates=lr.tril_indices_from(reverse,-1)
reverse:set(99,table.unpack(coordinates))
check(a:get(1,1)==99 and a:get(2,1)==99 and a:get(3,1)==8)
for _,fn in ipairs({lr.tril_indices,lr.triu_indices})do
 check(fn(-3)[1].size==0)
 local empty=fn(3,{m=0,k=math.mininteger})
 check(empty[1].size==0 and empty[1].strides[1]==0)
 check(not lr.shares_memory(empty[1],empty[2]))
 check(fn(2,0,4)[1].size>0)
 reject(function()fn()end)
 reject(function()fn(2.5)end)
 reject(function()fn(2,true)end)
 reject(function()fn(2,{m=2.5})end)
 reject(function()fn(2,{unknown=1})end)
 reject(function()fn(2,{['k\0']=0})end)
 reject(function()fn(2,{},4)end)
 reject(function()fn(2,0,2,1)end)
 reject(function()fn(2,{m=1,k=math.mininteger})end)
end
for _,fn in ipairs({lr.tril_indices_from,lr.triu_indices_from})do
 check(fn(lr.zeros({2,4}))[1].size>0)
 reject(function()fn({{1,2},{3,4}})end)
 reject(function()fn(lr.arange(3))end)
 reject(function()fn(lr.zeros({2,2,2}))end)
 reject(function()fn(a,{m=3})end)
 reject(function()fn(a,{k=true})end)
 reject(function()fn(a,0,1)end)
end
check(lr.tril_indices(2,math.maxinteger)[1].size==4)
check(lr.triu_indices(2,math.maxinteger)[1].size==0)
reject(function()lr.triu_indices(2,math.mininteger+1,1)end)
print('triangular indices regression: '..checks..' checks passed')
