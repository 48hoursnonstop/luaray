local np=require('luaray')
local a=np.array({{1,2,3},{4,5,6}},'int32')
local mask=np.greater(a,3)
local selected=np.where(mask,a,0)
assert(selected:get(1,3)==0 and selected:get(2,1)==4)
assert(np.where(mask)[1]:get(1)==2)
local piecewise=np.select({np.less(a,3),np.greater(a,4)},{-1,9},0)
assert(piecewise:get(1,1)==-1 and piecewise:get(1,3)==0 and piecewise:get(2,2)==9)
assert(np.where(true,1,2).ndim==0)
print('LuaRay native where/select example: passed')
