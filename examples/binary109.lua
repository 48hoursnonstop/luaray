local np=require('luaray')
assert(np.fmod(-5,3):tolist()==-2)
assert(np.remainder(-5,3):tolist()==1)
assert(np.float_power(2,-3):tolist()==.125)
assert(np.float_power(np.array({2},'int8'),300).dtype=='float64')
assert(np.add({1,2,3},2):tolist()[3]==5)
local b=np.multiply({{1},{2}},{10,20,30})
assert(b.shape[1]==2 and b.shape[2]==3 and b:tolist()[2][3]==60)
assert(np.add('λ','🙂'):tolist()=='λ🙂')
assert(np.add(np.array({'a\0b'},'S4'),np.array({'c'},'S4')):tolist()[1]=='a\0bc')
assert(np.logical_and(np.array({1},'float16'),1e-100):tolist()[1])
local out=np.full({3},99,'float64')
assert(rawequal(np.fmod({5,6,7},3,{out=out,where=np.array({true,false,true})}),out))
assert(out:tolist()[1]==2 and out:tolist()[2]==99 and out:tolist()[3]==1)
