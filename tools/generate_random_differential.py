#!/usr/bin/env python3
"""Reproducible PCG64/float64 oracle fixture, NumPy 2.3.5 at authoring time.

NumPy is needed only when regenerating this checked-in fixture. The Lua
fixture and the LuaRay runtime do not import or link against Python.
"""
from pathlib import Path
import numpy as np

out = Path(__file__).resolve().parents[1] / 'tests/random_differential_generated.lua'
seeds = [0, 1, 2, 42, 99, 123456789, (1 << 40) + 3, (1 << 62) + 5]
lines = ["-- generated by tools/generate_random_differential.py using NumPy " + np.__version__,
         "local np=require('luaray_core')", "local cases=0",
         "local function eq(a,b) assert(a==b, tostring(a)..' ~= '..tostring(b)); cases=cases+1 end"]

def floatlit(f):
    return repr(float(f))

for seed in seeds:
    rng = np.random.default_rng(seed)
    lines.append(f"do local r=np.random.default_rng({seed})")
    for _ in range(20):
        raw = int(rng.bit_generator.random_raw())
        lines.append(f"eq(r:raw_hex(),'{raw:016x}')")
    lines.append('end')

for seed in seeds:
    lines.append(f'do local r=np.random.default_rng({seed})')
    rng = np.random.default_rng(seed)
    for _ in range(24):
        value = rng.random()
        lines.append(f'eq(r:random(),{floatlit(value)})')
    lines.append('end')

for seed in seeds:
    for n in [0,1,2,3,7,18]:
        rng = np.random.default_rng(seed)
        values = rng.random(n)
        lines.append(f'do local r=np.random.default_rng({seed});local a=r:random({n})')
        lines.append(f"eq(a.dtype,'float64');eq(a.shape[1],{n})")
        for i, value in enumerate(values, 1):
            lines.append(f'eq(a:get({i}),{floatlit(value)})')
        lines.append('end')

for seed in seeds:
    for shape in [(2,3),(3,1,2),(2,0,4)]:
        rng = np.random.default_rng(seed)
        values = rng.random(shape)
        dims = ','.join(map(str,shape))
        lines.append(f'do local r=np.random.default_rng({seed});local a=r:random({{{dims}}})')
        for i,dim in enumerate(shape,1):lines.append(f'eq(a.shape[{i}],{dim})')
        for ix in np.ndindex(*shape):
            idx=','.join(str(v+1) for v in ix)
            lines.append(f'eq(a:get({idx}),{floatlit(values[ix])})')
        lines.append('end')

for seed in seeds:
    for low,high in [(-2.5, 5.75),(0.0,1.0),(9.0,9.0),(-1000.0,-10.0)]:
        rng=np.random.default_rng(seed)
        result=rng.uniform(low,high,7)
        lines.append(f'do local r=np.random.default_rng({seed});local a=r:uniform({low},{high},7)')
        for i,v in enumerate(result,1):
            lines.append(f'eq(a:get({i}),{floatlit(v)})')
        lines.append('end')

lines.append("print('random differential approved: '..cases..' exact comparisons')")
out.write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('generated',out, 'with',len(lines), 'lines using numpy',np.__version__)
