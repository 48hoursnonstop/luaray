local np=require('luaray_core')
local rng=np.random.default_rng(2026)
local population=np.array({'alpha','beta','gamma','delta'})
local with_replacement=rng:choice(population,8,true,{0.05,0.15,0.3,0.5})
local without_replacement=rng:choice(12,5,false)
local matrix=np.arange(12,'int64'):reshape({3,4})
local columns=rng:choice(matrix,{2,2},false,nil,2)
assert(with_replacement.size==8)
assert(without_replacement.size==5)
assert(columns.shape[1]==3 and columns.shape[2]==2 and columns.shape[3]==2)
print('Weighted labels:',table.concat(with_replacement:tolist(),', '))
print('Without replacement:',table.concat(without_replacement:tolist(),', '))
print('Sampled matrix shape:',table.concat(columns.shape,' x '))
print('choice74 example passed')
