local np=require('luaray')
local a=np.array({{1,2,3},{4,5,6}},'int32')
assert(np.asarray(a)==a)
local clone=a:copy()
assert(not np.shares_memory(a,clone))
clone:set(99,1,1);assert(a:get(1,1)==1)
local padded=np.array(a,{copy=false,ndmin=3})
assert(padded.shape[1]==1 and np.shares_memory(a,padded))
local full=np.full_like(a,7,{dtype='float32',shape={3,2},order='F'})
assert(full.dtype=='float32' and full:get(3,2)==7 and full.strides[1]==4)
local zeros=np.zeros_like(a);local ones=np.ones_like(a)
assert(zeros:get(2,3)==0 and ones:get(2,3)==1)
local empty=np.empty_like(a);np.copyto(empty,a)
assert(empty:get(2,3)==6)
assert(np.full({2,2},np.array(300,'int64'),'uint8'):get(2,2)==44)
assert(not pcall(function()np.full(2,300,'uint8')end))
assert(np.asarray_chkfinite(a)==a)
assert(not pcall(function()np.asarray_chkfinite({1,math.huge})end))
print('LuaRay native creation and copying example: passed')
