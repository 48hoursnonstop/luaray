local lr = require("luaray")
local x = lr.array({0, 1, 2, 3, 4})
local y = lr.array({3, 6, 11, 18, 27})
local weights = lr.array({1, 2, 3, 1, 2})
local x0, y0, w0 = x:tobytes(), y:tobytes(), weights:tobytes()
local a, residuals, rank, singular, rcond = lr.polyfit(x, y, 2, {full=true, w=weights})
assert(lr.allclose(a, {1, 2, 3}) and rank==3 and singular.size==3)
assert(residuals.size==1 and residuals[1]<1e-20 and rcond>0)
assert(x:tobytes()==x0 and y:tobytes()==y0 and weights:tobytes()==w0)

local f, cov = lr.polyfit(x, y, 2, {cov="unscaled"})
assert(lr.allclose(f, {1, 2, 3}))
assert(cov.shape[1]==3 and cov.shape[2]==3 and cov:get(1,1)>0)
local observed = lr.stack({y,lr.add(x,1)},2)
local m, c = lr.polyfit(x, observed, 2, {cov=true})
assert(lr.allclose(m, {{1,0},{2,1},{3,1}}))
assert(c.ndim==3 and c.shape[3]==2)
local p, _, reduced = lr.polyfit(lr.ones({5}), y, 3, {full=true, rcond=1e-9})
assert(p.shape[1]==4 and reduced==1)
assert(not pcall(lr.polyfit, x, y, 4, {cov=true}))
assert(not pcall(lr.polyfit, x, y, 2, {w={1,2}}))
assert(not pcall(lr.polyfit, x, y, -0.2))
print("Polynomial least squares regression passed")
