local lr=require('luaray')
local checks=0
local function eq(a,b)
 checks=checks+1
 if type(b)=='table' then
  assert(type(a)=='table' and #a==#b)
  for i=1,#b do eq(a[i],b[i]) end
 else assert(a==b,tostring(a)..' ~= '..tostring(b)) end
end
local function fails(fn)checks=checks+1;assert(not pcall(fn))end
local labels=lr.array({0,1,1,3,2,1,7},'uint64')
local counts=lr.bincount(labels)
eq(counts:tolist(),{1,3,1,1,0,0,0,1})
eq(counts.dtype,'int64');eq(counts.flags.owndata,true);eq(counts.flags.writeable,true)
eq(lr.shares_memory(counts,labels),false)
eq(lr.bincount({0,1,0,1,1},{minlength=3}):tolist(),{2,3,0})
eq(lr.bincount({0,1},nil,4):tolist(),{1,1,0,0})
eq(lr.bincount({1,2,4,5,2},{0.2,0.3,0.5,0.1,0.2},8):tolist(),{0,0.2,0.5,0,0.5,0.1,0,0})
eq(lr.bincount({0,0,1},{weights={2,3,4},minlength=3}):tolist(),{5,4,0})
local empty=lr.bincount({},function()error('empty weights must not be visited')end,3)
eq(empty.dtype,'int64');eq(empty:tolist(),{0,0,0})
eq(lr.bincount(lr.array({},'int64'),{weights=lr.array({1},'complex128')}):tolist(),{})
eq(lr.bincount({false,true,true}):tolist(),{1,2})
local raw=lr.ndarray({4},{dtype='bool',buffer=string.char(0,2,128,255)})
eq(lr.bincount(raw):tolist(),{1,3})
local reversed=labels:get(lr.s(nil,nil,-1));reversed:setflags(false)
eq(lr.bincount(reversed):tolist(),counts:tolist())
eq(reversed.flags.writeable,false)
local cancellation=lr.array({1e16,1,-1e16},'float64')
eq(lr.bincount({0,0,0},cancellation):tolist(),{0})
eq(lr.bincount({0,0,0},cancellation:get(lr.s(nil,nil,-1))):tolist(),{0})
local underflow=lr.ndarray({1},{dtype='uint64',buffer=string.rep(string.char(255),8)})
fails(function()lr.bincount(underflow)end)
fails(function()lr.bincount({math.maxinteger})end)
fails(function()lr.bincount({0},{minlength=math.maxinteger})end)
fails(function()lr.bincount({-1})end)
fails(function()lr.bincount(1)end)
fails(function()lr.bincount({{0,1}})end)
fails(function()lr.bincount({1.0})end)
fails(function()lr.bincount({},nil,-1)end)
fails(function()lr.bincount({},nil,true)end)
fails(function()lr.bincount({},nil,3.0)end)
fails(function()lr.bincount({0,1},{})end)
fails(function()lr.bincount({0,1},{1})end)
fails(function()lr.bincount({0,1},lr.array({1,2},'longdouble'))end)
fails(function()lr.bincount({0,1},lr.array({1,2},'complex128'))end)
fails(function()lr.bincount({0,1},{weights={1,2},order='C'})end)
fails(function()lr.bincount({0,1},{['minlength\0bad']=3})end)
fails(function()lr.bincount({0,1},{minlength=3},3)end)
fails(function()lr.bincount({0,1},nil,0,1)end)
for _,dtype in ipairs({'float64','complex128','S3','U2','datetime64[D]','timedelta64[h]'})do
 fails(function()lr.bincount(lr.empty({0},dtype))end)
end
counts[1]=99;eq(labels:tolist(),{0,1,1,3,2,1,7})
print('bincount regression: '..checks..' checks passed')
