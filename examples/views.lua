local lr=require('luaray')
local a=lr.array({{0,1,2},{3,4,5}},'float64')
local columns=lr.ravel(a,'F')
assert(table.concat(columns:tolist(),',')=='0.0,3.0,1.0,4.0,2.0,5.0')
local shared=a:ravel();assert(lr.shares_memory(a,shared))
local independent=a:flatten();assert(not lr.shares_memory(a,independent))
local t=lr.transpose(a)
local view=t:reshape(6,{order='F',copy=false})
assert(lr.shares_memory(view,a))
local negative=lr.flip(a:ravel(),1):reshape({2,3},{copy=false})
assert(negative.strides[1]==-24 and negative.strides[2]==-8)
lr.copyto(negative,7,'unsafe');assert(a:tolist()[1][1]==7)
assert(independent:tolist()[1]==0)
print('layout110 public example passed: traversal, sharing, copies and negative-stride writes')
