local np=require('luaray_core')
assert(np._version=='0.128.0-dev')
local r=np.random.default_rng(42)
local expect={0.30471707975443135,-1.0399841062404955,0.7504511958064572,0.9405647163912139,-1.9510351886538364}
for i=1,#expect do assert(r:standard_normal()==expect[i]) end
r:reseed(42)
local a=r:standard_normal({2,3})
assert(a.dtype=='float64' and a.shape[1]==2 and a.shape[2]==3)
assert(a:get(1,1)==expect[1] and a:get(1,2)==expect[2])
local f=np.random.default_rng(42):standard_normal(5,'float32')
assert(f.dtype=='float32' and f:get(1)==0.14190717041492462)
local n=np.random.default_rng(42):normal(5,2,5)
assert(n.dtype=='float64' and math.abs(n:get(1)-5.609434159508863)<1e-14)
assert(np.random.default_rng(3):standard_normal({2,0,3}).shape[2]==0)
assert(type(np.random.default_rng(3):standard_normal())=='number')
assert(not pcall(function()np.random.default_rng(42):standard_normal(2,'int64')end))
assert(not pcall(function()np.random.default_rng(42):standard_normal(-1)end))
assert(not pcall(function()np.random.default_rng(42):normal(0,-1)end))
assert(not pcall(function()np.random.default_rng(42):normal(0,1,3,'extra')end))
print('normal distribution regression passed')
