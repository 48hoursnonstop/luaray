local np=require('luaray')
local matrix=np.arange(12,'int32'):reshape({3,4})
local transposed=matrix:transpose()
transposed:put({1,-1,3},{90,80})
assert(matrix:get(1,1)==90 and matrix:get(3,4)==80)
local selected=np.greater(matrix,np.array(7,'int32'))
np.place(transposed,selected:transpose(),{5,6})
assert(matrix:get(1,1)==5)
print('LuaRay native put/place example: passed')
