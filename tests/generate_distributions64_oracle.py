from pathlib import Path
import numpy as np, math
p=Path(__file__).resolve().parents[1]
seeds=[0,1,2,42,123456,2**32-1,2**32,2**63-1]
probs=[1e-18, 1e-12, 1e-6,0.0001,0.001,0.01,0.1,0.2,np.nextafter(1/3,0),1/3,np.nextafter(1/3,1),0.35,0.5,0.9,0.999999,1.0]
sizes=[None,(),(0,),(1,),(2,3),(5,),(16,)]
def lit(x):
    if isinstance(x,float): return repr(x)
    if isinstance(x,(int,np.integer)): return str(int(x))
    raise TypeError(x)
def shape(s): return 'nil' if s is None else '{'+','.join(map(str,s))+'}'
def xhex(x): return format(int(x),'016x')
L=['-- Generated by tests/generate_distributions64_oracle.py using executable NumPy '+np.__version__,
   'local np=require("luaray_core")','assert(np._version=="0.64.0-dev")',
   'local total=0','local function eq(a,b) assert(a==b,("case %d: %s ~= %s"):format(total,tostring(a),tostring(b)));total=total+1 end']
for seed in seeds:
 for prob in probs:
  for sz in sizes:
   rng=np.random.default_rng(seed)
   out=rng.geometric(float(prob),size=sz)
   raw=xhex(rng.bit_generator.random_raw())
   L.append(f'do local r=np.random.default_rng({seed}); local v=r:geometric({lit(float(prob))},{shape(sz)})')
   if sz is None:
    L.append(f'eq(v,{int(out)})')
   else:
    L+=['eq(v.dtype,"int64")',f'eq(#v.shape,{len(sz)})']
    for idx,d in enumerate(sz): L.append(f'eq(v.shape[{idx+1}],{d})')
    for ix in np.ndindex(out.shape):
     indices=','.join(map(lambda x:str(x+1),ix));L.append(f'eq(v:get({indices}),{int(out[ix])})')
   L.append(f'eq(r:raw_hex(),"{raw}") end')
# interleaving stream verification
mixes=[(0.2,0.85,0.01),(1.,1/3,0.0001),(1e-18,0.5,0.99999)]
for seed in seeds:
 for mix in mixes:
  rng=np.random.default_rng(seed)
  L.append(f'do local r=np.random.default_rng({seed})')
  for prob in mix:
   v=int(rng.geometric(prob));L.append(f'eq(r:geometric({lit(float(prob))}),{v})')
   d=float(rng.random());L.append(f'eq(r:random(),{repr(d)})')
   v=int(rng.integers(0,1000));L.append(f'eq(r:integers(0,1000),{v})')
  L.append(f'eq(r:raw_hex(),"{xhex(rng.bit_generator.random_raw())}") end')
L.append('print("distributions64 differential passed",total,"checks")')
(p/'tests/distributions64_differential_generated.lua').write_text('\n'.join(L)+'\n')
(p/'tests/generate_distributions64_oracle.py').write_text(Path(__file__).read_text().replace("Path(__file__).resolve().parents[1]", "Path(__file__).resolve().parents[1]")+'\n')
print('Number of lines:',len(L))



