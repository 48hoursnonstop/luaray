local np=require('luaray_core')
assert(np._version=='0.147.0-dev')
local function rejected_without_draws(param,size,dtype)
 local rng=np.random.default_rng(314159)
 local ref=np.random.default_rng(314159)
 local ok,err=pcall(function()rng:standard_gamma(param,size,dtype)end)
 assert(not ok and type(err)=='string', 'invalid shape must raise')
 assert(rng:raw_hex()==ref:raw_hex(),'invalid shape advanced PCG64')
end
rejected_without_draws({1,-1,2},{0,3},'float32')
rejected_without_draws({{.1},{-3}}, {2,3},'float64')
rejected_without_draws(np.array({1,2,3}),{2,2},'float32')
rejected_without_draws({1,2},nil,'float16')
rejected_without_draws(np.array({{1,2},{3,-1}},'float32'),nil,'float64')
-- NumPy accepts NaN/+Inf parameters in the 0.81 compatibility update.
local q=np.random.default_rng(42)
assert(q:standard_gamma(1/0)==math.huge)
assert(q:standard_gamma(0/0)~=q:standard_gamma(0/0))
local r=np.random.default_rng(42)
local x=r:standard_gamma({{0.5},{2.0}}, {2,3},'float32')
assert(type(x)=='userdata' and x.dtype=='float32' and x.shape[1]==2 and x.shape[2]==3)
local y=r:standard_gamma(np.flip(np.array({{0,1,2},{3,4,5}},'float32'),2),nil,'float64')
assert(y.shape[1]==2 and y.shape[2]==3)
local z=r:standard_gamma({0.5,1.,2}, {0,3},'float32')
assert(z.shape[1]==0 and z.shape[2]==3)
print('random80 regression passed')
