HEADER='''-- Generated by tools/generate_vector116_differential.py; NumPy2.5.3.
local np=require('luaray_core')
local cases,checks,max_error,max_relative_error=0,0,0,0
local active_dtype,errors=nil,{}
local function eq(a,b,label,tol)
 checks=checks+1
 if type(b)=='table' then
  assert(type(a)=='table' and #a==#b,label..': shape')
  for i=1,#b do eq(a[i],b[i],label..'['..i..']',tol)end
 elseif type(b)=='userdata' then eq(a.real,b.real,label..'.real',tol);eq(a.imag,b.imag,label..'.imag',tol)
 elseif type(b)=='number' and b~=b then assert(a~=a,label..': NaN')
 elseif type(b)=='number' and a~=b then
  assert(type(a)=='number' and a==a and math.abs(b)~=math.huge,label..': finite/sign')
  local err=math.abs(a-b);max_error=math.max(max_error,err)
  local scaled=err/math.max(1,math.abs(b))
  max_relative_error=math.max(max_relative_error,scaled)
  if active_dtype then
   local record=errors[active_dtype]or{absolute=0,scaled=0}
   record.absolute=math.max(record.absolute,err);record.scaled=math.max(record.scaled,scaled)
   errors[active_dtype]=record
  end
  assert(err<=(tol or 0)*math.max(1,math.abs(b)),label..': '..tostring(a)..' != '..tostring(b))
 else assert(a==b,label..': '..tostring(a)..' != '..tostring(b))end
end
'''
def lua_axis(axis):return axis+1 if axis>=0 else axis
class Cross(Suite):
    def __init__(self,name):super().__init__(name);self.lines=[HEADER]
    def check(self,name,value,label,tol=0):
        a=np.asarray(value)
        if a.dtype.kind in 'Mm':self.lines+=['eq(np.astype('+name+',"int64"):tolist(),'+lua(a.astype('int64'))+','+lua(label+': ticks')+')']
        elif a.dtype.kind in 'iu' and a.itemsize==8:self.lines+=['eq(np.astype('+name+',"U40"):tolist(),'+lua(a.astype('U40'))+','+lua(label+': integer values')+')']
        else:self.lines+=['eq('+name+':tolist(),'+lua(a)+','+lua(label+': values')+','+str(tol)+')']
        for attr,value in [('shape',a.shape),('strides',a.strides),('dtype',dtype(a.dtype))]:self.lines+=['eq('+name+'.'+attr+','+lua(value)+','+lua(label+': '+attr)+')']
        if a.dtype.kind in 'fc':
            parts=[(name,a)] if a.dtype.kind=='f' else [(name+'.real',a.real),(name+'.imag',a.imag)]
            for expr,part in parts:self.lines+=['eq(np.logical_and(np.signbit('+expr+'),np.equal('+expr+',0)):tolist(),'+lua(np.signbit(part)&(part==0))+','+lua(label+': signed zero')+')']
    def case(self,a,b,axes=(-1,-1,-1),view='base',*,linalg=False,raw=False,general=False):
        self.count+=1
        if (self.count-1)%60==0:
            if self.count>1:self.lines+=['end','chunk()','end']
            self.lines+=['do','local function chunk()']
        abase=np.array(a,copy=True);bbase=np.array(b,copy=True)
        _,av,ae=next(v for v in views(abase) if v[0]==view)
        _,bv,be=next(v for v in views(bbase) if v[0]==view)
        self.lines+=['do','local abase='+array(abase),'local bbase='+array(bbase),
                     'local base=abase','local a='+ae,'base=bbase','local b='+be]
        axisa,axisb,axisc=axes
        label=f'cross/{dtype(av.dtype)}{av.shape}/{dtype(bv.dtype)}{bv.shape}/{axes}/{view}/linalg{linalg}/raw{raw}/general{general}'
        try:
            with warnings.catch_warnings(),np.errstate(all='ignore'):
                warnings.simplefilter('ignore')
                result=np.linalg.cross(av,bv,axis=axisa) if linalg else np.cross(av.tolist() if raw else av,bv,axisa=axisa,axisb=axisb,axisc=axisc)
            ok=True
        except (TypeError,ValueError,OverflowError,IndexError):ok=False
        call='np.linalg.cross(a,b,'+str(lua_axis(axisa))+')' if linalg else 'np.cross('+('a:tolist()' if raw else 'a')+',b,{axisa='+str(lua_axis(axisa))+',axisb='+str(lua_axis(axisb))+',axisc='+str(lua_axis(axisc))+'})'
        self.lines+=['local ok,result=pcall(function()return '+call+'end)',
                     'assert(ok=='+lua(ok)+','+lua(label+': acceptance')+'..": "..tostring(result))']
        if ok:
            # General complex products may choose a different baseline/SIMD
            # FMA path. Budget is fixed before running native comparisons.
            tol=6e-7 if general and result.dtype==np.dtype('complex64') else 2e-15 if general and result.dtype.kind=='c' else 0
            self.lines+=['active_dtype='+lua(dtype(result.dtype))]
            self.check('result',result,label+': result',tol)
            self.lines+=['active_dtype=nil']
            for name,other in [('a',av),('b',bv)]:self.lines+=['eq(np.shares_memory(result,'+name+'),'+lua(np.shares_memory(result,other))+','+lua(label+': shares '+name)+')']
        self.check('a',av,label+': input a');self.check('b',bv,label+': input b')
        self.lines+=['cases=cases+1','end']
    def write(self):
        self.lines+=['end','chunk()','end',f'assert(cases=={self.count})',
                     'print("'+self.name+': "..cases.." cases; "..checks.." checks; max_error="..max_error.." max_relative_error="..max_relative_error)']
        self.lines+=['for _,dt in ipairs({"complex64","complex128","clongdouble"})do local e=errors[dt]or{absolute=0,scaled=0};print(dt..": max_absolute_error="..e.absolute.." max_scaled_error="..e.scaled)end']
        from pathlib import Path
        (Path(__file__).resolve().parents[1]/'tests'/f'{self.name}_differential_generated.lua').write_text('\n'.join(self.lines)+'\n');print(self.name,self.count)
def values(shape,dt):
    a=np.arange(int(np.prod(shape))).reshape(shape)%7
    if np.dtype(dt).kind in 'fc':a=(a-2)/4
    if np.dtype(dt).kind=='c':a=a+1j*(a+1)/2
    return a.astype(dt)
def main():
    s=Cross('cross116')
    dtypes=['bool','int8','uint8','int16','int64','uint64','float16','float32','float64','longdouble','complex64','complex128','clongdouble','S3','U3','datetime64[ms]','timedelta64[h]']
    for ad in dtypes:
        for bd in dtypes:
            for axes in [(-1,-1,-1),(-1,-1,0),(0,0,-1),(0,0,0)]:s.case(values((3,3),ad),values((3,3),bd),axes)
        for shape in [(3,),(2,3),(3,2),(2,1,3),(1,2,3),(2,3,4),(0,3),(2,0,3),(),(2,)]:
            a=values(shape,ad)
            for view,_,_ in views(a):
                for axes in [(-1,-1,-1),(-1,-1,0),(0,0,0)]:s.case(a,a,axes,view,linalg=axes[0]==axes[1]==axes[2])
        if np.dtype(ad).kind in 'iufc':s.case(values((3,),ad),values((3,),ad),raw=True)
    for dt in ['int8','float16','float32','float64','complex64','clongdouble']:
        for ash,bsh,aa,bb in [((3,),(2,3),-1,-1),((2,1,3),(1,4,3),-1,-1),
                              ((2,3),(3,3),-1,-1),((3,2,1),(3,1,4),0,0),
                              ((0,3),(1,3),-1,-1)]:
            for cc in [-1,0]:s.case(values(ash,dt),values(bsh,dt),(aa,bb,cc))
    rng=np.random.default_rng(116)
    for dt in ['complex64','complex128','clongdouble']:
        for shape in [(3,),(2,3),(3,3),(2,1,3)]:
            for j in range(8):
                a=(rng.normal(size=shape)+1j*rng.normal(size=shape)).astype(dt)
                b=(rng.normal(size=shape)+1j*rng.normal(size=shape)).astype(dt)
                for axisc in [-1,0]:s.case(a,b,(-1,-1,axisc),general=True)
    for dt in ['float16','float32','float64','complex64','complex128']:
        for x in [0.,-0.,np.inf,-np.inf,np.nan]:s.case(np.array([x,1.,-0.],dt),np.array([1.,x,0.],dt))
    s.write()
if __name__=='__main__':main()
