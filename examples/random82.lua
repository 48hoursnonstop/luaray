local np=require('luaray_core')
local rng=np.random.default_rng(2026)
local w=rng:wald({{1},{2}},{{.5,2,4}})
local p=np.flip(np.array({.05,.5,.9},'float32'),1)
local l=rng:logseries(p,{2,3})
assert(w.dtype=='float64' and w.shape[1]==2 and w.shape[2]==3)
assert(l.dtype=='int64' and l.shape[1]==2 and l.shape[2]==3)
print('wald',w:tolist()[1][1],w:tolist()[2][3])
print('logseries',l:tolist()[1][1],l:tolist()[2][3])
print('PCG64 tail',rng:raw_hex())
