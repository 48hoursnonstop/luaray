local np=require('luaray_core')
local rng=np.random.default_rng(42)
local locations=np.array({{0.0},{10.0}},'float64')
local scales=np.array({{1.0,2.0,3.0}},'float64')
local draws=rng:normal(locations,scales)
assert(draws.dtype=='float64')
assert(draws.shape[1]==2 and draws.shape[2]==3)
print('normal, two batch locations x three scales:')
for _,row in ipairs(draws:tolist()) do print(table.concat(row,', ')) end
local uniforms=rng:uniform({0,10,20},{1,12,25},{2,3})
print('uniform shape:',table.concat(uniforms.shape,','))
local scales_view=np.flip(np.array({0.5,1.0,2.0},'float64'),1)
local durations=rng:exponential(scales_view,{2,3})
print('exponential with negative strides:',table.concat(durations:tolist()[1],', '))
