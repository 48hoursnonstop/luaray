local np=require('luaray_core')
local rng=np.random.default_rng(1234)
local n=np.array({{10},{20},{50}},'int64')
local p=np.array({{.15,.5,.85}})
local b=rng:binomial(n,p)
local nb=rng:negative_binomial({{.5},{2.5}},{{.1,.5,.95}})
print('binomial broadcast shape:',b.shape[1],b.shape[2], 'dtype:',b.dtype)
print('negative_binomial broadcast shape:',nb.shape[1],nb.shape[2], 'dtype:',nb.dtype)
