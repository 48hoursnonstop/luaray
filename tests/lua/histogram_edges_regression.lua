local lr=require('luaray')
local data=lr.array({1,2,3,4,8,10})
local fixed=lr.histogram_bin_edges(data,{bins=3})
assert(fixed.dtype=='float64' and fixed[1]==1 and fixed[4]==10)
assert(fixed[2]==4 and fixed[3]==7)
for name,n in pairs({sqrt=4,sturges=5,rice=5,scott=3,fd=3,doane=6,auto=5,stone=2}) do
  local edges=lr.histogram_bin_edges(data,{bins=name})
  assert(edges.size==n and edges[1]==1 and edges[n]==10)
end
local edges=lr.array({0,1,1,5},'float32')
assert(rawequal(lr.histogram_bin_edges(data,{bins=edges}),edges))
local empty=lr.histogram_bin_edges({}, {bins='auto'})
assert(empty.size==2 and empty[1]==0 and empty[2]==1)
local constant=lr.histogram_bin_edges({3,3,3},{bins=2})
assert(constant[1]==2.5 and constant[3]==3.5)
assert(not pcall(lr.histogram_bin_edges,data,{bins={0,2,1}}))
assert(not pcall(lr.histogram_bin_edges,data,{bins=0}))
assert(not pcall(lr.histogram_bin_edges,data,{range={1,math.huge}}))
assert(not pcall(lr.histogram_bin_edges,{1,0/0}))
assert(not pcall(lr.histogram_bin_edges,data,{bins='auto',weights=lr.ones(data.shape)}))
print('Histogram edges regression passed')
