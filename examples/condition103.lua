local np=require('luaray')
local a=np.array({{0,2,0},{3,0,4}},'int32')
local coordinates=a:nonzero()
assert(coordinates[1]:get(1)==1 and coordinates[2]:get(1)==2)
assert(coordinates[1].strides[1]==16)
assert(np.flatnonzero(a):get(3)==6)
local selected=np.extract({{false,true,false},{true,false,true}},a)
assert(selected:get(1)==2 and selected:get(3)==4)
local columns=a:compress({true,false,true},{axis=2})
assert(columns:get(2,1)==3 and columns:get(2,2)==4)
print('LuaRay native condition selection example: passed')
