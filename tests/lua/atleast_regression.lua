local np=require('luaray_core')
assert(np._version=='0.121.0-dev')
local function equal(x,y)assert(x==y,tostring(x)..' ~= '..tostring(y))end
local empty=np.atleast_1d()
equal(#empty,0)
local scalar=np.array(12,'int32')
local one=np.atleast_1d(scalar)
local two=np.atleast_2d(scalar)
local three=np.atleast_3d(scalar)
equal(one.shape[1],1); equal(two.shape[1],1); equal(two.shape[2],1)
equal(three.shape[1],1); equal(three.shape[3],1)
one[1]=33; equal(scalar:tolist(),33)
local x=np.array({1,2,3,4},'int16')
local row=np.atleast_2d(x)
equal(row.shape[1],1);equal(row.shape[2],4)
equal(row.strides[1],0);equal(row.strides[2],2)
row:set(66,1,3);equal(x[3],66)
local cube=np.atleast_3d(x)
equal(cube.shape[1],1);equal(cube.shape[2],4);equal(cube.shape[3],1)
equal(cube.strides[1],0);equal(cube.strides[2],2);equal(cube.strides[3],0)
local mat=np.reshape(np.arange(6,'float64'),{2,3})
local plane=np.atleast_3d(mat)
equal(plane.shape[1],2);equal(plane.shape[2],3);equal(plane.shape[3],1)
equal(plane.strides[1],24);equal(plane.strides[2],8);equal(plane.strides[3],0)
plane:set(-8,2,3,1);equal(mat:get(2,3),-8)
local flipped=np.flip(np.array({1,2,3},'int64'))
local negative=np.atleast_2d(flipped)
equal(negative.strides[2],-8)
negative:set(100,1,1);equal(flipped[1],100)
local many=np.atleast_3d({4,5},6,np.array({'東','西'},'U1'))
equal(#many,3);equal(many[1].ndim,3);equal(many[2].ndim,3);equal(many[3].dtype,'<U1')
local orphan
local function created()
 local parent=np.array({'A','ß','東'},'U1')
 return np.atleast_3d(parent)
end
orphan=created();collectgarbage('collect');collectgarbage('collect')
equal(orphan:get(1,3,1),'東')
local readonly=np.broadcast_to(np.array({1,2,3},'int32'),{2,3})
local roview=np.atleast_3d(readonly)
assert(not pcall(function()roview:set(77,1,1,1)end),'atleast should retain readonly flag')
assert(not pcall(function()np.atleast_2d(nil)end))
